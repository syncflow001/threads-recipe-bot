// 판마다 여러 편을 받아 한 편만 올린다 — 8월 실측으로 493편 받아 66편 올렸다.
// 나머지는 아무도 안 읽는 짐이 되어 열하루에 1.4GB 가 쌓였다.
//
// ⚠️ 처음에는 **그날 마지막 판에만** 치웠는데(사용자 제안) 검수에서 셋이 드러났다 (2026-08-31).
//   ① 「지금 시(hour)」로 마지막 판을 가렸다 — 판이 시간대를 넘기면 그날 정리가 통째로 빠진다.
//      `sample_table` 은 마지막 판이 23:54 라 여유가 **6분**뿐이고, 넘기면 자정까지 겹쳐 하루를 잃는다
//   ② 마지막 판이 안 뜨면(멈춤·GAP_MIN) 그날 정리가 조용히 사라진다
//   ③ 두 시간이라는 마법 숫자가 계정별 판 간격과 어긋날 수 있었다
// **판마다 치우면 셋이 한꺼번에 없어진다.** 치우는 값이 싸서 아낄 까닭이 없었다.
//
// 잣대는 **이 판이 시작한 시각**이다 — 그보다 먼저 받은 것은 이 판이 안 쓴 것이 확실하다.
// ⚠️ 보관함에 쟁여 둔 글의 재료는 안 지운다 — 다음 판이 그것부터 꺼내 쓴다.
// ⚠️ 치우다 무슨 일이 나도 **발행 결과를 뒤엎지 않는다.** 발행은 이미 끝났다
try {
  const { 치우기, 사람크기 } = await import('./도구/미디어치우기.mjs')
  const r = await 치우기({
    뿌리: process.cwd(), 계정들: [프로필],
    날수: (Date.now() - 판시작) / 86400000,
    실행: true, 기록: () => {},
  })
  if (r.지운수) console.error(`\n안 쓴 재료 ${r.지운수}개를 치웠습니다 (${사람크기(r.크기)}).`)
} catch (오류) {
  console.error(`\n재료 치우기를 건너뜁니다 — ${오류.message}`)
}

