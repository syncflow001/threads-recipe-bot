// 계정 쿠키가 「답글까지 읽는 눈」인지 잰다 — 조회수만 읽히는 반쯤 죽은 쿠키를 가려낸다

// ⚠️ **왜 있나 (2026-09-05 실측).** 열세 계정 가운데 아홉이 하루에 5편씩 올리다 1~3편으로 떨어졌다.
// 로그는 판마다 「걷은 글 47개 중 47개가 레시피 없음 — 쓸 만한 글이 없었습니다 (고장이 아닙니다)」였다.
// 고장이 맞았다. 레시피는 본문이 아니라 **작성자가 자기 글에 단 답글**에 있는데,
// 그 답글이 안 읽히니 걷어 온 글이 통째로 걸러진 것이다.
//
// 같은 글을 두 계정의 눈으로 읽어 갈랐다 ([[못-읽는-것과-없는-것을-가르려면-남의-눈으로-같은-것을-봐라]]) —
//     sample_momo 의 눈  → 답글 2 · 1 · 1편
//     sample_salim 의 눈 → 답글 0 · 0 · 0편   (같은 글이다)
// 문서 자체가 다르게 온다. 멀쩡한 눈은 `caption` 3개 · `like_count` 9개가 실려 오고,
// 못 읽는 눈은 `caption` 1개 · `like_count` 3개 — **본글만 오고 답글이 안 온다.**
// 로그인 화면도 안 뜨고 조회수는 멀쩡히 읽힌다. 그래서 아무 감시도 안 울렸다.
//
// ⚠️ **이미 있던 물러서기(src/읽기쿠키.mjs)가 이것을 못 잡는다.** 그쪽 `읽혔나()` 는
// 「조회수 **또는** 글타래」 가운데 하나라도 있으면 읽힌 것으로 본다. 반쯤 죽은 눈은
// 조회수를 내주므로 그 문을 그냥 지난다. 여기서는 **글타래만** 본다.
//
// ⚠️ **기준글을 코드에 박지 않는다.** 박아 두면 그 글이 지워지는 날 도구가 통째로 거짓말을 한다
// ([[검사에-날짜를-박으면-달이-바뀔-때-깨진다]]). 우리 계정이 오늘 올린 글을 그때그때 가져다 쓰고,
// **한 눈이라도 답글을 본 글**만 기준으로 삼는다 — 답글이 원래 없는 글로 재면 다 빨간불이 된다.

import './그물.mjs'   // IPv6 헛디딤 막기 (부수 효과) — 아래 fetch 가 그것에 걸린다
import { 상세 as 상세원본 } from './threads.mjs'
import { 계정열쇠읽기 } from './감시모음.mjs'
import { 계정목록, 정보 as 계정정보, 정보쓰기 } from './계정.mjs'

// 기준글을 몇 편으로 재나. 한 편으로 재면 안 된다 — 그 한 편에 답글이 없으면 멀쩡한 눈도 빨갛다
export const 기준글수 = 3

// 우리가 올린 글의 주소를 가져온다. 우리 글에는 레시피 답글이 달려 있어 기준글로 알맞다
export async function 내글주소들(계정, { 뿌리 = process.cwd(), 열쇠읽기 = 계정열쇠읽기, 부르기 = fetch, 몇편 = 4 } = {}) {
  const [토큰, 아이디] = await Promise.all([
    열쇠읽기(계정, 'THREADS_ACCESS_TOKEN', 뿌리),
    열쇠읽기(계정, 'THREADS_USER_ID', 뿌리),
  ])
  if (!토큰 || !아이디) return []
  try {
    const 답 = await 부르기(`https://graph.threads.net/v1.0/${아이디}/threads`
      + `?fields=permalink&limit=${몇편}&access_token=${토큰}`)
    const 것 = await 답.json()
    return (것?.data ?? [])
      .map((p) => String(p?.permalink ?? '').match(/@([^/]+)\/post\/([^/?#]+)/))
      .filter(Boolean)
      .map((m) => ({ 작성자: m[1], code: m[2] }))
  } catch { return [] }
}

// 이 눈으로 이 글들을 읽어 본다. **글타래(답글)를 봤는지**가 핵심이다
export async function 눈재기(쿠키, 기준글들, { 상세 = 상세원본 } = {}) {
  let 조회수본것 = 0
  let 글타래본것 = 0
  const 낱개 = []
  for (const 글 of 기준글들) {
    try {
      const 것 = await 상세(글.작성자, 글.code, { cookie: 쿠키 })
      const 타래 = 것.글타래?.length ?? 0
      if (typeof 것.조회수 === 'number') 조회수본것 += 1
      if (타래 > 0) 글타래본것 += 1
      낱개.push({ ...글, 조회수: 것.조회수 ?? null, 글타래: 타래 })
    } catch (e) {
      낱개.push({ ...글, 안됨: e.message })
    }
  }
  return { 조회수본것, 글타래본것, 낱개 }
}

// 무엇이라 부를까. 「반쯤」을 따로 부르는 것이 이 도구의 전부다 —
// 로그인 끊김과 뭉뚱그리면 또 「쿠키가 죽었다」 한마디로 끝나고 셋을 다 헛짚는다
// ([[한-계정이-안-돌면-문마다-따로-재라]])
export function 판정({ 조회수본것, 글타래본것 }, 기준글개수) {
  if (!기준글개수) return { 갈래: '못잼', 말: '기준글을 못 구했습니다' }
  if (글타래본것 > 0) return { 갈래: '멀쩡', 말: '답글까지 읽습니다' }
  if (조회수본것 > 0) return { 갈래: '반쯤', 말: '조회수는 읽는데 **답글을 못 읽습니다** — 레시피를 못 찾습니다' }
  return { 갈래: '끊김', 말: '로그인이 끊겼습니다 — 아무것도 못 읽습니다' }
}

// 한 판. 계정마다 쿠키를 꺼내 같은 기준글을 읽힌다.
// ⚠️ 기준글은 **한 눈이라도 답글을 본 글**만 남긴다. 그러지 않으면 답글이 원래 없는 글이
// 섞여 멀쩡한 눈까지 빨갛게 물든다
export async function 한판({
  뿌리 = process.cwd(), 계정들 = null, 열쇠읽기 = 계정열쇠읽기, 목록 = 계정목록,
  상세 = 상세원본, 주소들 = 내글주소들, 알림 = () => {},
  // 몇 편으로 잴까. 상세 문서 한 장이 800KB 라 헬스체크처럼 자주 도는 자리는 줄여 부른다
  잴글수 = 기준글수 * 2,
} = {}) {
  const 이름들 = 계정들 ?? await 목록(뿌리)

  // ① 기준글 후보를 모은다.
  // ⚠️ **한 계정이 후보를 독차지하면 안 된다** (2026-09-06 실측).
  //    앞 계정에서 잴글수를 다 채우고 끊었더니, 「이 두 계정만 재 달라」고 했을 때
  //    **막힌 그 두 계정의 글만** 후보가 됐다. 그 계정들은 답글이 안 달린 글이 많아
  //    아무 눈도 답글을 못 봤고, 도구는 「잣대로 쓸 글을 못 구했습니다」로 끝났다.
  //    계정마다 조금씩 걷어 여러 계정에 퍼지게 한다
  const 계정당 = 2
  const 후보 = []
  for (const 계정 of 이름들) {
    if (후보.length >= 잴글수) break
    const 것들 = await 주소들(계정, { 뿌리, 열쇠읽기 })
    for (const 글 of 것들.slice(0, 계정당)) {
      if (!후보.some((v) => v.code === 글.code)) 후보.push(글)
    }
  }
  알림(`기준글 후보 ${후보.length}편을 모았습니다`)

  // ② 계정마다 후보를 읽힌다
  const 잰것 = []
  for (const 계정 of 이름들) {
    const 쿠키 = await 열쇠읽기(계정, 'THREADS_COOKIE', 뿌리)
    if (!쿠키) { 잰것.push({ 계정, 쿠키없음: true }); 알림(`${계정} — 쿠키가 없습니다`); continue }
    const 잰값 = await 눈재기(쿠키, 후보.slice(0, 잴글수), { 상세 })
    잰것.push({ 계정, ...잰값 })
    알림(`${계정} — 조회수 ${잰값.조회수본것} · 답글 ${잰값.글타래본것}`)
  }

  // ③ **한 눈이라도 답글을 본 글**만 기준글로 남기고 다시 센다
  const 쓸글 = 후보.filter((글) => 잰것.some(
    (r) => (r.낱개 ?? []).some((v) => v.code === 글.code && v.글타래 > 0)))

  return {
    기준글: 쓸글,
    결과: 잰것.map((r) => {
      if (r.쿠키없음) return { 계정: r.계정, 갈래: '없음', 말: '쿠키가 아직 없습니다', 조회수본것: 0, 글타래본것: 0 }
      const 고른것 = (r.낱개 ?? []).filter((v) => 쓸글.some((g) => g.code === v.code))
      const 셈 = {
        조회수본것: 고른것.filter((v) => typeof v.조회수 === 'number').length,
        글타래본것: 고른것.filter((v) => (v.글타래 ?? 0) > 0).length,
      }
      return { 계정: r.계정, ...셈, ...판정(셈, 쓸글.length) }
    }),
  }
}

