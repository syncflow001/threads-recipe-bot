// (`src/읽기쿠키.mjs` 가 짐작했던 것을 이 실험이 확인했다.)
//
// 그래서 표시를 남긴다. 표시가 있으면 헬스체크가 그 계정을 안 부른다 —
// 3시간마다 고칠 수 없는 일로 부르면 곧 아무도 안 보는 신호가 된다
// ([[늘-빨간불인-신호는-신호가-아니다]]). 읽기는 남의 로그인을 빌려 이어 간다(읽기쿠키.mjs).
//
// **표시는 사람이 도구를 돌릴 때만 손댄다.** 예약이 도는 자리(헬스체크)에서는 읽기만 한다 —
// 계정정보.json 을 자동으로 쓰다가 통째로 날린 적이 있다 ([[검사가-실서버-장부를-쓰면-안-된다]])
export const 막힘칸 = '상세막힘'

export async function 막혔다표시(계정, { 뿌리 = process.cwd(), 오늘 = new Date() } = {}) {
  await 정보쓰기(계정, { [막힘칸]: String(오늘.toISOString()).slice(0, 10) }, 뿌리)
}

// 다시 읽히면 지운다. 스레드가 풀어 줄 수 있고, 그때까지 표시를 남겨 두면 진짜 고장을 가린다
export async function 막힘풀기(계정, { 뿌리 = process.cwd() } = {}) {
  const 그것 = await 계정정보(계정, 뿌리)
  if (!그것?.[막힘칸]) return false
  await 정보쓰기(계정, { [막힘칸]: null }, 뿌리)
  return true
}

export async function 막힌계정들(뿌리 = process.cwd(), 목록 = 계정목록) {
  const 것들 = await Promise.all((await 목록(뿌리)).map(async (계정) => [계정, (await 계정정보(계정, 뿌리))?.[막힘칸]]))
  return Object.fromEntries(것들.filter(([, v]) => v))
}
