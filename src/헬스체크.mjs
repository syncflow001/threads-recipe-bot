// ⚠️ **왜 만들었나 (2026-08-26, 사용자가 시켰다).**
// 「전체 알고리즘과 시스템과 자동화에 문제가 발생하면 절대 안 된다」 —
// 같은 날 두 사고가 났고 **둘 다 눈으로는 안 보이는 것**이었다.
//   · `sample_dinner` 로 누른 답글이 `example.cook` 로 나갔다 (§7-17)
//   · 계정 셋의 쿠키가 110자쯤 잘린 채 몇 달을 돌았다 (§7-18) — 잘려도 로그인은 됐다
// 사람이 화면을 봐서는 절대 못 잡는다. **재는 것만이 잡는다.** 그래서 3시간마다 잰다.
//
// 여기서 재는 것은 **열쇠와 계정의 무결성**뿐이다.
// 「발행이 멈췄나·보관함이 비었나」는 이미 `감시.sh`(아침·주간)가 본다. 겹치지 않는다.

import { readFile, readdir } from 'node:fs/promises'
import { spawnSync } from 'node:child_process'
import { join } from 'node:path'
import { 자식환경 } from './열쇠파일.mjs'
import { 계정열쇠읽기 } from './감시모음.mjs'
import { 쿠키주인 } from './계정벽.mjs'
import { 토큰주인 } from './publish.mjs'
import { 보일아이디, 첫계정있나, 계정길, 계정목록 as 계정목록읽기 } from './계정.mjs'
import { 목록 as 블롭목록 } from './blob.mjs'
import { 한판 as 눈한판, 막힌계정들 as 막힌계정들읽기 } from './눈점검.mjs'

// 빌려 쓰는 저장 자리(Vercel Blob)의 한도와, 몇 %에서 부를까.
// ⚠️ **왜 재나 (2026-09-06).** 19일에 걸쳐 서서히 차다가 하루에 열 판이 죽었는데
// 그동안 헬스체크는 탈 0건이었다 — 쿠키·토큰은 우리 것이라 물었고 남의 그릇은 안 물었다
// ([[초록불-둘이-켜져-있어도-저장-자리는-아무도-안-봤다]]). 서서히 차는 것은 미리 안 부르면 못 막는다
export const 블롭한도 = 1e9      // Hobby 판 1GB
export const 블롭문턱 = 0.6      // 60% 를 넘으면 부른다. 하루치가 100MB쯤이라 이틀 여유가 남는다

// 계정마다 반드시 제 것이어야 하는 열쇠. 공유 열쇠(쿠팡·블롭·텔레그램)는 안 본다
export const 계정열쇠 = ['THREADS_COOKIE', 'THREADS_ACCESS_TOKEN', 'THREADS_USER_ID']

export const 열쇠파일길 = (계정, 뿌리) => join(뿌리, 계정 ? 계정길(계정, '열쇠.env') : '.env.local')

// 파일에 적힌 값. `--env-file` 이 읽는 것과 견주려고 우리 손으로도 읽는다
export function 파일속값(글, 키) {
  const 줄 = String(글 ?? '').split('\n').find((l) => l.startsWith(`${키}=`))
  if (!줄) return null
  return 줄.slice(키.length + 1).trim().replace(/^(["'])([\s\S]*)\1$/, '$2')
}

// ⚠️ **node 에게 실제로 읽혀 본다.** 표기만 보고 「괜찮겠지」 하면 또 놓친다 —
// 쿠키가 잘린 것을 몇 달 몰랐던 까닭이 그것이다
export function 자식이받는길이(파일들, 뿌리, 돌리기 = spawnSync) {
  const 잰이 = join(뿌리, '.헬스체크-잰이.mjs')
  const r = 돌리기(process.execPath, [
    ...파일들.map((f) => `--env-file=${f}`), '-e',
    `console.log(JSON.stringify(Object.fromEntries(${JSON.stringify(계정열쇠)}`
    + '.map((k) => [k, (process.env[k] ?? "").length]))))',
  ], { cwd: 뿌리, env: 자식환경({ PATH: process.env.PATH }, 파일들.map((f) => join(뿌리, f))), encoding: 'utf8' })
  void 잰이
  try { return JSON.parse(String(r.stdout ?? '{}')) } catch { return {} }
}

// 목록을 뽑는 규칙은 src/계정.mjs 하나뿐이다 — 여기서 다시 적지 않는다 (2026-08-29)
export const 계정목록 = (뿌리) => 계정목록읽기(뿌리)

// 한 판. 네트워크(쿠키·토큰 주인 확인)는 `쿠키확인` 을 꺼서 뺄 수 있다 — 검사가 그렇게 쓴다
export async function 한판({
  뿌리 = process.cwd(), 계정정보 = null, 쿠키확인 = true,
  주인묻기 = 쿠키주인, 토큰묻기 = 토큰주인, 돌리기 = spawnSync,
  // 아래 둘은 검사가 갈아 끼운다 — 진짜 CLI 와 스레드를 부르면 검사가 느리고 흔들린다
  블롭재기 = 블롭목록, 눈재기 = 눈한판, 막힌계정들기 = 막힌계정들읽기,
} = {}) {
  let 찬만큼 = null
  let 눈결과 = null
  let 막힌것 = {}
  const 계정들 = await 계정목록(뿌리)
  const 정보 = 계정정보 ?? await readFile(join(뿌리, '계정정보.json'), 'utf8')
    .then(JSON.parse).catch(() => ({}))
  const 탈 = []
  const 잰것 = []
  const 지문표 = new Map()   // 값 → 그 값을 가진 계정들. 섞였는지 본다

  for (const 계정 of 계정들) {
    const 이름 = 계정 || '(첫 계정)'
    const 파일 = 열쇠파일길(계정, 뿌리)
    const 글 = await readFile(파일, 'utf8').catch(() => null)
    if (글 === null) { 탈.push(`${이름} — 열쇠 파일이 없습니다 (${파일})`); continue }

    // ① 자식이 실제로 받는 길이가 파일과 같은가 (잘림)
    const 파일들 = [...(계정 ? ['.env.local'] : []), 계정 ? 계정길(계정, '열쇠.env') : '.env.local']
    const 받는길이 = 자식이받는길이(파일들, 뿌리, 돌리기)
    for (const 키 of 계정열쇠) {
      const 값 = 파일속값(글, 키)
      if (!값) { 탈.push(`${이름} — ${키} 가 없습니다`); continue }
      if (받는길이[키] !== 값.length) {
        탈.push(`${이름} — ${키} 가 **잘려서** 들어갑니다 (파일 ${값.length}자 → 실제 ${받는길이[키] ?? 0}자)`)
      }
      // ② 다른 계정과 같은 값을 쓰고 있나 (섞임)
      const 자리 = `${키} ${값}`
      지문표.set(자리, [...(지문표.get(자리) ?? []), 이름])
    }

    // ③ 우리가 파일을 직접 읽는 길도 같은 값을 주는가 (따옴표를 안 벗기면 여기서 어긋난다)
    for (const 키 of 계정열쇠) {
      const 파일값 = 파일속값(글, 키)
      const 읽은값 = await 계정열쇠읽기(계정, 키, 뿌리)
      if (파일값 && 읽은값 !== 파일값) {
        탈.push(`${이름} — ${키} 를 우리가 읽으면 파일과 다릅니다 (따옴표를 안 벗겼을 수 있습니다)`)
      }
    }
    잰것.push(이름)
  }

  // 같은 열쇠를 두 계정이 함께 쓰면 그 자체가 사고다
  for (const [자리, 주인들] of 지문표) {
    if (주인들.length > 1) 탈.push(`${자리.split(' ')[0]} 을(를) ${주인들.join(' · ')} 가 **함께** 쓰고 있습니다`)
  }

  // ④ 쿠키의 주인이 정말 그 계정인가 — 스레드에게 직접 묻는다
  if (쿠키확인) {
    for (const 계정 of 계정들) {
      const 이름 = 계정 || '(첫 계정)'
      const 쿠키 = await 계정열쇠읽기(계정, 'THREADS_COOKIE', 뿌리)
      if (!쿠키) continue
      const 기대 = 보일아이디(계정, 정보[계정])
      const 진짜 = await 주인묻기(쿠키)
      if (!진짜) { 탈.push(`${이름} — 쿠키 주인을 확인하지 못했습니다 (쿠키가 죽었을 수 있습니다)`); continue }
      if (기대 && 진짜 !== 기대) 탈.push(`${이름} — 쿠키가 **@${진짜}** 것입니다 (기대: @${기대})`)
    }
  }

  // ⑤ **토큰도 스레드에게 직접 묻는다** (2026-09-04 에 붙였다).
  //
  // ⚠️ **왜 붙였나.** 전에는 쿠키만 물었다 — 토큰은 파일에 값이 있는지만 봤다.
  // `sample_noon` 이 세 판을 내리 실패했는데 헬스체크는 「쿠키 주인을 확인하지 못했습니다」
  // 한 줄만 냈다. 토큰은 아예 죽어 있었고(계정 자체가 스레드에 없었다) 그 사실을 아무도 몰랐다.
  // **본문을 올리는 것은 토큰이다.** 쿠키가 멀쩡해도 토큰이 죽으면 한 편도 못 올린다.
  //
  // 스레드가 준 까닭을 그대로 싣는다 — 「죽었다」만으로는 다시 넣어야 할지, 계정이 없는지 모른다
  if (쿠키확인) {
    for (const 계정 of 계정들) {
      const 이름 = 계정 || '(첫 계정)'
      const 토큰 = await 계정열쇠읽기(계정, 'THREADS_ACCESS_TOKEN', 뿌리)
      if (!토큰) continue // ①에서 이미 「없습니다」로 잡았다
      const { 번호, 아이디, 까닭 } = await 토큰묻기(토큰)
      if (!아이디) {
        탈.push(`${이름} — 토큰이 죽었습니다${까닭 ? ` (스레드: ${까닭})` : ''}`)
        continue
      }
      const 기대 = 보일아이디(계정, 정보[계정])
      if (기대 && 아이디 !== 기대) 탈.push(`${이름} — 토큰이 **@${아이디}** 것입니다 (기대: @${기대})`)
      // 적어 둔 번호가 실제와 다르면 인사이트·성적이 남의 것을 묻는다
      const 적힌번호 = await 계정열쇠읽기(계정, 'THREADS_USER_ID', 뿌리)
      if (번호 && 적힌번호 && 번호 !== 적힌번호) {
        탈.push(`${이름} — THREADS_USER_ID 가 실제와 다릅니다 (적힌 것 ${적힌번호} · 실제 ${번호})`)
      }
    }
  }

  // ⑥ **빌려 쓰는 저장 자리가 차 가나** (2026-09-06 에 붙였다).
  //
  // 메타가 자기 CDN 영상을 안 받아서 우리가 블롭에 올려 그 주소로 발행한다.
  // 그것이 꽉 차면 **영상 있는 글이 한 편도 못 나간다** — 실제로 다섯 계정 열 판이 그렇게 죽었다.
  // 계정마다 묻지 않는다. 저장 자리는 이 맥 전체가 하나를 같이 쓴다
  if (쿠키확인) {
    try {
      const 것들 = await 블롭재기()
      const 쓴것 = 것들.reduce((a, b) => a + (b.크기 ?? 0), 0)
      찬만큼 = 쓴것 / 블롭한도
      if (찬만큼 >= 블롭문턱) {
        탈.push(`영상 저장 자리가 ${(100 * 찬만큼).toFixed(0)}% 찼습니다 `
          + `(${(쓴것 / 1e6).toFixed(0)}MB / ${블롭한도 / 1e6}MB · 조각 ${것들.length}개). `
          + '꽉 차면 영상 있는 글이 한 편도 못 나갑니다 — '
          + '`node --env-file=.env.local 도구/블롭치우기.mjs --치운다` 로 치우세요')
      }
    } catch (e) {
      // 못 재는 것과 찬 것은 다르다. 못 쟀다고 발행이 죽지는 않으니 낮은 소리로 남긴다
      탈.push(`영상 저장 자리를 재지 못했습니다 — ${String(e.message).slice(0, 120)}`)
    }
  }

  // ⑦ **남의 글의 답글을 읽을 수 있나** (2026-09-06 에 붙였다).
  //
  // 레시피는 본문이 아니라 작성자가 자기 글에 단 답글에 있다. 그것이 안 읽히면
  // 걷어 온 글이 전부 「레시피 없음」으로 걸려 판마다 0편이 된다 —
  // 로그는 「고장이 아닙니다」라고 말하고 쿠키 주인 확인(④)은 멀쩡히 통과한다.
  // 2026-09-05 에 아홉 계정이 하루 5편에서 1~3편으로 떨어진 자리다
  if (쿠키확인) {
    try {
      const { 기준글, 결과 } = await 눈재기({ 뿌리, 계정들, 잴글수: 3 })
      눈결과 = 결과
      // ⚠️ **다시 로그인해도 안 고쳐지는 계정은 안 부른다** (2026-09-06).
      //    스레드가 그 계정에만 글 상세 화면을 안 내준다. 사람이 새로 로그인해 봤고 그대로였다.
      //    읽기는 남의 로그인을 빌려 이어 간다(src/읽기쿠키.mjs) — 고칠 수 없는 일로
      //    3시간마다 부르면 곧 아무도 안 보는 신호가 된다.
      //    표시는 **읽기만 한다.** 예약이 도는 자리에서 계정정보.json 을 쓰지 않는다
      막힌것 = await 막힌계정들기(뿌리).catch(() => ({}))
      if (기준글.length) {
        for (const r of 결과) {
          if (r.갈래 === '멀쩡' || r.갈래 === '없음') continue // 「없음」은 ①이 이미 잡았다
          if (막힌것[r.계정]) continue // 이미 알고 있는 막힘이다 (계정정보의 상세막힘 칸)
          // ⚠️ **고치는 길을 함께 적는다.** 이 탈은 사람이 크롬에서 로그인해야 풀리는데,
          //    3시간마다 같은 말만 오면 곧 무시하는 신호가 된다 ([[늘-빨간불인-신호는-신호가-아니다]])
          탈.push(`${r.계정} — ${r.말} (기준글 ${기준글.length}편 가운데 답글 ${r.글타래본것}편). `
            + `\`node 도구/쿠키받기.mjs ${r.계정}\` 로 고칩니다`)
        }
      }
    } catch (e) {
      탈.push(`답글을 읽을 수 있는지 재지 못했습니다 — ${String(e.message).slice(0, 120)}`)
    }
  }

  return {
    때: new Date().toISOString(), 계정수: 잰것.length, 잰것, 탈,
    블롭찬만큼: 찬만큼, 눈: 눈결과, 알고있는막힘: Object.keys(막힌것),
  }
}

// 사람이 읽는 글월. 이상이 없으면 null (조용히 지나간다)
export function 글월(결과) {
  if (!결과?.탈?.length) return null
  return [
    '🚨 헬스체크 — 계정 열쇠에 문제가 있습니다',
    `잰 때 ${new Date(결과.때).toLocaleString('ko-KR')} · 계정 ${결과.계정수}개`,
    '',
    ...결과.탈.map((t) => `• ${t}`),
    '',
    '대시보드 「감시」 쪽에서 다시 재 볼 수 있습니다.',
  ].join('\n')
}
