// 조회수 알리미 한 판 — 계정마다 최근 글을 보고 문턱을 넘은 것을 텔레그램으로 알리고, **그 글에 링크를 단다**
import { writeFile } from 'node:fs/promises'
import { 한판, 글월, 설정 } from './조회수알리미.mjs'
import { 알리기 } from './알림.mjs'
import { 달아야하나, 달기, 알림설정읽기, 실패인가 } from './늦은링크.mjs'
import { 계정팩 } from './팩.mjs'
import { 기록길 } from './늦은링크.mjs'
import { readFile } from 'node:fs/promises'

export const 결과길 = '조회수알리미결과.json'

const r = await 한판()

// ⚠️ **터진 글에만 링크를 단다** (2026-09-07, 사용자가 정했다 — 30시간 이내 · 1만 조회).
// 발행은 늘 깨끗하게 나가고, 여기서 문턱을 넘긴 글에 링크 답글을 하나 더 단다.
// 알림(한 번)과 달기(될 때까지)는 따로 본다 — 달기가 브라우저에서 죽으면 다음 30분에 다시 한다.
// 한 판에 여러 편이 넘어도 **한 편씩** 단다. 몰아 달면 봇처럼 보인다
const 단것 = []
const 못단것 = []
for (const 판 of r.판들) {
  const 정보 = r.정보?.[판.계정] ?? {}
  let 팩
  try { 팩 = 계정팩(정보) } catch { continue } // 팩이 안 맞는 계정은 발행도 안 된다. 여기서 던지면 알림까지 죽는다
  for (const g of 판.잰것 ?? []) {
    const 글 = await readFile(기록길(판.계정, g.code), 'utf8').then(JSON.parse).catch(() => null)
    const 판정 = 달아야하나(글, {
      조회수: g.성적?.조회수, 문턱: 설정.문턱, 시간: 설정.시간, 계정정보: 정보, 제휴팩: 팩.제휴팩,
    })
    if (!판정.단다) continue
    try {
      const 결과 = await 달기(판.계정, g.code, { 언어팩: 팩.언어팩, 제휴팩: 팩.제휴팩, 알림: (m) => console.log(m) })
      console.log(`  ${판.계정} ${g.code} → ${결과.달았다 ? '✅ 달았다' : `건너뜀 — ${결과.까닭}`}`)
      if (결과.달았다) 단것.push({ 계정: 판.계정, code: g.code, 상품: 결과.상품?.이름 ?? '', 주제결과: 결과.주제결과, 주소: 결과.주소 })
      else if (실패인가(결과)) 못단것.push({ 계정: 판.계정, code: g.code, 조회수: g.성적?.조회수, 까닭: 결과.까닭 })
    } catch (e) {
      // 다음 판에 다시 한다. 여기서 던지면 나머지 계정과 알림까지 죽는다
      console.error(`  ${판.계정} ${g.code} 링크 달기 실패 — ${String(e.message).slice(0, 160)}`)
      못단것.push({ 계정: 판.계정, code: g.code, 조회수: g.성적?.조회수, 까닭: String(e.message).slice(0, 160) })
    }
  }
}
await writeFile(결과길, `${JSON.stringify({
  때: r.때, 문턱: 설정.문턱, 시간: 설정.시간,
  판들: r.판들.map((p) => ({ 계정: p.계정, 본글: p.본글 ?? 0, 알린수: (p.알릴것 ?? []).length, 안됨: p.안됨 ?? null })),
  알린것: r.알릴것,
  링크단것: 단것,
  링크못단것: 못단것,
}, null, 1)}\n`)

// 단 것도 못 단 것도 사람에게 말한다 (2026-09-07, 사용자가 시켰다). 모니터링 화면의 스위치로 끈다.
// ⚠️ 잠잠 시간을 두지 않는다 — 글마다 한 번씩이라 시끄러워지지 않고, 못 단 것은 매 판 알아야 한다
const 알림설정 = await 알림설정읽기()
if (!알림설정.늦은링크 && (단것.length || 못단것.length)) console.log('(링크 달기 알림은 꺼져 있습니다 — 모니터링 화면)')
for (const d of 알림설정.늦은링크 ? 단것 : []) {
  const 붙었나 = /^「.+」 달았다$/.test(String(d.주제결과 ?? ''))
  await 알리기(
    `🔗 [${d.계정}] 터진 글에 링크를 달았습니다\n${d.상품}\n${d.주소}`
    // 「광고」 주제는 덤이다 — 답글 안에 대가성 문구가 있어 표기는 갖춰져 있다 (2026-09-07, 사용자가 정했다)
    + (붙었나 ? '' : `\n(「광고」 주제는 못 붙였습니다 — 대가성 문구는 들어 있어 표기는 갖춰져 있습니다. ${d.주제결과})`),
    { 종류: `늦은링크-${d.계정}-${d.code}`, 잠잠시간: 0 },
  )
}

const 글 = 글월(r.알릴것)
if (!글) {
  console.log(`문턱(${설정.문턱.toLocaleString('ko-KR')}회)을 넘은 새 글이 없습니다`)
  process.exit(0)
}
console.log(글)
// 잘 퍼지는 글은 **바로** 알아야 한다. 한 글은 한 번만 알리므로 시끄러워지지 않는다
const 결과 = await 알리기(글, { 종류: '조회수알리미', 잠잠시간: 0 })
console.log(결과.보냄 ? '→ 텔레그램으로 보냈습니다' : `→ 못 보냈습니다: ${결과.까닭}`)
for (const d of 알림설정.늦은링크 ? 못단것 : []) {
  await 알리기(
    `❌ [${d.계정}] 터진 글에 링크를 못 달았습니다\n조회 ${Number(d.조회수 ?? 0).toLocaleString('ko-KR')} · 글 ${d.code}\n까닭 — ${d.까닭}\n다음 30분 판에 다시 해 봅니다. 그래도 안 되면 손으로 달아 주세요.`,
    { 종류: `늦은링크실패-${d.계정}-${d.code}`, 잠잠시간: 0 },
  )
}
