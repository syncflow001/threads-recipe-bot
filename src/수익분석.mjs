// 쿠팡이 준 날짜별 숫자를 「그래서 무엇이 문제인가」로 바꾼다 — 순수 함수만 둔다
//
// ★ 클릭이 느는데 돈이 안 늘 때 어디가 막혔는지는 총액만 봐서는 절대 안 보인다.
//   클릭 → 주문 → 거래액 → 수수료 로 이어지는 길목마다 비율을 내야 보인다.

// 나누는 값이 0 이면 비율을 만들지 않는다. 0으로 나눈 Infinity 를 화면에 그리면 사람이 못 읽는다
const 나누기 = (위, 아래) => (아래 > 0 ? 위 / 아래 : null)
const 반올림 = (n, 자리 = 1) => (n == null ? null : Math.round(n * 10 ** 자리) / 10 ** 자리)

export function 합치기(줄들) {
  const 것 = { 수수료: 0, 클릭: 0, 주문: 0, 거래액: 0, 취소: 0 }
  for (const r of 줄들 ?? []) {
    것.수수료 += Number(r.수수료) || 0
    것.클릭 += Number(r.클릭) || 0
    것.주문 += Number(r.주문) || 0
    것.거래액 += Number(r.거래액) || 0
    것.취소 += Number(r.취소) || 0
  }
  return 것
}

// 길목마다의 비율. 하나라도 null 이면 그 자리는 「아직 모름」이다
export function 전환(합) {
  const ㅎ = 합 ?? {}
  return {
    // 클릭 한 번이 얼마를 벌어 주나. 이 값이 곧 「글 하나를 더 올릴 값어치」다
    클릭당수익: 반올림(나누기(ㅎ.수수료, ㅎ.클릭), 1),
    // 100번 눌러 몇 건이 사나. 상품이 글과 안 맞으면 여기서 무너진다
    백클릭당주문: 반올림(나누기(ㅎ.주문 * 100, ㅎ.클릭), 1),
    // 한 건에 얼마짜리를 사나. 싼 것만 팔리면 클릭이 많아도 돈이 안 된다
    주문당거래액: 반올림(나누기(ㅎ.거래액, ㅎ.주문), 0),
    // 수수료가 거래액의 몇 %인가. 쿠팡 기본이 3% 쯤이다 (실측)
    수수료율: 반올림(나누기(ㅎ.수수료 * 100, ㅎ.거래액), 2),
    // 취소가 많으면 수수료가 왜 안 느는지 이것으로만 설명된다
    취소율: 반올림(나누기(ㅎ.취소 * 100, ㅎ.주문 + ㅎ.취소), 1),
  }
}

export const 요일이름 = ['일', '월', '화', '수', '목', '금', '토']

// 어느 요일이 잘 되나. 발행 시각을 정하는 근거가 된다
export function 요일별(줄들) {
  const 칸 = 요일이름.map((이름) => ({ 이름, 수수료: 0, 클릭: 0, 주문: 0, 날수: 0 }))
  for (const r of 줄들 ?? []) {
    const d = new Date(`${r.날짜}T12:00:00`)
    if (Number.isNaN(+d)) continue
    const 것 = 칸[d.getDay()]
    것.수수료 += Number(r.수수료) || 0
    것.클릭 += Number(r.클릭) || 0
    것.주문 += Number(r.주문) || 0
    것.날수 += 1
  }
  // 날수가 다르면 총액끼리 견줄 수 없다. 하루 평균으로 고쳐야 요일끼리 비교가 된다
  return 칸.map((것) => ({
    ...것,
    하루평균수수료: 반올림(나누기(것.수수료, 것.날수), 0),
    하루평균클릭: 반올림(나누기(것.클릭, 것.날수), 1),
  }))
}

// 달마다 묶는다. 「이번 달이 지난달보다 나은가」가 가장 알기 쉬운 잣대다
export function 달별(줄들) {
  const 달 = new Map()
  for (const r of 줄들 ?? []) {
    const 키 = String(r.날짜).slice(0, 7)
    const 것 = 달.get(키) ?? { 달: 키, 수수료: 0, 클릭: 0, 주문: 0, 거래액: 0, 취소: 0, 날수: 0 }
    것.수수료 += Number(r.수수료) || 0
    것.클릭 += Number(r.클릭) || 0
    것.주문 += Number(r.주문) || 0
    것.거래액 += Number(r.거래액) || 0
    것.취소 += Number(r.취소) || 0
    것.날수 += 1
    달.set(키, 것)
  }
  return [...달.values()].sort((a, b) => a.달.localeCompare(b.달))
}

// 두 달을 견준다. 어느 칸이 늘고 줄었는지 화면이 그대로 그린다
export function 달견주기(이번, 지난) {
  if (!이번 || !지난) return null
  const 칸들 = ['수수료', '클릭', '주문', '거래액']
  return 칸들.map((칸) => {
    const ㅇ = Number(이번[칸]) || 0
    const ㅈ = Number(지난[칸]) || 0
    return {
      칸,
      이번: ㅇ,
      지난: ㅈ,
      차: ㅇ - ㅈ,
      // 지난달이 0 이면 몇 배 늘었다고 말할 수 없다. 늘었다는 사실만 전한다
      비율: ㅈ > 0 ? 반올림(((ㅇ - ㅈ) / ㅈ) * 100, 1) : null,
    }
  })
}

// 벌이가 없는 날이 며칠이나 되나. 「이번 달 3만 원」이 하루에 몰린 것인지 고르게 난 것인지
export function 벌이있는날(줄들) {
  const 다 = 줄들 ?? []
  const 있는날 = 다.filter((r) => (Number(r.수수료) || 0) > 0).length
  return { 전체: 다.length, 있는날, 비율: 반올림(나누기(있는날 * 100, 다.length), 0) }
}
