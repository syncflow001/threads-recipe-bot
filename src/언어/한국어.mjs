// 한국어 팩 — 이 언어로 글을 쓸 때 언어 자체가 정하는 것들

// 분야·제휴와 무엇이 다른가.
//   언어팩 — 어느 말로 쓰는가, 광고를 어떻게 표기하는가
//   분야팩 — 무엇을 쓸 만한 글로 보는가, 글의 뼈대가 무엇인가 (언어마다 따로 있다)
//   제휴팩 — 상품을 어디서 찾고 대가성 문구를 뭐라고 적는가

import { 씻기 } from '../글자.mjs'

// ── 수량 — 이 언어에서 분량을 어떻게 적는가 ─────────────────────────
// 분야팩이 아니라 여기 사는 까닭. 「2큰술」을 읽어 내는 일은 **한국어의 성질**이지
// 요리의 성질이 아니다. 일본어는 단위가 숫자 앞에 오고(大さじ2), 영어는 사이에
// 괄호가 낀다(2 (15-ounce) cans). 언어가 바뀌면 이 셋이 통째로 바뀐다.
// 예전에는 이것이 요리 팩마다 베껴져 있었고, 일본어 팩이 도우미 하나를 빠뜨려
// 발행 직전에 후보 네 편이 죽었다 (2026-08-24, 실측).

// ⚠️ 정규식에 `\b` 를 쓰지 마라. 자바스크립트 단어 경계는 한글을 단어로 안 쳐서
// 「2스푼」 뒤에서 절대 성립하지 않는다 — 한글 단위가 통째로 안 잡힌다.
const 수량꼴 = /(\d+(?:[./]\d+)?)\s*(티스푼|작은술|큰술|스푼|컵|개|장|모|쪽|줌|알|팩|인분|kg|g|ml|L|T|t)(?![\w가-힣])/g

// 같은 양인데 표기만 다른 것들. 큰술 = Tablespoon = T = 15ml, 작은술 = teaspoon = t = 5ml.
// 하나로 모아 두지 않으면 "2큰술" 과 "2T" 가 서로 다른 분량인 줄 알고 헛경보가 난다
const 단위한줄 = { 큰술: 'T', T: 'T', 작은술: 't', 티스푼: 't', t: 't' }

export const 수량 = {
  뽑기: (글) => [...씻기(글).matchAll(수량꼴)].map((m) => ({ 수: m[1], 단위: m[2] })),
  고른단위: (u) => 단위한줄[u] ?? u,
  // 표준 단위(T·t)는 원문에 그 글자로 없다. 겉모습을 되짚어야 헛경보가 안 난다
  같은표기: { T: ['큰술', 'T'], t: ['작은술', '티스푼', 't'] },
  // 글자가 깨졌나 보는 그물 — 「1스푼」이 「1스푤」로 나간 적이 있다
  깨짐꼴: /\d+(?:[./]\d+)?\s*[가-힣]{1,3}/g,
  // 한국어는 분량 뒤에 조사가 붙는다 — 「5분 담가둔다」를 「5분만 담가둬」로 쓴 것은
  // 깨진 것이 아니다. 조사를 떼고 견준다
  꼬리떼기: (꼴) => (/[만도은는이가을를에와과씩쯤랑나]$/.test(꼴) ? 꼴.slice(0, -1) : 꼴),
}

export default {
  이름: '한국어',
  코드: 'ko',

  // 광고임을 맨 앞에서 밝힌다. 첫 답글 첫 줄에 와야 한다.
  // 공정위 추천·보증 심사지침상 "눈에 잘 띄는 곳에" 표시해야 한다
  // ⚠️ 2026-09-02 — **사용자가 본문 [광고] 를 빼기로 정했다.** 이제 광고 표시는
  //    답글의 주제 태그(아래 주제태그) 하나뿐이다.
  //    그래서 **주제 달기가 실패하면 광고 표기가 아예 없는 글이 나간다** —
  //    src/브라우저답글.mjs 가 실패를 알리게 해 두었다. 알림이 오면 바로 봐야 한다
  광고표기: '',
  // 답글 작성창의 「커뮤니티 또는 주제」 칸에 넣는 말. 스레드가 공식으로 주는 광고 표시다
  주제태그: '광고',

  // LLM 에게 주는 언어 지시. 분야팩 지시문 앞에 붙는다
  쓰기지시: ['한국어로 쓴다.'],

  // 이 언어에서 분량을 어떻게 적는가. 분야팩(요리)이 이것으로 레시피를 가리고 분량을 대조한다
  수량,

  됨: true,
}
