// 일본어 팩 — 이 언어로 글을 쓸 때 언어 자체가 정하는 것들

import { 씻기 } from '../글자.mjs'

// ── 수량 — 이 언어에서 분량을 어떻게 적는가 ─────────────────────────
// ⚠️ **일본어는 단위가 숫자 앞에 온다** — `大さじ1` 이지 `1大さじ` 가 아니다.
// 한국어(`1큰술`)와 순서가 반대다. 숫자가 먼저인 꼴만 찾다가 진짜 레시피 24편을 막았다 (실측).
// 그래서 두 꼴을 다 훑는다. 이것이 언어팩에 사는 까닭이다 — 어순은 언어의 성질이다.
//   앞단위 — 大さじ1 · 小さじ1/2 · カップ1
//   뒷단위 — 2本 · 300g · 1/3本 · 1丁
// 「大1」「小2」 처럼 줄여 쓰기도 한다 (실측). 숫자가 바로 붙을 때만 단위로 본다
const 앞단위 = /(大さじ|小さじ|カップ|大匙|小匙|大|小)\s*(\d+(?:[./]\d+)?)/g
const 뒷단위 = /(\d+(?:[./]\d+)?)\s*(本|個|枚|片|切れ|玉|束|杯|人分|丁|房|株|かけ|パック|缶|袋|合|kg|g|ml|L|cc)(?![\wぁ-んァ-ヶ一-龠])/g

// 大さじ = 大匙 = 大 = 15ml, 小さじ = 小匙 = 小 = 5ml.
// ⚠️ 이 표가 없어서 `수량대조()` 가 `고른단위 is not defined` 로 죽었다 —
// 발행 직전 재구성 자리라 **쓸 만한 글을 찾아 놓고 네 편 다 버렸다** (2026-08-24 20:32, 실측)
const 단위한줄 = { 大さじ: 'T', 大匙: 'T', 大: 'T', 小さじ: 't', 小匙: 't', 小: 't', カップ: 'cup' }

export const 수량 = {
  뽑기: (글) => {
    const 씻은것 = 씻기(글)
    return [
      ...[...씻은것.matchAll(앞단위)].map((m) => ({ 수: m[2], 단위: m[1] })),
      ...[...씻은것.matchAll(뒷단위)].map((m) => ({ 수: m[1], 단위: m[2] })),
    ]
  },
  고른단위: (u) => 단위한줄[u] ?? u,
  // 하나로 모은 뒤에는 원문에서 되짚을 겉모습이 필요하다 — 원문에 'T' 라는 글자는 없다
  같은표기: { T: ['大さじ', '大匙', '大'], t: ['小さじ', '小匙', '小'], cup: ['カップ'] },
  깨짐꼴: /\d+(?:[./]\d+)?\s*[ぁ-んァ-ヶ一-龠]{1,4}/g,
}

export default {
  이름: '일본어',
  코드: 'ja',

  // 일본은 2023년 10월부터 스테마 규제(景品表示法)가 시행돼 광고임을 반드시 밝혀야 한다.
  // 실제 일본 스레드 요리 계정들이 쓰는 표기를 그대로 따랐다 (실측 2026-08-22) —
  // `[PR]` 이 가장 흔하고, 링크 바로 옆이나 앞줄에 붙인다
  광고표기: '[PR]',

  쓰기지시: [
    '日本語で書く。韓国語や英語を混ぜない。',
    // 스레드 일본 계정은 대부분 반말체(だ・である 아닌 친근한 구어)로 쓴다.
    // 다만 말투는 사람마다 다르므로 여기서 못 박지 않고 페르소나에 맡긴다
    '数字と単位は原文のまま写す。大さじ・小さじを勝手に入れ替えない。',
  ],

  // 이 언어에서 분량을 어떻게 적는가. 분야팩(요리)이 이것으로 레시피를 가리고 분량을 대조한다
  수량,

  됨: true,
}
