// 요리 분야의 로직 한 벌 — 낱말과 문장은 언어별 데이터 파일(`요리/<언어>.mjs`)이 준다

// 왜 갈랐나. 「이 글이 레시피인가」를 재는 알고리즘이 요리 팩 셋(한국어·일본어·영어)에
// **각각 베껴져** 있었다. 베낀 코드는 한쪽만 고쳐진다 — 수량 대조가 그렇게 사고를 냈다
// (2026-08-24, 설계서 §11). 알고리즘은 여기 한 벌만 둔다.
//
// 무엇이 어디 사는가.
//   여기            — 레시피 판정 알고리즘 · 계정 잣대 · 지시문 조립 (언어와 무관하다)
//   요리/<언어>.mjs — 낱말과 문장만 (醤油·大さじ·일본어 지시문). **함수를 두지 않는다**
//   언어/<언어>.mjs — 수량을 읽는 규칙 · 광고 표기 · 그 언어로 쓰라는 지시
//   제휴/<제휴사>   — 링크 · 대가성 문구
//
// 「醤油」는 요리 낱말이면서 일본어 낱말이다. 이 교차분은 없앨 수가 없어서
// 분야 폴더 밑 데이터 파일에 둔다. 새 언어를 열 때는 **그 파일 하나만** 채우면 된다.

import { 씻기 } from '../글자.mjs'
import { 수량대조만들기 } from '../수량.mjs'
import { 언어규칙 } from '../언어규칙.mjs'

// 데이터 파일이 반드시 갖춰야 할 칸. 하나라도 없으면 만들 때 던진다 —
// 조용히 빠지면 그 언어 계정에서만 판정이 헐거워지고 아무도 모른다
export const 있어야할칸 = [
  '글이름', '먹는말', '만드는말', '어림말', '촘촘단위꼴', '만드는법머리',
  '지시문', '출력지시', '부가글지시', '규칙', '마법사안내',
]

// 낱말(분야×언어 데이터)과 언어팩(수량 규칙)을 받아 분야팩 하나를 만든다.
// 돌려주는 모양은 갈라 놓기 전과 똑같다 — run.mjs·compose.mjs 는 아무것도 모른다
export default function 요리팩만들기(ㄴ, 언어팩) {
  for (const 칸 of 있어야할칸) {
    if (ㄴ?.[칸] == null) throw new Error(`요리 낱말 파일에 "${칸}" 이 없다`)
  }
  const 수량 = 언어팩?.수량
  if (!수량?.뽑기) throw new Error(`"${언어팩?.이름}" 언어팩에 수량 규칙이 없다`)

  // 분량으로 세면 안 되는 대목을 먼저 지운다. 영어의 영양 성분표(`20g protein per 100g`)가
  // 그것이다 — 요리 고유의 함정이라 언어팩이 아니라 낱말 파일이 정한다
  const 다듬기 = (글) => (ㄴ.지울꼴 ? String(글).replace(ㄴ.지울꼴, ' ') : String(글))
  const 분량뽑기 = (글) => 수량.뽑기(다듬기(글))

  // 어림말을 셀 때만 쓰는 전역판. `.test` 는 lastIndex 를 물고 다니면 안 되니 따로 둔다
  const 어림말들 = new RegExp(ㄴ.어림말.source, ㄴ.어림말.flags.includes('i') ? 'gi' : 'g')

  // 소문자로 모으는 것은 영어에만 뜻이 있다. 한글·가나에는 아무 일도 일어나지 않아
  // 칸을 하나 두는 대신 늘 소문자로 모은다
  const 재료수 = (글) => new Set((글.match(ㄴ.먹는말) ?? []).map((s) => s.toLowerCase())).size

  // 어디를 읽나. **영어권은 레시피가 본문에 있다** — 한국·일본과 반대다.
  // 표본 119편에서 글타래 8편 대 본문 20편이었다 (실측 2026-08-24)
  const 글모으기 = (게시물) => 씻기([
    ...(ㄴ.본문도본다 ? [게시물?.본문 ?? ''] : []),
    ...(게시물?.글타래 ?? []),
  ].filter((s) => s?.trim()).join('\n'))

  // 이 글 하나가 발행할 만한가.
  // ⚠️ 인자를 하나만 받아 넘긴다. `filter` 는 (글, 순번, 목록) 셋을 넘겨서
  // 뒤의 둘이 최소분량·최소재료 자리에 앉는다 — 검사가 통째로 무력해진다.
  // 실제로 요리가 아닌 글(Claude 쇼츠 프롬프트)이 레시피로 발행됐다 (08-24 00시 판)
  function 레시피있나(게시물, 최소분량 = 3, 최소재료 = 2) {
    const 타래 = 글모으기(게시물)
    if (!타래.trim()) return false
    // 숫자 분량이 먼저다. 어림말만 늘어놓은 글은 따라 만들 수가 없다.
    // 일본·영어는 둘이면 되고 그 위에 어림말을 더해 셋을 채운다 (`少々`·`to taste` 가 재료의 절반이다).
    // 한국어는 셋을 다 숫자로 요구한다 — 표본에서 그래도 안 막혔다
    const 분량수 = 분량뽑기(타래).length
    if (분량수 < (ㄴ.숫자최소 ?? 2)) return false
    if (분량수 + (타래.match(어림말들) ?? []).length < 최소분량) return false
    if (재료수(타래) < 최소재료) return false
    // 번호 목록도 순서로 본다. 여러 줄에 걸쳐 1. 2. 3. 이 나오면 만드는 차례다
    const 번호목록 = (타래.match(/(^|\n)\s*[1-9][.)]\s/g) ?? []).length >= 3
    if (ㄴ.만드는말.test(타래) || 번호목록) return true
    // 여기부터는 순서도 조리 동작도 없는 글이다 (드레싱·무침·재료 목록만 적은 글).
    // 갈리는 신호 둘 — ① 어림말은 레시피에만 나온다 ② 조리 계량이 촘촘하다
    if (ㄴ.어림말.test(타래)) return true
    return 분량뽑기(타래).filter((d) => ㄴ.촘촘단위꼴.test(d.단위)).length >= 2
  }

  // 이 계정이 요리 계정인가 — **글 하나가 발행할 만한가와 다른 물음이다.**
  // `레시피있나()` 는 분량·재료·순서를 다 요구한다. 계정을 고를 때 그것을 쓰면
  // "저장하세요" 한 줄로 터진 글만 올리는 요리 계정이 통째로 떨어진다
  // (실측 2026-08-24 — 영어 계정 다섯을 읽어 0개가 남았다).
  // 계정은 **무슨 이야기를 하는가**로 본다. 그래서 여기는 늘 본문도 함께 읽는다
  function 분야스러운가(게시물) {
    const 글 = 씻기([게시물?.본문 ?? '', ...(게시물?.글타래 ?? [])].filter((s) => s?.trim()).join('\n'))
    if (!글.trim()) return false
    const 수 = 재료수(글)
    return 수 >= 2 || (수 >= 1 && ㄴ.만드는말.test(글))
  }

  return {
    이름: '요리',
    글이름: ㄴ.글이름,
    검색어: ㄴ.검색어 ?? null,
    마법사안내: ㄴ.마법사안내,
    말투서식: ㄴ.말투서식 ?? null,
    쓸만한가: (게시물) => 레시피있나(게시물),
    분야스러운가,
    // 분량 대조는 공용(`수량.mjs`)이 한다. 언어팩이 준 규칙으로 돈다
    결과검사: 수량대조만들기(수량, ㄴ.지울꼴 ? { 미리다듬기: 다듬기 } : {}),
    링크앞머리: ㄴ.만드는법머리,
    별명꼴: ㄴ.별명꼴 ?? null,
    // 배열은 베껴 넘긴다. 부르는 쪽이 밀어 넣어도 팩이 안 더러워진다
    지시문: () => [...ㄴ.지시문],
    출력지시: () => [...ㄴ.출력지시],
    // ⚠️ **언어 지시는 여기서 박는다** (2026-08-26). 예전에는 언어팩의 `쓰기지시` 가
    // 아무 데서도 안 쓰였고, 「日本語で書く」 같은 못은 **계정 말투 파일에만** 있었다 —
    // 사용자가 대시보드에서 말투를 손보다 그 줄을 지우면 언어가 통째로 풀렸다.
    // 이제 말투를 어떻게 고쳐도 언어팩이 규칙 칸에 못을 박는다
    규칙: () => [...언어규칙(언어팩), ...ㄴ.규칙],
    // 페르소나가 레시피 형식을 적어 두었으면 맨 끝에 한 줄 더 붙는다.
    // 라벨은 언어마다 다르다 (한국어 `[레시피 형식]` · 일본어 `[형식]`)
    부가글지시: (페르소나) => [
      ...ㄴ.부가글지시,
      페르소나?.['레시피 형식'] ? `[${ㄴ.형식라벨 ?? '형식'}] ${페르소나['레시피 형식']}` : '',
    ].filter(Boolean),
  }
}
