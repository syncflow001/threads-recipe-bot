// 뷰티 분야의 로직 한 벌 — 낱말과 문장은 언어별 데이터 파일(`뷰티/<언어>.mjs`)이 준다

// 요리와 결정적으로 다른 점 셋을 실측으로 확인하고 만들었다 (표본 60편, 2026-08-21).
//   ① 알맹이가 글타래가 아니라 본문에 있다 — 60편 중 43편이 글타래가 없다.
//      요리처럼 글타래만 보면 뷰티는 전멸한다. 그래서 늘 본문과 글타래를 함께 본다
//   ② 질문글이 아주 많다 — "인생 파데 있으신가여" "추천해줄 수 있어?"
//   ③ 판매자·시딩 글이 섞인다 — "우리 회사 앰플 나왔다" "시딩용 제품이 사무실에 입고됐어"
//
// 요리와 판정이 아예 다르다. 그래서 분야마다 로직 파일이 하나씩이다 —
// 억지로 하나로 묶지 않는다

import { 씻기 } from '../글자.mjs'
import { 언어규칙 } from '../언어규칙.mjs'

export const 있어야할칸 = [
  '글이름', '제품말', '평가말', '쓰는말', '막을말', '쓰는법머리',
  '지시문', '출력지시', '부가글지시', '규칙', '마법사안내',
]

export default function 뷰티팩만들기(ㄴ, 언어팩) {
  for (const 칸 of 있어야할칸) {
    if (ㄴ?.[칸] == null) throw new Error(`뷰티 낱말 파일에 "${칸}" 이 없다`)
  }

  const 글모으기 = (게시물) => 씻기([게시물?.본문 ?? '', ...(게시물?.글타래 ?? [])].join('\n'))

  // 어떤 갈래의 제품 이야기인지 잡히고, 그 제품이 어떤지 말하거나
  // 어떻게 쓰는지 말해야 다시 쓸 알맹이가 된다
  const 알맹이있나 = (글) => new Set(글.match(ㄴ.제품말) ?? []).size >= 1
    && (ㄴ.평가말.test(글) || ㄴ.쓰는말.test(글))

  function 쓸만한가(게시물) {
    const 글 = 글모으기(게시물)
    if (!글.trim()) return false
    // 막을 것 넷 — 조르는 질문글 · 판매·시딩글 · 나쁘다는 후기 · 남에게 들은 이야기
    if (ㄴ.막을말.some((꼴) => 꼴.test(글))) return false
    return 알맹이있나(글)
  }

  // 이 계정이 뷰티 계정인가 — **글 하나가 쓸 만한가와 다른 물음이다.**
  // `쓸만한가()` 는 질문글·판매글·나쁜 후기를 다 막는다. 계정을 고를 때 그것을 쓰면
  // 멀쩡한 뷰티 계정이 통째로 떨어진다 (요리 영어에서 실제로 그랬다 — 다섯 중 0개)
  function 분야스러운가(게시물) {
    const 글 = 씻기([게시물?.본문 ?? '', ...(게시물?.글타래 ?? [])].filter((s) => s?.trim()).join('\n'))
    if (!글.trim()) return false
    return 알맹이있나(글)
  }

  return {
    이름: '뷰티',
    글이름: ㄴ.글이름,
    검색어: ㄴ.검색어 ?? null,
    마법사안내: ㄴ.마법사안내,
    말투서식: ㄴ.말투서식 ?? null,
    쓸만한가: (게시물) => 쓸만한가(게시물),
    분야스러운가,
    결과검사: null,   // 요리의 분량 대조에 해당하는 것이 없다. 없으면 compose 가 건너뛴다
    링크앞머리: ㄴ.쓰는법머리,
    별명꼴: ㄴ.별명꼴 ?? null,
    지시문: () => [...ㄴ.지시문],
    출력지시: () => [...ㄴ.출력지시],
    // 언어 지시는 여기서 박는다 — 까닭은 `분야/요리.mjs` 의 같은 자리에 적었다
    규칙: () => [...언어규칙(언어팩), ...ㄴ.규칙],
    부가글지시: (페르소나) => [
      ...ㄴ.부가글지시,
      페르소나?.['레시피 형식'] ? `[${ㄴ.형식라벨 ?? '형식'}] ${페르소나['레시피 형식']}` : '',
    ].filter(Boolean),
  }
}
