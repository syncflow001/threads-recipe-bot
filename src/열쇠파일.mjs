// `.env` 열쇠 파일을 다루는 규칙 한 곳 — 어떻게 적고, 자식에게 어떻게 넘기는가

// ⚠️ **왜 따로 있나 — 실제로 사고가 났다 (2026-08-26).**
// `node --env-file` 은 **이미 환경에 있는 변수를 덮어쓰지 않는다** (실측).
// 대시보드는 `--env-file=.env.local`(첫 계정)로 떠 있어서 `process.env.THREADS_COOKIE` 가
// 첫 계정 것이다. 그것을 자식에게 통째로 물려주니 `--env-file=.env.sample_dinner` 를 줘도
// **첫 계정 쿠키가 이겼다** — `sample_dinner` 로 누른 답글이 `example.cook` 로 달렸다.
//
// 그래서 **두 .env 파일에 적힌 열쇠 이름을 부모 환경에서 지우고** 넘긴다.
// 값은 안 읽는다 — 채우는 것은 `--env-file` 이 한다. 여기서는 자리를 비워 줄 뿐이다.
// (`.env.local` 에만 있는 공유 열쇠도 지운다 — 어차피 그 파일이 다시 채운다)

import { readFileSync } from 'node:fs'

// 값은 안 읽는다. 이름만 본다
export const 파일속열쇠이름 = (길) => {
  try {
    return readFileSync(길, 'utf8').split('\n')
      .map((줄) => 줄.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=/)?.[1])
      .filter(Boolean)
  } catch { return [] }
}

export function 자식환경(부모, 열쇠파일들) {
  const 나온것 = { ...부모 }
  for (const 길 of 열쇠파일들 ?? []) for (const 이름 of 파일속열쇠이름(길)) delete 나온것[이름]
  return 나온것
}

// ⚠️ **열쇠 한 줄을 어떻게 적는가 — 실측으로 정했다 (2026-08-26).**
// 예전에는 값에 공백이나 큰따옴표가 있으면 `JSON.stringify` 로 감쌌다. 그런데
// **`node --env-file` 은 `\\"` 를 못 읽고 거기서 값을 잘라 버린다** —
// 스레드 쿠키에는 `ig_did="..."` 처럼 큰따옴표가 들어 있어서, 계정 셋의 쿠키가
// 368→258 · 377→267 · 392→282 자로 **말없이 잘려 있었다.**
//
// 세 가지 표기를 실제로 재 봤다.
//   따옴표 없음  → 공백·큰따옴표는 되는데 **`#` 뒤가 잘린다** (주석으로 본다)
//   작은따옴표    → 공백·큰따옴표·`#` **전부 온전하다** ← 이것을 쓴다
//   JSON        → `\\"` 에서 잘린다 ⛔
//
// 작은따옴표가 값 안에 있으면 감쌀 수가 없다. 그때는 **조용히 자르지 않고 거부한다** —
// 잘린 열쇠로 도는 것이 못 쓰는 것보다 나쁘다
export function 열쇠줄(이름, 값) {
  const 다듬 = String(값 ?? '').trim()
  if (/[\r\n]/.test(다듬)) throw new Error(`${이름} 에 줄바꿈이 들어 있습니다 — 한 줄로 붙여 주세요`)
  if (다듬.includes("'")) throw new Error(`${이름} 에 작은따옴표(')가 들어 있어 안전하게 저장할 수 없습니다`)
  return `${이름}='${다듬}'`
}
