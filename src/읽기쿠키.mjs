// ⚠️ **아래 진단은 2026-09-06 에 절반이 뒤집혔다.** 먼저 읽어라 —
//    「계정(세션) 자체에 걸린 것」이 아니었다. **우리 요청 모양이 문제였다.**
//    `Sec-Fetch-Site: none` 으로 보내면 스레드가 어떤 계정에는 검색엔진용 껍데기를 준다.
//    홈에서 눌러 들어간 모양(`same-origin` + Referer)으로 바꾸자 **열세 계정이 다 읽혔다**
//    (`src/threads.mjs` 의 `문서헤더` 주석 참고). 사용자가 짚어 줬다 —
//    「크롬에서 홈의 글을 누르면 답글이 다 보이는데?」.
//    아래 「쿠키 칸을 하나씩 빼며 네 번 시험해도 그대로였다」가 맞는 관찰이었는데,
//    거기서 **「그러니 계정 문제다」로 건너뛴 것**이 틀렸다. 쿠키가 아니면 요청도 의심했어야 한다.
//    이 물러서기는 그대로 둔다 — 진짜로 못 읽는 날(2026-09-05 같은)에 여전히 쓸모가 있다.
//
// ⚠️ **왜 있나 (2026-09-03 실측 — 위 뒤집힘을 감안하고 읽어라).**
// 스레드가 어떤 계정에는 **글 상세 화면을 아예 안 그려 준다.** `sample_yori` 는 쿠키가 살아 있고
// 주인도 맞는데(`쿠키주인 → sample_yori`) 문서가 619KB 짜리 검색엔진용 축약본으로 온다 —
// 문서 안의 화면 이름이 `BarcelonaPostColumnRoute`(글 상세) 가 아니라
// `BarcelonaFeedColumnRoute · LoggedOutGating · SEO` 다. 그래서 **조회수도, 레시피가 실린
// 답글(글타래)도 통째로 빠진다.** 쿠키 칸을 하나씩 빼며 네 번 시험해도 그대로였다 —
// 쿠키 구성이 아니라 계정(세션) 자체에 걸린 것이다.
//
// 얼마나 손해인가 — `sample_yori` 홈에서 실제로 걷은 같은 글 15편을 두 쿠키로 열어 봤다.
//   제 쿠키   레시피 0편 (글타래 0조각)
//   남의 쿠키 레시피 3편 (글타래 10조각)
// 홈 피드는 멀쩡했다. 못 읽는 것 하나 때문에 판마다 0편이었다.
// 크롬으로 보면 답글이 보인다 — 이 대목이 열쇠였다. **브라우저가 더 받아 와서가 아니라,
// 브라우저가 보내는 요청 모양이 우리와 달랐기 때문이다** (2026-09-06 에 밝혀졌다).
//
// ⚠️ **읽기 전용이다. 여기서 얻은 쿠키를 쓰는 길에 넘기지 마라.**
// 글 올리기는 계정 제 API 토큰으로 하고(`토큰벽`), 답글·하트·팔로우는 `계정벽` 이 지킨다.
// CLAUDE.md §3-1 이 금하는 것은 **쓰기**에서 남의 열쇠로 물러서는 것이다 — 2026-08-26 에
// 남의 쿠키로 활동이 나간 사고 뒤에 세운 규칙이다. 읽기는 그 사고를 못 만든다.
// 빌리면 **누구 것인지 반드시 말한다** (2026-09-03 에 사용자가 정했다).

import { 상세채우기 } from './threads.mjs'
import { 계정열쇠읽기 } from './감시모음.mjs'
import { 계정목록 } from './계정.mjs'

// 빌린 쿠키가 쓸 만한지 볼 때 몇 편으로 재나. 한 편만 재면 안 된다 —
// 멀쩡한 쿠키로도 글 한 편은 조회수가 비어 있을 수 있다 (48편 중 1편 실측)
export const 표본수 = 3

// 이 글들에서 조회수나 레시피 답글을 하나라도 건졌나.
// **둘 다** 본다 — 조회수는 오래된 글이면 멀쩡한 쿠키로도 안 오고,
// 글타래는 작성자가 답글을 안 달았으면 원래 없다. 하나라도 있으면 읽힌 것이다
export const 읽혔나 = (글들) => (글들 ?? []).some(
  (p) => typeof p?.조회수 === 'number' || (p?.글타래?.length ?? 0) > 0)

// 이 계정 말고 로그인 쿠키가 있는 계정들. 목록은 `계정목록()` 하나로만 뽑는다 (CLAUDE.md §3-1)
export async function 빌릴쿠키들(계정, { 열쇠읽기 = 계정열쇠읽기, 목록 = 계정목록 } = {}) {
  const 것들 = []
  for (const 이름 of (await 목록()).filter((n) => n !== 계정)) {
    const c = await 열쇠읽기(이름, 'THREADS_COOKIE')
    if (c) 것들.push({ 계정: 이름, cookie: c })
  }
  return 것들
}

// 글 목록의 조회수·글타래를 채운다. 제 쿠키로 **하나도** 못 읽었으면 다른 계정 로그인을
// 빌려 다시 채우고, 어느 계정 것을 썼는지 함께 돌려준다.
//
// 헛디딤은 스스로 바로잡힌다 — 그 글들이 원래 조회수도 답글도 없는 것이라면
// 빌린 쿠키로 재도 똑같이 비어서 안 빌린다. 문서 몇 장이 더 나갈 뿐이다
export async function 읽어채우기(글들, {
  계정, cookie, 알림 = () => {}, 채우기 = 상세채우기, 빌릴것 = null,
} = {}) {
  await 채우기(글들, { cookie })
  if (!글들?.length || 읽혔나(글들)) return { cookie, 빌린계정: null }

  for (const 후보 of 빌릴것 ?? await 빌릴쿠키들(계정)) {
    const 표본 = 글들.slice(0, 표본수)
    await 채우기(표본, { cookie: 후보.cookie })
    if (!읽혔나(표본)) continue
    알림(`이 계정 로그인으로는 글을 못 읽습니다 — @${후보.계정} 의 로그인으로 다시 읽습니다 (읽기만 합니다)`)
    await 채우기(글들, { cookie: 후보.cookie })
    return { cookie: 후보.cookie, 빌린계정: 후보.계정 }
  }
  return { cookie, 빌린계정: null }
}
