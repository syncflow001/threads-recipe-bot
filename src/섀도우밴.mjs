// 계정이 조용히 덜 퍼지고 있는지(섀도우밴) 날마다 밖에서 재서 쌓는다.
//
// ⚠️ **「걸렸다」를 단정할 수 없다.** 메타는 이것을 reduced distribution ·
// not eligible for recommendations 라 부르고, 그 표시는 **앱의 「계정 상태」 화면에만** 있다.
// 밖에서는 못 읽는다. 그러니 여기서 하는 것은 **흔적 재기**이고, 화면은 반드시
// 「진짜 확인은 앱에서」를 함께 말해야 한다 (docs/섀도우밴-대응.md).
//
// 재는 것 둘.
//   ① 공개 노출 — **로그아웃한 눈으로 본 편수를 어제까지의 나와 견준다.**
//      ⚠️ 처음에는 「로그인한 눈 대 로그아웃한 눈」으로 견줬는데 **못 쓰는 신호였다** —
//      쿠키를 붙이면 스레드가 늘 8편만 준다(상한). 그래서 로그아웃 쪽이 늘 더 많아
//      이 신호는 **영영 안 켜졌다.** 검색 신호를 뺀 까닭이 「늘 빨간불」이었는데
//      이건 「늘 초록불」이라 같은 병이었다 (2026-08-31 검수에서 잡혔다).
//      지금은 **같은 눈끼리** 견준다 — 어제까지 열 편 보이던 것이 오늘 두 편이면 신호다
//   ② 도달 급락 — 이미 쌓고 있는 도달이력의 기준선 대비 비율.
//      ⚠️ 그 줄이 **언제 것인지 본다.** 도달 재기가 멈추면 몇 주 전 값이 오늘의 초록으로
//      계속 보고된다. 이틀 넘게 낡았으면 못 잰 것으로 친다
//
// ⚠️ **재 봤지만 못 쓴 신호 둘** (2026-08-31 실측). 다시 넣지 마라.
//   · **검색 노출** — 로그아웃 검색은 낱말 하나에만 먹고(네 낱말 넣으면 0편), 작은 계정 글이
//     상위에 안 뜨는 것은 정상이다. 건강한 `sample.unni`(도달 618%)도 「안 잡힘」이 나왔다.
//     늘 빨간불인 신호는 신호가 아니다
//   · **글 열어 보기** — 로그아웃으로 글 주소를 열면 **의심 계정도 멀쩡히 열린다.**
//     섀도우밴은 글을 지우는 게 아니라 **안 퍼뜨리는** 것이라 그렇다 (조사 결론과 같다)
import { readFile } from 'node:fs/promises'
import { join } from 'node:path'
import { 계정길 } from './계정.mjs'
import { 이어쓰기 } from './장부쓰기.mjs'
import { 프로필읽기 } from './threads.mjs'

export const 장부파일 = (계정, 뿌리 = process.cwd()) => join(뿌리, 계정길(계정, '섀도우밴장부.jsonl'))

export const 설정 = {
  // 도달이 기준선의 이만큼 아래면 신호를 켠다. 30% 는 노랑, 10% 는 빨강 —
  // 조사에서 「추천에서 빠지면 조회수가 90% 까지 준다」고 했다. 그 선을 빨강으로 잡았다
  도달노랑: 30,
  도달빨강: 10,
  // 어제까지 보이던 편수의 이만큼도 안 보이면 신호. 0편이면 빨강
  공개노랑: 0.5,
  공개볼날: 7,      // 며칠 치를 「평소」로 볼까
  도달낡음일: 2,    // 도달이력이 이만큼 낡았으면 못 잰 것으로 친다
  // 기준선이 팔로워 수의 이만큼도 안 되면 **그때 이미 눌려 있었다**고 본다.
  // 우리 일곱 계정 실측 — 성한 여섯이 3.09~8.47배인데 sample_dinner 만 0.06배였다.
  // 두 자릿수 차이라 1.0 배로 그으면 성한 것을 안 건드린다 (2026-08-31)
  기준선의심배수: 1.0,
  기준선최소표본: 3,   // 이보다 적은 편수로 찍은 기준선은 못 믿는다
}

// 신호 셋을 등급으로 바꾼다. 순수 함수라 검사로 다 재 볼 수 있다.
// 빨강 하나면 의심, 노랑 둘이면 주의. 못 잰 것(null)은 등급에 안 넣는다 —
// 그물이 끊긴 것을 「걸렸다」로 읽으면 헛알람이 된다
export function 판정(신호) {
  const 것들 = []
  const { 공개글수, 평소공개글수, 도달비율, 못받음 } = 신호 ?? {}

  // ⚠️ 그물이 끊긴 것을 사고로 읽지 않는다. `프로필읽기` 는 **안 던지고 빈 목록을 준다** —
  // 그것을 「0편 보인다」로 읽어 「의심」을 보내던 헛알람이 있었다 (2026-08-31 검수)
  if (!못받음 && 공개글수 != null && 평소공개글수) {
    것들.push(공개글수 === 0
      ? { 이름: '공개 노출', 빛: '빨강', 말: `평소 ${평소공개글수}편 보이던 글이 한 편도 안 보입니다` }
      : 공개글수 < 평소공개글수 * 설정.공개노랑
        ? { 이름: '공개 노출', 빛: '노랑', 말: `평소 ${평소공개글수}편이던 것이 ${공개글수}편만 보입니다` }
        : { 이름: '공개 노출', 빛: '초록', 말: `남 눈에 ${공개글수}편 보입니다 (평소 ${평소공개글수}편)` })
  }
  if (도달비율 != null) {
    것들.push(도달비율 < 설정.도달빨강
      ? { 이름: '도달', 빛: '빨강', 말: `평소의 ${도달비율}% 입니다` }
      : 도달비율 < 설정.도달노랑
        ? { 이름: '도달', 빛: '노랑', 말: `평소의 ${도달비율}% 로 낮습니다` }
        : { 이름: '도달', 빛: '초록', 말: `평소의 ${도달비율}% 입니다` })
  }

  const 빨강 = 것들.filter((s) => s.빛 === '빨강').length
  const 노랑 = 것들.filter((s) => s.빛 === '노랑').length
  // 신호가 둘뿐이라 노랑 하나도 말할 값이 있다.
  // ⚠️ **신호 하나로 「괜찮음」을 말하지 않는다.** 그 하나가 초록이어도 나머지를 못 잰 것이라
  // 「덜 잼」이다 — 초록 배지를 보고 안심하면 안 된다 (2026-08-31 검수)
  const 등급 = !것들.length ? '못잼'
    : 빨강 ? '의심'
    : 노랑 ? '주의'
    : 것들.length < 2 ? '덜잼'
    : '괜찮음'
  return { 등급, 신호들: 것들, 빨강, 노랑 }
}

// 도달이력의 마지막 줄. **날짜를 본다** — 도달 재기가 멈추면 몇 주 전 값이
// 오늘의 초록으로 계속 보고된다 (2026-08-31 검수에서 잡혔다)
async function 도달비율읽기(계정, 뿌리, 오늘 = new Date()) {
  const 글 = await readFile(join(뿌리, 계정길(계정, '도달이력.jsonl')), 'utf8').catch(() => '')
  const 줄들 = 글.trim().split('\n').filter(Boolean)
    .map((l) => { try { return JSON.parse(l) } catch { return null } }).filter(Boolean)
  const 마지막 = 줄들.sort((a, b) => String(a.날짜).localeCompare(String(b.날짜))).pop()
  if (!Number.isFinite(마지막?.비율)) return null
  const 지난날 = (Date.parse(오늘.toISOString().slice(0, 10)) - Date.parse(마지막.날짜)) / 86400000
  return Number.isFinite(지난날) && 지난날 > 설정.도달낡음일 ? null : 마지막.비율
}

// 도달 기준선을 못 믿을 까닭이 있나. **자를 못 믿으면 그 자로 잰 값도 못 쓴다** —
// 섀도우밴에 걸린 뒤 기준선을 처음 찍으면 아픈 상태가 「평소」로 굳어 비율이 늘 100% 근처다.
// 그러면 계정이 죽어 있어도 도달 신호는 영영 초록이다 (2026-08-31 검수가 짚은 구멍)
export function 기준선판정(기준선것, 팔로워, 옵션 = 설정) {
  if (!기준선것?.기준선) return null
  const { 기준선, 표본, 찍은때 } = 기준선것
  if (Number.isFinite(표본) && 표본 < 옵션.기준선최소표본) {
    return { 의심: true, 까닭: `기준선을 ${표본}편으로만 쟀어요 — 너무 적어 못 믿습니다`, 기준선, 팔로워, 표본, 찍은때 }
  }
  if (Number.isFinite(팔로워) && 팔로워 > 0 && 기준선 < 팔로워 * 옵션.기준선의심배수) {
    return {
      의심: true,
      까닭: `기준선(${Math.round(기준선)}회)이 팔로워(${팔로워}명)보다 적어요 — ` +
        `기준선을 찍을 때 이미 눌려 있었을 수 있습니다`,
      기준선, 팔로워, 표본, 찍은때,
    }
  }
  return { 의심: false, 기준선, 팔로워, 표본, 찍은때 }
}

// 어제까지 로그아웃 눈에 보이던 편수의 중앙값. 하루치 튐에 안 흔들리게 중앙값을 쓴다
export function 평소값(수들) {
  const 것 = (수들 ?? []).filter((n) => Number.isFinite(n)).sort((a, b) => a - b)
  if (!것.length) return null
  const 가운데 = Math.floor(것.length / 2)
  return 것.length % 2 ? 것[가운데] : Math.round((것[가운데 - 1] + 것[가운데]) / 2)
}

// 한 계정을 잰다. **로그아웃한 눈 하나로만** 본다 — 견줄 상대는 어제까지의 나다.
// ⚠️ `프로필읽기` 는 못 받아도 **안 던지고 빈 목록을 준다.** 그것을 「0편 보인다」로 읽으면
// 그물이 끊긴 날 「의심」이 날아간다. 팔로워도 글도 없으면 못 받은 것으로 친다
export async function 재기(계정, {
  뿌리 = process.cwd(), 아이디 = 계정, 프로필받기 = 프로필읽기, 지난것들, 오늘 = new Date(),
} = {}) {
  const 밖 = await 프로필받기(아이디, {}).catch(() => null)
  const 못받음 = !밖 || (밖.팔로워 == null && 밖.글들.length === 0)
  const 지난 = 지난것들 ?? await 장부읽기(계정, 뿌리, 설정.공개볼날)

  const 기준선것 = await 짐읽기(join(뿌리, 계정길(계정, '도달기준선.json')))
  const 팔로워줄들 = await 짐읽기(join(뿌리, 계정길(계정, '팔로워장부.json')))
  const 팔로워 = Array.isArray(팔로워줄들) ? 팔로워줄들[팔로워줄들.length - 1]?.수 : null
  const 기준선 = 기준선판정(기준선것, 팔로워)

  // ⚠️ 자를 못 믿으면 그 자로 잰 값도 안 쓴다. 오염된 기준선으로 잰 「100%」를 초록으로
  // 보여 주면 죽은 계정이 멀쩡해 보인다
  const 도달비율 = 기준선?.의심 ? null : await 도달비율읽기(계정, 뿌리, 오늘)

  return {
    공개글수: 못받음 ? null : 밖.글들.length,
    평소공개글수: 평소값(지난.filter((r) => !r.못받음).map((r) => r.공개글수)),
    도달비율,
    못받음,
    기준선탈: 기준선?.의심 ? 기준선.까닭 : null,
  }
}

const 짐읽기 = (길) => readFile(길, 'utf8').then(JSON.parse).catch(() => null)

export async function 한판(계정, 옵션 = {}) {
  const 뿌리 = 옵션.뿌리 ?? process.cwd()
  const 신호 = await 재기(계정, 옵션)
  const 것 = 판정(신호)
  const 줄 = { 때: (옵션.지금?.() ?? new Date()).toISOString(), 계정, ...신호, 등급: 것.등급, 신호들: 것.신호들 }
  await 이어쓰기(장부파일(계정, 뿌리), JSON.stringify(줄) + '\n')
  return 줄
}

export async function 장부읽기(계정, 뿌리 = process.cwd(), 몇줄 = 30) {
  const 글 = await readFile(장부파일(계정, 뿌리), 'utf8').catch(() => '')
  return 글.trim().split('\n').filter(Boolean)
    .map((l) => { try { return JSON.parse(l) } catch { return null } })
    .filter(Boolean).slice(-몇줄)
}
