// 여러 계정이 같은 시각에 몰리지 않게 발행 칸(시·분)을 자동으로 나눠 준다. 순수 함수, 파일을 안 읽는다

// 다른 계정과 이만큼(분) 안 떨어지면 겹친 것으로 본다.
// 3분에서 20분으로 늘렸다 (2026-08-28 사용자 요청) — 몇 분 차이로 두 계정이 연달아 올라가면
// 같은 사람이 굴리는 것이 눈에 보인다
export const 최소간격분 = 20

// 칸이 남의칸들 중 하나와 20분 안으로 붙어 있으면 true. 자정 넘김은 안 본다 (옛 규칙과 같다)
export function 겹치나(칸, 남의칸들) {
  const 나 = 칸.시 * 60 + 칸.분
  return 남의칸들.some((남) => Math.abs(나 - (남.시 * 60 + 남.분)) < 최소간격분)
}

// 그 시 안에서 남의칸들과 안 겹치는 첫 분(0,3,6,…,57 순서)을 찾는다. 없으면 null
function 빈분찾기(시, 남의칸들) {
  for (let 분 = 0; 분 <= 57; 분 += 3) {
    if (!겹치나({ 시, 분 }, 남의칸들)) return 분
  }
  return null
}

// 남들의 칸을 피해 이 계정의 칸을 고른다. 이미 고른 시가 있으면 그 시는 유지하고 분만 새로 고른다.
// 그 시에 빈 분이 없으면 다음 시로 밀고 밀림에 적는다
export function 자동배정({ 남들 = [], 시들 = [8, 12, 16, 20], 이미 = [] }) {
  const 남의칸들 = 남들.flatMap((x) => x.칸들)
  const 대상시들 = 이미.length ? 이미.map((c) => c.시) : 시들
  const 칸들 = []
  const 밀림 = []
  for (const 바란시 of 대상시들) {
    let 시 = 바란시
    let 분 = 빈분찾기(시, 남의칸들)
    while (분 === null) {
      시 += 1
      분 = 빈분찾기(시, 남의칸들)
    }
    if (시 !== 바란시) 밀림.push({ 바란시, 시 })
    칸들.push({ 시, 분 })
  }
  return { 칸들, 밀림 }
}
