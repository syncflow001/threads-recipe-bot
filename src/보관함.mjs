// 나중에 쓸 만한 글을 쟁여 두는 보관함 — 홈에서 건진 것을 담고, 발행할 때 꺼내 쓴다

import { readFile } from 'node:fs/promises'
import { 계정길 } from './계정.mjs'
import { 등급 as 등급매기기, 등급순위 as 순위 } from './score.mjs'
import { 안전쓰기 } from './장부쓰기.mjs'

export const 기본파일 = '보관함.json'

// ⚠️ **계정마다 따로 쟁인다.** 한 파일을 넷이 같이 쓰면 두 가지가 난다 (2026-08-24 에 짚었다).
//   ① 두 판이 겹치는 시각에 돌면 한쪽이 쓴 것을 다른 쪽이 통째로 덮는다 (둘 다 읽고 둘 다 쓴다)
//   ② **두 계정이 같은 글을 집어 같은 요리가 두 계정에 나갈 수 있다.**
//      중복 막이(미디어지문)는 계정별이라 이것을 못 잡는다
// 이름꼴은 열쇠·말투 파일과 같다 — 첫 계정은 이름이 빈 값이라 옛 파일을 그대로 쓴다
export const 보관함길 = (계정) => 계정길(계정, 기본파일)

// 미디어 주소는 하루 반이면 죽는다. 주소에 만료 시각이 박혀 있다 (실측 — oe 파라미터).
// 그래서 보관함은 주소를 믿지 않는다. 무엇이 쓸 만한지만 기억해 두고,
// 실제로 쓸 때 그 글을 다시 받아 새 주소를 얻는다.
export const 보관기간일 = 14

export async function 읽기(파일 = 기본파일) {
  try {
    const 것 = JSON.parse(await readFile(파일, 'utf8'))
    return Array.isArray(것) ? 것 : []
  } catch {
    return [] // 아직 없으면 빈 보관함이다. 없는 것은 고장이 아니다
  }
}

// 같은 글을 두 번 담지 않는다. 다시 담으면 등급과 조회수를 새것으로 갱신한다 —
// 조회수는 시간이 지나며 오르니 나중에 잰 값이 더 맞다.
export async function 담기(글들, { 파일 = 기본파일, 지금 = Date.now() } = {}) {
  const 자리 = new Map((await 읽기(파일)).map((p) => [p.code, p]))
  let 새것 = 0
  for (const p of 글들 ?? []) {
    if (!p?.code) continue
    const 있던 = 자리.get(p.code)
    if (!있던) 새것 += 1
    자리.set(p.code, { ...있던, ...p, 건진때: 있던?.건진때 ?? 지금, 갱신때: 지금 })
  }
  const 담긴것 = [...자리.values()]
  await 안전쓰기(파일, `${JSON.stringify(담긴것, null, 1)}\n`)
  return { 새것, 전체: 담긴것.length }
}

// ★ 저장된 등급을 그대로 믿지 않는다.
//   담을 때 팔로워를 몰라 옛 기준(좋아요÷조회수)으로 매겨진 글이 섞여 있고,
//   조회수는 시간이 지나며 오르므로 나중에 매기면 등급이 올라가기도 한다.
//   실측 (2026-08-25) — 저장된 등급으로는 실버 이상이 0개인데 다시 매기니 4개였다.
//   그 4개가 여태 묻혀서 발행이 보관함을 못 쓰고 있었다
export const 지금등급 = (p) => 등급매기기(p)?.등급 ?? p.등급 ?? '미달'

// 쓸 만한 것만 좋은 순으로 꺼낸다. 오래된 것은 내보내지 않는다 —
// 원글이 지워졌거나 미디어가 죽었을 확률이 높아서다.
// 문턱을 두지 않는다 (2026-08-25 에 사용자가 정했다). 등급은 순서만 정한다 —
// 좋은 것부터 꺼내되, 좋은 것이 없으면 그 아래라도 꺼낸다.
// 최소등급 매개변수는 남겨 두되 **발행은 안 쓴다** — 등급으로 막지 않는 것이 모든 계정의 규칙이다
// (2026-08-25 확정). 옛 MIN_GRADE 는 없앴다.
// ⚠️ **바탕값은 「미달」이 아니라 「알수없음」이다** (2026-09-03 에 사용자가 정했다).
// 「미달」로 두면 **조회수를 못 받아 등급을 못 매긴 글이 통째로 안 나온다** — 실측으로
// 여섯 계정에 9편이 그렇게 막혀 있었고 `sample_table` 은 보관함 전부가 그것이었다.
// 화면(`/api/archive`)은 그것들을 「쓸 수 있는 글」로 세고 있어서 **화면과 엔진이 어긋나 있었다**
export async function 꺼내기({ 파일 = 기본파일, 최소등급 = '알수없음', 지금 = Date.now() } = {}) {
  const 문턱 = 순위[최소등급] ?? 9
  const 만료 = 지금 - 보관기간일 * 24 * 60 * 60 * 1000
  return (await 읽기(파일))
    .map((p) => ({ ...p, 등급: 지금등급(p) }))
    .filter((p) => (순위[p.등급] ?? 9) <= 문턱 && (p.건진때 ?? 0) >= 만료)
    .sort((a, b) => (순위[a.등급] ?? 9) - (순위[b.등급] ?? 9) || (b.확산 ?? -1) - (a.확산 ?? -1))
}

// 쓴 글은 보관함에서 뺀다. 안 빼면 다음에 또 1등으로 올라온다
export async function 빼기(codes, { 파일 = 기본파일 } = {}) {
  const 뺄것 = new Set(codes ?? [])
  const 남은것 = (await 읽기(파일)).filter((p) => !뺄것.has(p.code))
  await 안전쓰기(파일, `${JSON.stringify(남은것, null, 1)}\n`)
  return 남은것.length
}
