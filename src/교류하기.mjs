export function 댓글다듬기(원시, 옵션 = 설정) {
  let j
  try { j = JSON.parse(원시) } catch { throw new Error(`LLM 이 JSON 이 아닌 것을 돌려줬다: ${String(원시).slice(0, 100)}`) }
  const 댓글 = String(j.댓글 ?? '').trim()
  const 뜻 = String(j.한국어뜻 ?? '').trim()
  if (!댓글) throw new Error('댓글이 비었다')
  if (!뜻) throw new Error('한국어 뜻이 없다 — 무슨 말이 나가는지 모르면 안 올린다')
  if (댓글.length > 옵션.댓글최대글자) throw new Error(`댓글이 너무 길다 (${댓글.length}자)`)
  if (/https?:\/\//.test(댓글)) throw new Error('댓글에 링크가 들어 있다')
  if (댓글.includes('#')) throw new Error('댓글에 해시태그가 들어 있다')
  return { 댓글, 뜻 }
}

// 화면에서 하트를 누른다. 이미 눌린 글은 건드리지 않는다 (누른 것을 취소하면 더 이상하다)
// 안에 — 주면 그 칸 안에서만 찾는다. 내 글 페이지에서 특정 댓글의 하트를 누를 때 쓴다 (답하기.mjs) —
// 페이지 전체에서 첫 하트를 잡으면 내 본문 것을 누른다
export async function 하트누르기(쪽, { 이름 = 하트이름, 안에 = null } = {}) {
  const 잡기 = (이름들) => (안에 ?? 쪽).locator(이름들.map((n) => `[role="button"]:has(svg[aria-label="${n}"])`).join(', '))
  if (await 잡기(이름.누름).count()) return '이미눌림'
  const 단추 = 잡기(이름.누르기).first()
  if (!(await 단추.count())) return '단추못찾음'
  await 단추.click()
  await 쪽.waitForTimeout(1500)
  // 눌렀다고 눌린 것이 아니다. 이름표가 「좋아요 취소」로 바뀌었는지 본다
  return (await 잡기(이름.누름).count()) ? '눌렀다' : '안눌림'
}

async function 댓글받아오기({ 언어, 분야, 글자, 재료 = [], 물어보기: 묻기 = 물어보기 }) {
  const { system, user } = 댓글지시문(언어, 분야, 글자, 재료)
  // 지시와 남의 글을 갈라 넘긴다. 합치면 그 글에 심긴 문장이 지시로 읽힐 수 있다
  return 댓글다듬기(await 묻기({ system, user }))
}

// 한 판 — 홈을 걷고, 그 언어 글에 하트를 누르고, 한 편에 댓글을 단다
export async function 한판(계정, {
  // 보기만 — 하트도 안 누르고 댓글도 안 올린다. 무엇을 할지와 댓글 뜻만 보여 준다.
  // 남에게 나가는 행동이라 미리 볼 자리가 있어야 한다
  보기만 = false,
  쿠키, 목표언어, 분야 = '요리', 내아이디, 뿌리 = process.cwd(), 분야스러운가 = null,
  재료 = [], // 계정의 목소리 — 활동말투.mjs
  옵션 = 설정, 굴림 = Math.random, 때 = new Date(), 알림 = () => {},
  걷기 = 홈에서걷기, 답글달기 = 브라우저로답글달기, 댓글만들기 = 댓글받아오기,
} = {}) {
  if (!목표언어) throw new Error('어느 언어로 활동할지 모른다')
  // 나가기 직전의 벽 — 이 쿠키가 정말 그 계정 것인가 (src/계정벽.mjs).
  // 「보기만」은 아무것도 안 나가니 안 건다 — 확인 한 번이 문서 요청 한 번이다
  if (!보기만) await (await import('./계정벽.mjs')).계정이름으로벽(계정, 쿠키, { 알림 })
  const 이미한것 = (await 장부읽기(뿌리))[계정] ?? []
  const 오늘까지 = 오늘한것(이미한것, 때)
  if (오늘까지.하트 >= 옵션.하루한계.하트) throw new Error(`오늘 하트를 이미 ${오늘까지.하트}개 눌렀다 (하루 ${옵션.하루한계.하트}개까지)`)

  const 하트수 = 사람처럼(옵션.하트, 굴림)
  const 적을것 = []
  const 초안하트 = [] // 보기만일 때 — 누를 뻔한 글
  let 댓글감 = null

  알림(`홈을 훑어 ${목표언어} 글을 찾는다`)
  await 걷기({
    쿠키, 계정, 스크롤수: 사람처럼(옵션.스크롤, 굴림),
    머문뒤: async (쪽, 걷은것) => {
      const 고른것 = 고를글(걷은것, { 목표언어, 내아이디, 이미한것, 몇개: 하트수, 분야스러운가 })
      if (!고른것.length) { 알림(`홈에 ${목표언어} ${분야} 글이 없다 — 먼저 그 언어 ${분야} 계정을 팔로우해야 한다`); return }
      알림(`${고른것.length}편에 하트를 누른다`)
      for (const p of 고른것) {
        const 초 = 사람처럼(옵션.머물초, 굴림)
        try {
          await 쪽.goto(`https://www.threads.com/@${p.작성자}/post/${p.code}`,
            { waitUntil: 'domcontentloaded', timeout: 45000 })
          await 쪽.waitForTimeout(초 * 1000) // 글을 읽는 시간. 열자마자 누르면 사람이 아니다
          const 결과 = 보기만 ? '보기만' : await 하트누르기(쪽)
          알림(`  하트 @${p.작성자} — ${결과}`)
          if (결과 === '눌렀다' || 결과 === '보기만') {
            if (보기만) 초안하트.push({ code: p.code, 작성자: p.작성자, 글자: String(p.글자 ?? '').slice(0, 80) })
            else 적을것.push({ 때: new Date(때).toISOString(), 한것: '하트', code: p.code, 작성자: p.작성자 })
            // 댓글은 하트를 실제로 누른 글 가운데 하나에만 단다
            if (!댓글감 && 오늘까지.댓글 < 옵션.하루한계.댓글) 댓글감 = p
          }
        } catch { 알림(`  하트 @${p.작성자} — 못 열었다`) }
      }
      await 쪽.goto('https://www.threads.com/', { waitUntil: 'domcontentloaded', timeout: 45000 }).catch(() => {})
    },
  })

  let 댓글기록 = null
  let 초안댓글 = null
  if (댓글감 && 옵션.댓글 > 0) {
    알림(`@${댓글감.작성자} 의 글에 ${목표언어}로 댓글을 쓴다`)
    const { 댓글, 뜻 } = await 댓글만들기({ 언어: 목표언어, 분야, 글자: 댓글감.글자, 재료 })
    // 사용자가 그 언어를 못 읽는다. 무슨 말이 나가는지 기록에 남긴다
    알림(`  ${보기만 ? '올릴 뻔한' : '올릴'} 댓글 — ${댓글}`)
    알림(`  한국어 뜻 — ${뜻}`)
    if (보기만) {
      초안댓글 = { code: 댓글감.code, 작성자: 댓글감.작성자, 원글: String(댓글감.글자 ?? '').slice(0, 120), 글: 댓글, 뜻 }
      알림('  보기만이라 아무것도 안 올렸다')
    } else {
      await 답글달기({
        주소: `https://www.threads.com/@${댓글감.작성자}/post/${댓글감.code}`,
        조각들: [댓글], 쿠키, 계정,
      })
      댓글기록 = {
        때: new Date(때).toISOString(), 한것: '댓글',
        code: 댓글감.code, 작성자: 댓글감.작성자, 글: 댓글, 뜻,
      }
      적을것.push(댓글기록)
      알림('  댓글을 올렸고 화면에서 보이는 것까지 확인했다')
    }
  }

  if (적을것.length) await 장부적기(계정, 적을것, 뿌리)
  return {
    하트: 적을것.filter((r) => r.한것 === '하트').length,
    댓글: 댓글기록 ? 1 : 0,
    댓글기록,
    초안: 보기만 ? { 하트: 초안하트, 댓글: 초안댓글 } : null,
  }
}

// 초안을 그대로 올린다 — 다시 고르거나 다시 쓰지 않는다. 사람이 본 그것이 나간다
export async function 초안올리기(계정, {
  쿠키, 뿌리 = process.cwd(), 옵션 = 설정, 굴림 = Math.random, 때 = new Date(), 알림 = () => {},
  걷기 = 홈에서걷기, 답글달기 = 브라우저로답글달기,
} = {}) {
  const 초안 = await 초안읽기(계정, 뿌리)
  if (!초안) throw new Error('올릴 초안이 없다 — 먼저 단추를 눌러 초안을 만든다')
  초안신선한가(초안, 때)
  const 적을것 = []
  if (초안.하트?.length) {
    알림(`초안대로 ${초안.하트.length}편에 하트를 누른다`)
    await 걷기({
      쿠키, 계정, 스크롤수: 0,
      머문뒤: async (쪽) => {
        for (const p of 초안.하트) {
          try {
            await 쪽.goto(`https://www.threads.com/@${p.작성자}/post/${p.code}`, { waitUntil: 'domcontentloaded', timeout: 45000 })
            await 쪽.waitForTimeout(사람처럼(옵션.머물초, 굴림) * 1000)
            const 결과 = await 하트누르기(쪽)
            알림(`  하트 @${p.작성자} — ${결과}`)
            if (결과 === '눌렀다') 적을것.push({ 때: new Date(때).toISOString(), 한것: '하트', code: p.code, 작성자: p.작성자 })
          } catch { 알림(`  하트 @${p.작성자} — 못 열었다`) }
        }
      },
    })
  }
  // ⚠️ 하트는 여기서 바로 적는다. 댓글 단계에서 죽으면 눌린 하트가 장부에 안 남는다 (2026-08-26 실측 —
  // 하트 3개·댓글 1개가 다 나갔는데 장부는 비고 초안은 남아, 다시 누르면 댓글이 두 번 갈 뻔했다)
  if (적을것.length) await 장부적기(계정, 적을것, 뿌리)
  if (초안.하트?.length) await 초안쓰기(계정, { ...초안, 하트: [] }, 뿌리) // 남은 일은 댓글뿐이라고 초안에 적어 둔다
  let 댓글기록 = null
  if (초안.댓글) {
    const c = 초안.댓글
    알림(`초안대로 @${c.작성자} 의 글에 댓글을 단다 — ${c.글}`)
    알림(`  한국어 뜻 — ${c.뜻}`)
    댓글기록 = { 때: new Date(때).toISOString(), 한것: '댓글', code: c.code, 작성자: c.작성자, 글: c.글, 뜻: c.뜻 }
    try {
      await 답글달기({ 주소: `https://www.threads.com/@${c.작성자}/post/${c.code}`, 조각들: [c.글], 쿠키, 계정 })
      알림('  댓글을 올렸고 화면에서 보이는 것까지 확인했다')
    } catch (e) {
      // 「게시」는 눌렀는데 화면에서 못 본 것이다. 올라갔을 가능성이 크다 — 다시 올리면 두 번 간다.
      // 그래서 장부에 「못봄」으로 적고 초안은 지운다. 사람이 그 글을 열어 보고 판단한다
      if (!/화면에 안 보인다/.test(e.message)) throw e
      댓글기록.확인 = '못봄'
      알림(`  ⚠️ 댓글을 올렸는데 화면에서 못 봤다 — 장부에 「못봄」으로 적는다. 그 글을 직접 열어 확인한다`)
    }
    await 장부적기(계정, [댓글기록], 뿌리)
  }
  await 초안버리기(계정, 뿌리) // 올린 초안은 지운다. 남겨 두면 두 번 올라간다
  return { 하트: 적을것.filter((r) => r.한것 === '하트').length, 댓글: 댓글기록 ? 1 : 0, 댓글기록 }
}

// ─── 단추가 부르는 자리 ────────────────────────────────────────────
if (import.meta.main) {
  const 계정 = (process.argv[2] ?? '').trim()
  // --보기만 을 주면 아무것도 안 누르고 무엇을 할지만 보여 준다
  const 보기만 = process.argv.includes('--보기만')
  const { 정보, 보일아이디 } = await import('./계정.mjs')
  const 그정보 = await 정보(계정)
  const 이름 = 계정 || '첫 계정'
  // 그 분야 글인지 보는 잣대 — 길들이기와 같다. 팩이 없으면 언어만 본다
  let 분야스러운가 = null
  try { 분야스러운가 = (await import('./팩.mjs')).계정팩(그정보).분야팩.분야스러운가 ?? null } catch {}
  // 댓글은 이 계정의 말투·언어팩·분야팩을 다 보고 짓는다 (2026-08-26)
  const 재료 = await (await import('./활동말투.mjs')).활동재료(계정, 그정보)

  if (!사람깨어있나()) {
    console.log(`⏸  [${이름}] 밤이라 안 한다 — 새벽에 하트가 찍히면 사람이 아닌 것이 보인다`)
    process.exit(0)
  }
  if (!process.env.THREADS_COOKIE?.trim()) {
    console.error(`‼️  [${이름}] THREADS_COOKIE 가 없다`)
    process.exit(1)
  }
  const 초안올림 = process.argv.includes('--초안')
  try {
    if (초안올림) {
      const r = await 초안올리기(계정, {
        쿠키: process.env.THREADS_COOKIE, 옵션: 하트댓글옵션(설정, 그정보.활동설정),
        알림: (m) => console.log(`  · ${m}`),
      })
      console.log(`✅ [${이름}] 초안대로 올렸다 — 하트 ${r.하트}개 · 댓글 ${r.댓글}개`)
      process.exit(0)
    }
    const r = await 한판(계정, {
      보기만,
      쿠키: process.env.THREADS_COOKIE,
      목표언어: 그정보.언어,
      분야: 그정보.분야,
      내아이디: 보일아이디(계정, 그정보),
      분야스러운가,
      재료,
      // 계정마다 값을 다르게 잡을 수 있다. 화면의 「하트·댓글」 칸에서 고친다
      옵션: 하트댓글옵션(설정, 그정보.활동설정),
      알림: (m) => console.log(`  · ${m}`),
    })
    if (보기만) {
      await 초안쓰기(계정, r.초안)
      const n = r.초안.하트.length + (r.초안.댓글 ? 1 : 0)
      console.log(n
        ? `👀 [${이름}] 초안을 만들었다 — 하트 ${r.초안.하트.length}개 · 댓글 ${r.초안.댓글 ? 1 : 0}개. 화면에서 확인하고 「이대로 올리기」를 누른다`
        : `👀 [${이름}] 초안에 담을 것이 없다 — 홈에 그 언어 글이 없었다`)
    } else {
      console.log(`✅ [${이름}] 하트 ${r.하트}개 · 댓글 ${r.댓글}개`)
      if (r.댓글기록) console.log(`   댓글 뜻 — ${r.댓글기록.뜻}`)
    }
  } catch (오류) {
    console.error(`‼️  [${이름}] ${오류.message}`)
    process.exit(1)
  }
}
