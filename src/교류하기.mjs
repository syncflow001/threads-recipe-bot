// 계정별 파일을 읽어 `{ 계정: [최신순 줄들] }` 로 준다.
// 옛 한 덩이 파일도 아직 읽는다 — `옛장부옮기기()` 를 안 돌린 자리(백업·다른 폴더)에서 돌 수 있다.
// **한 줄이 깨져도 그 줄만 버린다** — 예전 꼴이었다면 파일 전체가 날아갔다
export async function 장부읽기(뿌리 = process.cwd()) {
  const 다 = {}
  try {
    const 옛것 = JSON.parse(await readFile(장부길(뿌리), 'utf8'))
    if (옛것 && typeof 옛것 === 'object') for (const [계정, 줄들] of Object.entries(옛것)) {
      if (Array.isArray(줄들)) 다[계정] = [...줄들]
    }
  } catch { /* 옛 파일은 없어도 된다 */ }

  // ⚠️ **계정 폴더를 훑는다** (2026-08-29). 옛 코드는 뿌리에서 `활동장부.<계정>.jsonl` 을 찾았고,
  // 폴더 개편 뒤 하나도 못 찾아 **하루 한계가 전부 0 으로 읽혔다** — 같은 글에 하트를 또 누르고
  // 같은 사람을 또 팔로우하는, 계정이 막히기 딱 좋은 상태였다 (검증 에이전트가 잡았다)
  let 자리들 = []
  try { 자리들 = await readdir(join(뿌리, '계정')) } catch { return 다 }
  for (const 자리 of 자리들) {
    const 계정 = 자리 === 'main' ? '' : 자리
    let 원문 = ''
    try { 원문 = await readFile(계정장부길(계정, 뿌리), 'utf8') } catch { continue }
    const 줄들 = []
    for (const 줄 of 원문.split('\n')) {
      if (!줄.trim()) continue
      try { 줄들.push(JSON.parse(줄)) } catch { /* 깨진 줄 하나는 버리고 나머지를 살린다 */ }
    }
    다[계정] = [...줄들, ...(다[계정] ?? [])]
  }
  // 최신이 앞. 옛 파일은 최신이 앞이고 이어붙인 파일은 최신이 뒤라 때로 다시 세운다
  for (const 계정 of Object.keys(다)) {
    다[계정].sort((a, b) => String(b?.때 ?? '').localeCompare(String(a?.때 ?? '')))
  }
  return 다
}

// 옛 한 덩이 파일을 계정별 파일로 **한 번** 옮긴다. 옮기고 나면 옛 파일 이름을 바꿔 두어
// 두 번 옮기지 않는다. **지우지 않는다** — 되돌릴 자리를 남긴다.
// 사용자가 못 박았다 (2026-08-26) — 「각 계정마다 파일이 따로. 다른 계정과 혼용되거나 겹치면 안 된다」
export async function 옛장부옮기기(뿌리 = process.cwd()) {
  let 옛것
  try { 옛것 = JSON.parse(await readFile(장부길(뿌리), 'utf8')) } catch { return { 옮김: 0, 계정수: 0 } }
  if (!옛것 || typeof 옛것 !== 'object') return { 옮김: 0, 계정수: 0 }

  let 옮김 = 0
  let 계정수 = 0
  for (const [계정, 줄들] of Object.entries(옛것)) {
    if (!Array.isArray(줄들) || !줄들.length) continue
    // 옛 파일은 최신이 앞이다. 이어붙이기는 뒤로 쌓이니 뒤집어 넣는다 —
    // 읽을 때 때로 다시 세우지만 파일 자체도 시간 순이라야 사람이 열어 봤을 때 안 헷갈린다
    await 이어쓰기(계정장부길(계정, 뿌리), `${[...줄들].reverse().map((줄) => JSON.stringify(줄)).join('\n')}\n`)
    옮김 += 줄들.length
    계정수 += 1
  }
  await rename(장부길(뿌리), `${장부길(뿌리)}.옮김`).catch(() => {})
  return { 옮김, 계정수 }
}

// **이어붙이기만 한다. 읽지도 덮지도 않는다** — 그래야 겹쳐 적어도 남의 줄이 안 지워진다.
// 줄을 잘라 내지도 않는다. 사용자가 「유실되면 안 된다」고 못 박았다 (2026-08-26)
export async function 장부적기(계정, 줄들, 뿌리 = process.cwd()) {
  const 적을것 = (줄들 ?? []).filter(Boolean)
  if (!적을것.length) return []
  const 글 = `${적을것.map((줄) => JSON.stringify({ 때: new Date().toISOString(), ...줄 })).join('\n')}\n`
  await 이어쓰기(계정장부길(계정, 뿌리), 글)
  return 적을것
}

