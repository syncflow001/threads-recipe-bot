// 글에 적힌 분량이 원문과 같은지 대조한다 — 언어팩이 준 규칙으로 돈다

// 왜 공용인가. 예전에는 이 알고리즘이 요리 팩 셋(한국어·일본어·영어)에 각각 베껴져 있었다.
// 베낀 코드는 한쪽만 고쳐진다 — 일본어 팩을 만들 때 `고른단위` 를 빠뜨려
// **발행 직전에 후보 네 편이 통째로 죽었다** (2026-08-24 20:32, 실측).
// 검사 421개가 전부 초록인 채였다. 그래서 알고리즘은 여기 한 벌만 둔다.
//
// 무엇이 어디 사는가.
//   언어팩 — 이 언어에서 분량을 **어떻게 적는가** (`2큰술` · `大さじ2` · `2 tbsp`)
//   분야팩 — 이 글이 **그 분야 글인가** (재료 이름 · 조리 동작 · 어림말)
//   여기   — 원문과 결과글의 분량이 **같은가**
//
// 왜 필요한가. LLM 이 분량을 슬쩍 바꾸거나 글자를 깨뜨리는 일이 실제로 있었다
// (한국어에서 "1스푼" → "1스푤"). 자동 발행이라 아무도 못 잡는다.

import { 씻기, 붙이기 } from './글자.mjs'

// 언어팩의 `수량` 을 받아 대조 함수 하나를 만들어 돌려준다.
//   수량.뽑기(글)        → [{ 수, 단위 }]        그 언어의 분량을 다 찾아낸다
//   수량.고른단위(단위)   → 표준 단위             큰술·T 를 하나로 모은다
//   수량.같은표기        → { 표준: [겉모습들] }   원문에서 되짚을 겉모습
//   수량.깨짐꼴          → 정규식                 글자가 깨졌나 보는 그물
//   수량.안세는말        → 정규식 (없어도 된다)   분량이 아닌 것 (분·인분 따위)
//   수량.꼬리떼기(꼴)     → 꼴 (없어도 된다)      말끝을 떼고 견준다. 한국어 조사(2개**만**) 자리다
//   수량.대소문자무시     → 참이면 견줄 때 소문자로 (영어)
//
// 분야팩이 주는 선택값
//   미리다듬기(글) → 글    분량으로 세면 안 되는 대목을 지우고 넘긴다.
//                          영어 요리팩이 영양 성분표(`20g protein per 100g`)를 지우는 데 쓴다
export function 수량대조만들기(수량, { 미리다듬기 } = {}) {
  if (!수량?.뽑기) throw new Error('수량 규칙이 없다 — 언어팩에 `수량` 이 있어야 대조할 수 있다')

  const 같게 = (s) => (수량.대소문자무시 ? String(s).toLowerCase() : String(s))
  const 다듬 = (글) => (미리다듬기 ? 미리다듬기(글) : 글)

  return function 수량대조(원문, 결과글) {
    const 덩어리들 = (t) => 수량.뽑기(다듬(t)).map((d) => ({ 수: d.수, 단위: 수량.고른단위(d.단위) }))
    const 열쇠 = (d) => `${d.수}${d.단위}`

    const 원 = new Set(덩어리들(원문).map(열쇠))
    const 결덩어리 = 덩어리들(결과글)
    const 결 = new Set(결덩어리.map(열쇠))
    const 원붙임 = 같게(붙이기(원문))

    // 원문이 「양념장(큰술)」 처럼 머리말에만 단위를 쓰기도 한다. 그것을 풀어 쓴 것은 지어낸 게 아니다.
    // ⚠️ 표준 단위(T·t)는 원문에 그 글자로 없다 — `같은표기` 로 겉모습을 되짚어야 한다.
    // 이것이 없으면 헛경보가 난다. 경고가 잦으면 아무도 안 읽는다
    const 겉모습들 = (표준) => (수량.같은표기?.[표준] ?? [표준]).map(같게)
    const 풀어쓴것 = (d) => 원붙임.includes(같게(d.수)) && 겉모습들(d.단위).some((u) => 원붙임.includes(u))

    // 깨짐 — 원문에 없던 분량꼴이 결과에 생겼다. 글자가 깨졌을 수 있다.
    // ⚠️ 집합으로 견주면 안 된다. 원문에 셋 결과에 둘이면 양쪽 집합이 같아 사라진 하나가 안 보인다
    const 깨짐 = [...new Set([...씻기(결과글).matchAll(수량.깨짐꼴)].map((m) => 같게(붙이기(m[0]))))]
      .filter((꼴) => {
        if (원붙임.includes(꼴)) return false
        // 한국어는 분량 뒤에 조사가 붙는다 — 「2개만」 은 「2개」 가 깨진 것이 아니다
        if (수량.꼬리떼기 && 원붙임.includes(수량.꼬리떼기(꼴))) return false
        const 글자 = 꼴.replace(/^\d+(?:[./]\d+)?\s*/, '')
        if (!글자) return false
        if (수량.안세는말?.test(글자)) return false // 「10 minutes」 는 분량이 아니다
        return !원붙임.includes(글자)
      })

    return {
      추가됨: [...new Set(결덩어리.filter((d) => !원.has(열쇠(d)) && !풀어쓴것(d)).map(열쇠))],
      빠짐: [...원].filter((x) => !결.has(x)),
      깨짐,
    }
  }
}
