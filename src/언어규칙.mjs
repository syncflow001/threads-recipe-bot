// 언어팩의 「이 말로 쓰라」는 지시를 프롬프트 규칙 칸의 줄로 바꾼다

// 왜 따로 있나. 분야 로직 둘(요리·뷰티)이 같은 일을 하는데, 베껴 두면 한쪽만 고쳐진다 —
// 이 저장소가 그것으로 두 번 사고를 냈다 (설계서 §11-6).
//
// ⚠️ **언어 지시는 규칙 칸에 박아야 한다.** 예전에는 언어팩의 `쓰기지시` 가 아무 데서도
// 안 쓰였고, 「日本語で書く。韓国語や英語を混ぜない。」 같은 못은 계정 말투 파일
// (`persona.<계정>.json` 의 `지켜야 할 것`)에만 있었다. 대시보드에서 말투를 손보다
// 그 줄을 지우면 **언어가 통째로 풀린다.** 말투는 사람이 고치는 것이고 팩은 아니다.
export function 언어규칙(언어팩) {
  const 줄들 = 언어팩?.쓰기지시 ?? []
  if (!줄들.length) throw new Error(`"${언어팩?.이름 ?? '?'}" 언어팩에 쓰기 지시가 없다`)
  return 줄들.map((줄) => `- ${줄}`)
}
