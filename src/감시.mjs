// 조용히 멈춘 자동 발행을 잡는다 — 아무 일이 없어도 주에 한 번은 숫자를 보낸다
const 이틀 = (n) => String(n).padStart(2, '0')
const 칸글 = (c) => `${이틀(c.시)}:${이틀(c.분)}`

// 「기록없음」만 센다. 건너뜀은 간격을 지킨 것이고, 못올림은 쓸 글이 없었다는 뜻이다.
// 둘 다 정상인데 이걸 알리면 늘 우는 경보가 되고, 늘 우는 경보는 결국 꺼진다
// 첫판 은 'YYYY-MM-DD' 도 되고 'YYYY-MM-DD HH:MM' 도 된다.
// 시각까지 주면 **계정을 만든 날, 만들기 전 시각의 칸**을 세지 않는다 (2026-08-25 에 붙였다)
const 첫판가르기 = (첫판) => {
  if (첫판 == null) return { 날: null, 분: null }
  const [날, 시각] = String(첫판).split(' ')
  if (!시각) return { 날, 분: null }
  const [시, 분] = 시각.split(':').map(Number)
  return { 날, 분: 시 * 60 + 분 }
}

const 그날그상태 = (격자, 날짜, 첫판, 상태) => {
  const { 날: 첫날, 분: 첫분 } = 첫판가르기(첫판)
  // 계정이 그 날짜보다 뒤에 생겼으면 그날은 기록이 없는 게 정상이므로 세지 않는다
  if (첫날 !== null && 날짜 < 첫날) return []
  const 줄 = (격자?.줄 ?? []).find((r) => r.날짜 === 날짜)
  return (줄?.칸 ?? [])
    .filter((c) => c.상태 === 상태)
    .filter((c) => !(첫분 !== null && 날짜 === 첫날 && c.시 * 60 + c.분 < 첫분))
    .map(({ 시, 분 }) => ({ 시, 분 }))
}

export function 빈칸찾기(격자, 날짜, 첫판 = null) {
  return 그날그상태(격자, 날짜, 첫판, '기록없음')
}

// 「실패」는 돌긴 돌았는데 죽은 칸이다. 「기록없음」(아예 안 돈 것)과 다른 고장이라 따로 센다.
// ⚠️ 이걸 안 세서 후보 4편이 코드 오류로 전부 죽은 판을 감시기가 그냥 지나갔다 (2026-08-24 20:32).
// 못올림·건너뜀은 여전히 안 센다 — 그 둘은 정상이고, 늘 우는 경보는 결국 꺼진다
export function 실패찾기(격자, 날짜, 첫판 = null) {
  return 그날그상태(격자, 날짜, 첫판, '실패')
}

export function 아침글월(모음) {
  const 시각표문제 = (모음 ?? []).filter((m) => m.시각표없음)
  const 빈칸문제 = (모음 ?? []).filter((m) => m.빈칸?.length)
  const 실패문제 = (모음 ?? []).filter((m) => m.실패?.length)
  if (!시각표문제.length && !빈칸문제.length && !실패문제.length) return null // 보낼 것이 없으면 안 보낸다

  // 시각표없음 은 빈칸과 다른 고장이다 — 간격을 지킨 건너뜀이 아니라
  // 발행 시각표 자체가 없거나 못 읽는 것이다. 한 줄에 섞으면 구분이 안 된다
  const 시각표줄들 = 시각표문제.map((m) =>
    `[${m.별칭 || m.계정 || '첫 계정'}] 발행 시각표를 찾을 수 없습니다 — 자동 발행이 꺼졌을 수 있습니다`)
  const 빈칸줄들 = 빈칸문제.map((m) => {
    const 몇 = m.빈칸.length
    return `[${m.별칭 || m.계정 || '첫 계정'}] 어제 ${몇}번이 안 돌았습니다 (${m.빈칸.map(칸글).join(' · ')})`
  })
  // 「안 돌았다」와 「돌았는데 죽었다」는 사람이 할 일이 다르다. 말을 섞으면 안 된다
  const 실패줄들 = 실패문제.map((m) => {
    const 몇 = m.실패.length
    return `[${m.별칭 || m.계정 || '첫 계정'}] 어제 ${몇}판이 돌다가 실패했습니다 (${m.실패.map(칸글).join(' · ')})`
  })
  return ['⚠️ 자동 발행이 조용히 멈췄습니다', '', ...시각표줄들, ...빈칸줄들, ...실패줄들, '',
    '설정 화면 맨 아래 「왜 안 올라갔나」 를 눌러 보세요'].join('\n')
}

// 아무 일이 없어도 보낸다. 조용한 성공과 고장이 구분되지 않기 때문이다.
// ★이 글월이 안 오면 감시기가 죽은 것이다. 그게 감시기를 감시하는 유일한 신호다
export function 주간글월(모음) {
  const 줄들 = (모음 ?? []).map((m) => {
    const 도달 = m.도달 ? `도달 ${m.도달.비율}%` : '도달 (데이터 부족)'
    return `[${m.별칭 || m.계정 || '첫 계정'}]  올림 ${m.올림 ?? 0} · 막힘 ${m.막힘 ?? 0} · ${도달}`
  })
  return ['📋 지난 7일', '', ...(줄들.length ? 줄들 : ['(아직 계정이 없습니다)']), '',
    '이 보고가 안 오면 감시기가 멈춘 것입니다'].join('\n')
}

// 예정된 시각에 글이 안 올라갔을 때 사람에게 보내는 글월.
// ⚠️ 이것이 없어서 20:32 판이 후보 4편을 오류로 전부 버렸는데 아무도 몰랐다 (2026-08-24).
// 기록에는 「⏭ 쓸 만한 글이 없었습니다 (고장이 아닙니다)」 라고 찍혀 있었다 — 거짓말이었다.
//
// 담을 것 넷은 사용자가 정했다 — 계정 이름 · 사용자 이름 · 예정 시각 · 까닭.
// 까닭은 `쉬운말()` 이 이미 조치까지 한 문장에 담아 준다 ("… — 토큰을 다시 받아 주세요").
// 그래서 여기서 조치를 새로 짓지 않는다. 두 곳에 적으면 서로 어긋난다
export function 발행실패글월({ 계정, 별칭, 때, 까닭, 기록파일 } = {}) {
  const 이틀 = (n) => String(n).padStart(2, '0')
  const 날 = 때 instanceof Date && !Number.isNaN(+때) ? 때 : new Date()
  const 시각 = `${이틀(날.getMonth() + 1)}월 ${이틀(날.getDate())}일 ${이틀(날.getHours())}:${이틀(날.getMinutes())}`
  const 이름 = String(계정 || '').trim() || '첫 계정'
  const 부르는이름 = String(별칭 || '').trim()

  const 줄 = ['⚠️ 예정된 시각에 글이 안 올라갔습니다', '',
    `계정      ${부르는이름 ? `${부르는이름} (${이름})` : 이름}`,
    `예정 시각  ${시각}`,
    `까닭      ${String(까닭 || '').trim() || '까닭을 알 수 없습니다'}`, '',
    '무엇을 하면 되나',
    '· 대시보드 맨 아래 「왜 안 올라갔나」 를 눌러 보세요']
  if (기록파일) 줄.push(`· 자세한 것은 기록에 있습니다 — ${기록파일}`)
  return 줄.join('\n')
}
