// 「지금 이 쿠키가 정말 그 계정인가」를 나가기 직전에 확인한다 — 아니면 그 자리에서 멈춘다

// ⚠️ **왜 만들었나 — 실제로 사고가 났다 (2026-08-26).**
// 사용자가 `sample_dinner` 대시보드에서 「내 글 댓글에 답하기」를 눌렀는데
// **`example.cook`(첫 계정)로 댓글이 달렸다.**
//
// 까닭은 `node --env-file` 의 성질이었다 — **이미 환경에 있는 변수를 덮어쓰지 않는다** (실측).
// 대시보드는 `--env-file=.env.local`(첫 계정)로 떠 있고 자식에게 `env: {...process.env}` 를
// 통째로 물려줬다. 그래서 `--env-file=.env.sample_dinner` 를 줘도 첫 계정 쿠키가 이겼다.
// 그 구멍은 `설정화면.mjs` 에서 막았다. **하지만 그것만으로는 부족하다** —
// 열쇠가 어디서 어떻게 새든, **남에게 나가기 직전에 한 번 더 확인**해야 한다.
//
// 그래서 이 벽은 「값이 어디서 왔는가」를 안 믿는다. **스레드에게 직접 묻는다.**
//
// 벽을 세울 자리 — 남에게 무언가 나가는 모든 길목.
//   · 브라우저로 답글·댓글 달기 (`브라우저답글.mjs`)
//   · 팔로우 (`팔로우하기.mjs`)
//   · 하트 (`교류하기.mjs`)
// 읽기만 하는 길(홈 수집·조회수 재기)에는 안 건다. 잘못 읽는 것은 되돌릴 수 있다.

import { 문서받기 } from './threads.mjs'

// 로그인한 계정 아이디는 홈 문서 안에 있다 (실측 2026-08-26 — 세 계정 모두 하나만 나왔다).
// **다른 사람 아이디는 안 섞인다** — 홈 글 목록의 작성자들은 다른 칸에 들어 있다
const 아이디꼴 = /"username":"([A-Za-z0-9._]{2,30})"/g

export class 딴계정 extends Error {
  constructor(기대, 진짜) {
    super(`이 쿠키는 @${진짜} 것이다 — @${기대} 로 나가려던 것을 막았다`)
    this.기대 = 기대
    this.진짜 = 진짜
  }
}

// 쿠키의 주인이 누구인지 스레드에게 묻는다. 모르면 null (막지 않는다 — 아래 참고)
export async function 쿠키주인(쿠키, { 받기 = 문서받기 } = {}) {
  if (!쿠키?.trim()) return null
  let html = ''
  try { html = await 받기('https://www.threads.com/', { cookie: 쿠키 }) } catch { return null }
  const 것들 = [...new Set([...String(html).matchAll(아이디꼴)].map((m) => m[1]))]
  // 하나가 아니면 우리가 잘못 읽은 것이다. 짐작해서 막거나 통과시키지 않는다
  return 것들.length === 1 ? 것들[0] : null
}

// 나가기 직전의 벽. 주인이 기대와 **다르면 던진다.**
//
// ⚠️ **주인을 못 읽었을 때는 막지 않는다.** 스레드가 문서 꼴을 바꾸면 이 벽이
// 모든 활동을 통째로 세운다 — 그건 사고를 막는 게 아니라 프로그램을 죽이는 것이다.
// 대신 `알림` 으로 「확인 못 했다」를 남겨 사람이 안다. 확실히 다를 때만 막는다.
export async function 계정벽(기대아이디, 쿠키, { 받기 = 문서받기, 알림 = () => {} } = {}) {
  const 진짜 = await 쿠키주인(쿠키, { 받기 })
  if (!진짜) { 알림('⚠️ 이 쿠키가 누구 것인지 확인하지 못했다 — 그대로 진행한다'); return null }
  if (기대아이디 && 진짜 !== 기대아이디) throw new 딴계정(기대아이디, 진짜)
  return 진짜
}

// 계정 이름만 주면 실제 스레드 아이디를 스스로 알아내 벽을 친다.
// 부르는 쪽이 아이디를 안 갖고 있어도 되게 — 첫 계정은 이름이 빈 문자열이라 그냥 못 쓴다
export async function 계정이름으로벽(계정, 쿠키, opts = {}) {
  const { 정보, 보일아이디 } = await import('./계정.mjs')
  const 기대 = 보일아이디(계정, await 정보(계정).catch(() => null))
  if (!기대) { opts.알림?.('⚠️ 이 계정의 스레드 아이디를 몰라 확인을 건너뛴다'); return null }
  return 계정벽(기대, 쿠키, opts)
}
