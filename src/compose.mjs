// 원글에서 LLM 에게 줄 재료를 모은다. 자막과 이미지 속 글자까지 있으면 같이 넘긴다 —
// 본문만으로는 레시피의 분량·순서가 안 나오는 글이 많다.
export function 재료모으기(원글) {
  const 조각 = [`[원글]\n${원글.본문 ?? ''}`]
  // 레시피는 보통 여기 있다. 본문은 궁금하게만 만들고 재료·순서는 작성자가 답글로 단다.
  const 타래 = (원글.글타래 ?? []).filter((s) => s?.trim())
  if (타래.length) 조각.push(`[작성자가 이어 단 글 — 레시피는 보통 여기 있다]\n${타래.join('\n\n')}`)
  if (원글.자막) 조각.push(`[영상 자막]\n${원글.자막}`)
  if (원글.이미지글자) 조각.push(`[이미지 속 글자]\n${원글.이미지글자}`)
  return 조각.join('\n\n')
}

// 도입을 하나로 못 박으면 모든 글이 같은 첫 문장으로 나간다. 실제로 그랬다 —
// "~보고 따라 해봤거든" 을 규칙으로 굳힌 뒤 아홉 편 연속 같은 도입이었고 조회수가 열 배 넘게 떨어졌다.
// LLM 에게 고르라고 하면 또 한쪽으로 쏠린다. 원글 code 로 돌려 써서 글마다 다른 도입이 걸리게 한다
// 첫 줄 훅을 고른다. `{ 말, 무게 }` 로 주면 **무게만큼 자주** 뽑는다 —
// 잘 퍼지는 훅을 더 자주 쓰되 낮은 것도 계속 섞는다. 매번 같은 훅으로 열면 봇처럼 보인다.
// 글 번호로 고르므로 같은 글은 늘 같은 훅이다 (2026-08-31)
export function 도입고르기(유형들, 씨) {
  if (!Array.isArray(유형들) || !유형들.length) return ''
  let 해시 = 0
  for (const 글자 of String(씨 ?? '')) 해시 = (해시 * 31 + 글자.charCodeAt(0)) >>> 0
  // 소수 무게를 100배 해서 정수로 다룬다 — 나머지 연산이 소수에 흔들리지 않게
  const 것들 = 유형들.map((v) => (typeof v === 'string'
    ? { 말: v, 칸: 100 }
    : { 말: String(v?.말 ?? ''), 칸: Math.max(1, Math.round((Number(v?.무게) || 1) * 100)) }))
  const 합 = 것들.reduce((a, b) => a + b.칸, 0)
  let 쌓임 = 0
  const 뽑은칸 = 해시 % 합
  for (const 것 of 것들) {
    쌓임 += 것.칸
    if (뽑은칸 < 쌓임) return 것.말
  }
  return 것들[것들.length - 1].말
}

// 묶음(분야)이 없으면 만들지 않는다. 기본값을 두면 뷰티 계정이 조용히 요리 글을 뱉는다 —
// 그 조용한 실패를 없애려고 분야를 나눈 것이다
// 계정 말투 위에 **분야 팩의 서식을 바탕으로 깐다.** 계정 파일에 있는 칸이 이긴다 —
// 누가 말하느냐(정체성·말투·표현)는 계정 것이고, 레시피가 어떻게 생겼느냐는 분야 것이다.
// ⚠️ 전에는 서식이 계정 파일에만 있어서, 한 계정의 말투 파일이 망가지면 아무도 못 고쳤다.
// `sample_salim` 이 실제로 그랬다 — 레시피 형식 칸이 통째로 없어 밋밋한 글이 나갔다 (2026-08-31)
// ⚠️ 2026-09-02 — **분야 팩이 가진 칸은 전부 팩 것이다. 계정이 못 덮는다.**
//
// 사용자가 정했다 — 「한국어 요리팩이 실제 글을 쓰는 형식이고, 각 계정의 persona.json 은
// 그 계정의 **말투**를 담당하는 참고사항이다」.
//
// 전에는 `도입 유형` 하나만 팩 것이었다. 그래서 레시피 형식·규칙·길이를 실측대로 고쳐도
// **일곱 한국어 요리 계정 중 여섯에 한 글자도 안 갔다** — 계정 파일이 아직 「25줄 이내」와
// 「단계마다 요령을 한 줄 덧붙인다」를 시키고 있었다 (2026-09-02 실측, 프롬프트를 뽑아 확인).
// 그 여섯 칸은 손으로 다듬은 것이 아니라 **언어별로 똑같이 베껴진 보일러플레이트**였다
// ([[계정마다-복사본을-두면-아무도-못-고친다]]).
//
// 가르는 자리는 하나다 — **팩의 `말투서식` 에 그 칸이 있으면 형식이고, 없으면 말투다.**
// 형식(레시피 형식·규칙·길이·도입 유형·본문 길이·본문 이모지)은 실측이라 계정 취향으로
// 흔들면 안 되고, 말투(정체성·말투·자주 쓰는 표현·내 글 예시·글 구조…)는 계정 것이다.
// 팩에 없는 칸은 그대로 통과한다 — 계정이 제 칸을 더 두는 것을 막지 않는다
export function 서식깔기(페르소나, 묶음) {
  const 바탕 = 묶음?.말투서식
  if (!바탕) return 페르소나 ?? {}
  const 것 = { ...바탕 }
  for (const [칸, 값] of Object.entries(페르소나 ?? {})) {
    if (칸 in 바탕) continue // 팩이 가진 칸 = 형식. 계정 값은 버린다
    것[칸] = 값
  }
  return 것
}

