// 그래서 그 줄만 빼고 나머지 레시피로 올린다 (사용자가 정했다).
// LLM 이 지시를 놓쳐도 여기서 한 번 더 훑어 걷어낸다
// ⚠️ **그물은 분야팩이 준다** (2026-08-26). 예전에는 한국어 그물이 여기 박혀 있어서
// 일본어·영어 계정에는 이 안전장치가 통째로 없었다. 그물이 없는 팩(뷰티)이면
// LLM 이 찾아 준 별명만 지운다 — 없는 그물을 지어내지 않는다
export function 비밀재료빼기(레시피, 비밀재료, 별명꼴 = null) {
  const 실제 = (비밀재료?.실제 ?? '').trim()
  if (실제) return { 레시피: String(레시피 ?? ''), 뺀줄: [] } // 정체를 알면 그대로 둔다
  const 별명 = (비밀재료?.별명 ?? '').trim()
  if (!별명 && !별명꼴) return { 레시피: String(레시피 ?? ''), 뺀줄: [] }
  const 별명그대로 = 별명.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  const 지울꼴 = 별명 && 별명꼴 ? new RegExp(`${별명그대로}|${별명꼴.source}`)
    : 별명 ? new RegExp(별명그대로)
      : 별명꼴
  const 뺀줄 = []
  const 남은줄 = String(레시피 ?? '').split('\n').filter((줄) => {
    if (!지울꼴.test(줄)) return true
    뺀줄.push(줄.trim())
    return false
  })
  // 줄을 빼면 빈 줄이 둘씩 붙을 수 있다. 문단이 갈리면 링크만 덩그러니 남는다
  return { 레시피: 남은줄.join('\n').replace(/\n{3,}/g, '\n\n').trim(), 뺀줄 }
}

// 링크는 LLM 에게 맡기지 않는다. 주소를 지어내거나 흘리면 수수료가 날아간다.
//
// 지켜야 할 자리가 넷이다. 하나라도 어긋나면 안 된다.
//   1. 광고 표기 — 레시피 맨 위. 그래서 첫 답글의 첫 줄이 된다. 언어팩이 준다 (한국 [광고])
//   2. 한 줄 소개 — 링크 바로 위. 왜 이 재료인지 한 마디 (빈 줄 없이 같은 문단)
//   3. 링크 — 준비물 문단 끝. 재료를 읽는 그 자리에서 사러 갈 수 있어야 한다
//   4. 대가성 문구 — 레시피 맨 아래. 제휴팩이 준다. 제휴가 「없음」이면 넷 다 안 넣는다
// 링크가 없으면 넷 다 넣지 않는다. 광고가 아닌 글에 광고 표기를 붙이지 않는다.
export function 링크넣기(레시피, 링크들 = [], { 소개, 앞머리, 광고표기, 대가성문구, 되짚을말, 감춘꼴 } = {}) {
  const 줄 = 링크들.filter(Boolean).map((l) => (typeof l === 'string' ? l : `${l.이름} ${l.url}`))
  if (!줄.length) return 레시피

  // 소개와 링크는 빈 줄 없이 한 문단이다. 나뉘면 링크만 덩그러니 남는다
  // ⚠️ 2026-09-02 — **가림막을 여기서 자른다.** 팩이 「20자 이내」를 시키지만 LLM 은 넘긴다 —
  //    실측에서 111자까지 나왔다. 안 자르면 레시피 340자를 지켜도 답글이 쪼개진다(0.62배).
  //    지시는 부탁이고 이 줄이 약속이다.
  // ⚠️ **가림막은 레시피 340자에 안 들어간다.** LLM 이 「한줄소개」라는 딴 칸에 쓰고
  //    이 함수가 나중에 끼우기 때문이다. 그래서 340 + 30 이 함께 490 안에 들어가야 한다
  //    (2026-09-02 사용자 확인). 실측 — 레시피 340 + 가림막 30 → 답글 481자 · 한 조각
  const 가림막한도 = 30
  const 소개줄 = String(소개 ?? '').trim().slice(0, 가림막한도)
  const 링크문단 = [소개줄, ...줄].filter(Boolean).join('\n')

  const 문단들 = String(레시피 ?? '').split(/\n\s*\n/).filter((v) => v.trim())
  // 어느 문단 앞에 끼울지는 분야가 정한다 (요리는 「만드는 법」 앞 = 준비물 끝).
  // 못 찾으면 맨 뒤에 붙인다 — 링크를 잃는 것보다 낫다
  // ⚠️ 첫 문단은 건너뛴다. 요리 이름이 '🍳 애호박볶음' 이면 만드는법머리(🍳)에 걸려
  //    **링크가 맨 앞으로 간다** — 2026-09-02 에 시험하다 찾았다. 옛 코드에도 있던 결함이다
  const 자리 = 앞머리 ? 문단들.findIndex((문단, i) => i > 0 && 앞머리.test(문단)) : -1
  if (자리 < 0) { 문단들.push(링크문단); return [광고표기, ...문단들, 대가성문구].filter(Boolean).join('\n\n') }

  // ⚠️ 2026-09-02 — 링크를 준비물 문단 **끝**이 아니라 **안**에 끼운다.
  //
  // 답글에 링크를 단 레시피 글 146편 실측 — **78%가 재료 목록 「안」에 넣는다.**
  // 링크 뒤에도 재료가 이어지므로 읽는 사람이 링크를 건너뛰면 재료를 놓친다.
  // 조회수 827 대 568회. 맨 끝에 몰아 두는 것은 18%뿐이다 (docs/조사-제휴답글-형식.md)
  // 링크를 끼우면 뒤 문단이 밀릴 수 있다. 밀린 뒤의 「만드는 법」 자리를 따로 들고 간다
  let 만드는법자리 = 자리
  const 준비물 = 문단들[자리 - 1]
  const 재료줄 = 준비물 ? 준비물.split('\n') : []
  // 재료가 셋 이상이어야 「안」이 생긴다. 둘 이하면 끼울 자리가 없으니 옛 자리를 쓴다
  if (재료줄.length >= 4) {
    // ⚠️ 2026-09-02 — **이름을 감춘 그 줄 바로 밑**에 놓는다.
    //
    // 표본이 그렇게 한다 (docs/조사-제휴답글-형식.md §2) —
    //     ・이것 1~2큰술        ← 이름을 지운 재료 줄
    //     😳ㅡㅡ감칠맛재료!ㅡㅡ😳   ← 가림막 (우리는 한줄소개)
    //     https://link.coupang.com/a/…
    // 감춘 줄과 링크가 떨어져 있으면 「무엇을 사라는 건지」가 안 이어진다.
    // 못 찾으면 옛 자리(마지막 재료 앞)로 물러선다 — 링크를 잃는 것보다 낫다
    const 감춘줄 = 감춘꼴 ? 재료줄.findIndex((줄, k) => k > 0 && 감춘꼴.test(줄)) : -1
    // 뒤에 재료가 적어도 한 줄은 남아야 「건너뛰면 놓친다」가 성립한다
    const 끼울곳 = 감춘줄 > 0 ? 감춘줄 + 1 : 재료줄.length - 1
    문단들[자리 - 1] = [...재료줄.slice(0, 끼울곳), 링크문단, ...재료줄.slice(끼울곳)].join('\n')
  } else {
    // ⚠️ 2026-09-02 저녁 — **여기서 만드는 법 자리가 한 칸 밀린다.**
    //    밀린 것을 아래 되짚기에 알려 주지 않아, 되짚기가 방금 끼운 링크문단 자신을
    //    「만드는 법」으로 보고 아무것도 못 찾았다. **재료가 셋 이하인 레시피에서만**
    //    같은 링크 두 번(2.00배)이 통째로 무산됐다. 아무 경고도 없었다 (검수 에이전트가 잡았다)
    문단들.splice(자리, 0, 링크문단)
    만드는법자리 += 1
  }

  // ⚠️ 2026-09-02 — **같은 링크를 만드는 법에도 한 번 더 놓는다.**
  //
  // 146편 실측에서 32%가 그렇게 한다. 조회수 868 대 647회, 상위 비율로 2.00배다
  // (docs/조사-제휴답글-형식.md §6). 재료 목록에서 한 번, **그 재료를 실제로 쓰는 단계**에서 또 한 번 —
  // 읽다가 그 대목에서 링크를 다시 만난다.
  //
  // ⚠️ **서로 다른 링크를 늘리는 것과 다르다.** 그쪽은 691 대 800회로 오히려 낮았다.
  //    같은 링크를 반복하는 것만 통한다
  const 되짚기 = String(되짚을말 ?? '').trim()
  if (되짚기 && 만드는법자리 >= 0) {
    const 만드는법 = 문단들[만드는법자리]
    const 줄들 = 만드는법.split('\n')
    // 머리(👩🏻‍🍳 만드는 법)는 빼고, 그 재료가 나오는 **첫 단계** 뒤에 놓는다
    const i = 줄들.findIndex((줄, k) => k > 0 && 줄.includes(되짚기))
    if (i > 0) 문단들[만드는법자리] = [...줄들.slice(0, i + 1), ...줄, ...줄들.slice(i + 1)].join('\n')
  }

  return [광고표기, ...문단들, 대가성문구].filter(Boolean).join('\n\n')
}
