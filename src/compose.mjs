export async function 재구성(원글, { 페르소나, 키 = process.env.OPENAI_API_KEY, 모델 = 기본모델, fetch: 가져오기 = fetch } = {}) {
  if (!키) throw new Error('OPENAI_API_KEY 가 없다')
  const { system, user } = 프롬프트만들기(원글, 페르소나)

  const res = await 가져오기(끝점, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${키}` },
    body: JSON.stringify({
      model: 모델,
      messages: [{ role: 'system', content: system }, { role: 'user', content: user }],
      response_format: { type: 'json_object' },
    }),
  })
  if (!res.ok) throw new Error(`OpenAI ${res.status}: ${(await res.text()).slice(0, 200)}`)

  const 원시 = (await res.json())?.choices?.[0]?.message?.content
  if (!원시) throw new Error('OpenAI 응답이 비었다')

  let 결과
  try {
    결과 = JSON.parse(원시)
  } catch {
    throw new Error(`JSON 이 아닌 응답: ${원시.slice(0, 120)}`)
  }
  // 형태를 여기서 막지 않으면 빈 글이 발행 단계까지 흘러간다
  if (!결과.본문?.trim() || !결과.레시피?.trim()) throw new Error('본문 또는 레시피가 비었다')
  return {
    본문: 결과.본문.trim(),
    레시피: 결과.레시피.trim(),
    핵심재료: (결과.핵심재료 ?? '').trim(),
    한줄소개: (결과.한줄소개 ?? '').trim(),
    원글code: 원글.code,
    // 둘 다 비어 있어야 정상이다
    수량경고: 수량대조(재료모으기(원글), 결과.레시피),
  }
}

// LLM 이 분량을 슬쩍 바꾸거나 글자를 깨뜨리는 일이 실제로 있었다 ("1스푼" → "1스푤").
// 자동 발행이면 아무도 못 잡으므로 여기서 대조한다. 원문에 없는 수량은 전부 알린다.
// \b 를 쓰면 안 된다. 자바스크립트의 단어 경계는 한글을 단어로 치지 않아
// "2스푼" 뒤에서 절대 성립하지 않는다 — 한글 단위가 통째로 안 잡힌다.
const 수량꼴 = /(\d+(?:[./]\d+)?)\s*(스푼|큰술|작은술|컵|개|장|모|쪽|줌|알|팩|인분|kg|g|ml|L|T|t)(?![\w가-힣])/g

// 스레드 글에는 폭 없는 문자가 게시물당 3~25개씩 섞여 있다 (이모지 변형 선택자, 제로폭 공백).
// 자바스크립트의 \s 는 이것들을 공백으로 치지 않아서, "1<제로폭>모" 는 분량으로 안 잡힌다.
// 씻어내지 않으면 멀쩡한 레시피가 통째로 걸러진다.
const 씻기 = (s) => String(s ?? '').replace(/[\u200B-\u200D\uFEFF\u2060\uFE0E\uFE0F]/g, '')

// 양쪽으로 본다. 한 방향만 보면 못 잡는 것이 있다 —
// "1스푼" 이 "1스푤" 로 깨지면 단위 목록에 없는 글자라 결과에서는 아예 안 걸린다.
// 원문에 있던 분량이 결과에서 사라진 것으로 잡아야 보인다.
// 레시피가 실제로 적힌 글만 고른다.
// 스레드는 영상 자막(transcription_data)을 한 번도 안 채워준다 — 확인한 게시물 전부 null 이었다.
// 그래서 "순서는 영상 참고하세요" 류의 글은 아무리 잘 재구성해도 재료만 있고 순서가 빈다.
// 직접 음성인식을 돌리는 건 배보다 배꼽이라 하지 않는다. 대신 이런 글을 후보에서 뺀다.
export function 레시피있나(게시물, 최소분량 = 3) {
  const 타래 = 씻기((게시물.글타래 ?? []).filter((s) => s?.trim()).join('\n'))
  if (!타래.trim()) return false
  return [...타래.matchAll(수량꼴)].length >= 최소분량
}

// 집합만으로는 못 잡는다. "1스푼" 이 원문에 셋, 결과에 둘 있으면 양쪽 집합에 다 들어 있어
// 사라진 하나가 안 보인다. 실제로 "초절임 식초 1스푼" 이 "1스푤" 로 깨진 채 발행됐다.
// 그래서 '숫자+한글' 을 통째로 훑어, 원문에 없는 꼴이 결과에 있으면 깨진 것으로 본다.
// 단위 목록에 기대지 않는 게 핵심이다 — 깨진 글자는 어차피 목록에 없다.
const 한글수량꼴 = /\d+(?:[./]\d+)?\s*[가-힣]{1,3}/g
const 붙이기 = (s) => 씻기(s).replace(/\s+/g, '')

export function 수량대조(원문, 결과글) {
  const 뽑기 = (s) => new Set([...씻기(s).matchAll(수량꼴)].map((m) => `${m[1]}${m[2]}`))
  const 원 = 뽑기(원문)
  const 결 = 뽑기(결과글)
  const 원붙임 = 붙이기(원문)
  // "5분" 이 "5분만" 으로 쓰이면 원문에 그대로는 없다. 조사 한 글자를 떼고 다시 본다.
  // 깨진 글자는 조사가 아니라서 떼어도 안 맞는다 — "1스푤" 은 그대로 걸린다
  const 조사떼기 = (꼴) => (/[만도은는이가을를에와과씩쯤랑나]$/.test(꼴) ? 꼴.slice(0, -1) : 꼴)
  const 깨짐 = [...new Set([...씻기(결과글).matchAll(한글수량꼴)].map((m) => 붙이기(m[0])))]
    .filter((꼴) => !원붙임.includes(꼴) && !원붙임.includes(조사떼기(꼴)))
  return {
    추가됨: [...결].filter((x) => !원.has(x)), // 없던 분량을 지어냈다
    빠짐: [...원].filter((x) => !결.has(x)), // 원문 분량이 사라졌다
    깨짐, // 원문에 없는 '숫자+한글' — 글자가 깨졌거나 지어냈다
  }
}

// 공정위 추천·보증 심사지침상 대가를 받는 링크에는 그 사실을 밝혀야 한다. 빼면 안 된다.
export const 대가성문구 = '쿠팡파트너스 활동의 일환으로 일정액의 수수료를 제공받습니다'

// 만드는 법이 시작되는 문단. 링크는 이 앞에 — 즉 준비물 문단 끝에 넣는다
const 만드는법머리 = /^\s*(?:[👩🧑🍳]|만드는|만들기|조리법|조리\s)/u

// 광고임을 맨 앞에서 밝힌다. 첫 답글 첫 줄에 와야 한다
export const 광고표기 = '[광고]'

// 링크는 LLM 에게 맡기지 않는다. 주소를 지어내거나 흘리면 수수료가 날아간다.
//
// 지켜야 할 자리가 넷이다. 하나라도 어긋나면 안 된다.
//   1. [광고] — 레시피 맨 위. 그래서 첫 답글의 첫 줄이 된다
//   2. 한 줄 소개 — 링크 바로 위. 왜 이 재료인지 한 마디 (빈 줄 없이 같은 문단)
//   3. 링크 — 준비물 문단 끝. 재료를 읽는 그 자리에서 사러 갈 수 있어야 한다
//   4. 대가성 문구 — 레시피 맨 아래
// 링크가 없으면 넷 다 넣지 않는다. 광고가 아닌 글에 광고 표기를 붙이지 않는다.
export function 링크넣기(레시피, 링크들 = [], { 소개 } = {}) {
  const 줄 = 링크들.filter(Boolean).map((l) => (typeof l === 'string' ? l : `${l.이름} ${l.url}`))
  if (!줄.length) return 레시피

  // 소개와 링크는 빈 줄 없이 한 문단이다. 나뉘면 링크만 덩그러니 남는다
  const 링크문단 = [String(소개 ?? '').trim(), ...줄].filter(Boolean).join('\n')

  const 문단들 = String(레시피 ?? '').split(/\n\s*\n/).filter((v) => v.trim())
  const 자리 = 문단들.findIndex((문단) => 만드는법머리.test(문단))
  if (자리 < 0) 문단들.push(링크문단)
  else 문단들.splice(자리, 0, 링크문단)

  return [광고표기, ...문단들, 대가성문구].join('\n\n')
}
