// 쿠팡파트너스 팩 — 상품을 찾아 글마다 다른 꼬리표를 붙인 링크를 만든다 (한국 전용)

import { 레시피링크 } from '../coupang.mjs'

export default {
  이름: '쿠팡파트너스',
  나라: '한국',

  // 공정위 추천·보증 심사지침상 대가를 받는 링크에는 그 사실을 밝혀야 한다. 빼면 안 된다.
  // 링크와 한 문단으로 묶는다 — 사이에 빈 줄을 두면 글타래가 나뉠 때
  // 링크만 있고 고지가 없는 조각이 생긴다
  대가성문구: '쿠팡파트너스 활동의 일환으로 일정액의 수수료를 제공받습니다',

  // 이름 한 번, 주소 두 줄. 사용자가 벤치마킹한 계정들이 그렇게 한다 —
  // 두 줄이면 사람들이 더 잘 누르고, 이름까지 두 번 쓰면 지저분하다
  링크만들기: (핵심재료, code, opts) => 레시피링크(핵심재료, code, opts),
  링크줄만들기: (상품) => [상품.이름.slice(0, 30), 상품.url, 상품.url],

  됨: true,
}
