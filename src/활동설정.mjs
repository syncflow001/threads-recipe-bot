export const 범위로 = (가운데) => {
  const n = Math.max(1, Math.round(Number(가운데) || 1))
  return [Math.max(1, Math.round(n * (1 - 흩뜨림))), Math.max(1, Math.round(n * (1 + 흩뜨림)))]
}

