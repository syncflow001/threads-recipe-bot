export const 기본값 = Object.fromEntries(차림.map((ㅊ) => [ㅊ.키, ㅊ.기본]))

// 화면에서 온 값을 믿지 않는다. 차림표에 없는 키는 버리고, 범위 밖은 잘라 넣는다
export function 다듬기(받은것) {
  const 것 = {}
  for (const ㅊ of 차림) {
    const v = Number(받은것?.[ㅊ.키])
    것[ㅊ.키] = Number.isFinite(v)
      ? Math.min(ㅊ.최대, Math.max(ㅊ.최소, Math.round(v)))
      : ㅊ.기본
  }
  // 자는 시각이 깨는 시각보다 빠르면 하루 종일 안 돈다. 그때는 기본으로 되돌린다
  if (것.자는시각 <= 것.깨는시각) {
    것.깨는시각 = 기본값.깨는시각
    것.자는시각 = 기본값.자는시각
  }
  return 것
}

// 길들이기.mjs 가 쓰는 꼴로 바꾼다. 범위는 우리가 흩뜨린다
export function 길들이기옵션(원래설정, 계정설정) {
  const 것 = 다듬기(계정설정)
  return {
    ...원래설정,
    깨는시각: 것.깨는시각,
    자는시각: 것.자는시각,
    스크롤: 범위로(것.스크롤),
    열어볼글: 범위로(것.열어볼글),
    머물초: 범위로(것.머물초),
    한판에검색어: 것.한판에검색어,
  }
}

// 교류하기.mjs 가 쓰는 꼴
export function 하트댓글옵션(원래설정, 계정설정) {
  const 것 = 다듬기(계정설정)
  return {
    ...원래설정,
    하트: 범위로(것.하트),
    댓글: 것.댓글,
    하루한계: { 하트: 것.하루하트, 댓글: 것.하루댓글 },
  }
}

// 말투추천.mjs 의 한도 꼴
export function 팔로워찾기옵션(원래한도, 계정설정) {
  const 것 = 다듬기(계정설정)
  return { ...원래한도, 볼계정: 것.볼계정, 읽을글: 것.읽을글 }
}
