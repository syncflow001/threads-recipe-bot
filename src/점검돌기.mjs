// 30분마다 전 계정을 훑어 이상을 찾고, 상태가 바뀔 때만 기록하고 알린다 — 아무것도 켜거나 끄지 않는다
import { homedir } from 'node:os'
import { join } from 'node:path'
import { 계정점검, 전체점검, 견주기, 날짜글 } from './점검.mjs'
import { 상태읽기, 상태쓰기, 기록더하기, 전체자리 } from './점검기록.mjs'
import { 정보, 장부읽기 } from './계정.mjs'
import { 알리기 } from './알림.mjs'

const 지금이소 = (지금) => new Date(지금).toISOString()

// 기록 한 줄의 꼴 그대로. 처음본때 는 기록에 안 넣는다 — 상태(점검상태.json)에만 쓴다
const 기록줄 = (일, 지금, x) => ({ 때: 지금이소(지금), 일, 갈래: x.갈래, 무엇: x.무엇, 원인: x.원인, 심각도: x.심각도, 열쇠: x.열쇠 })

const 문제줄글 = (x) => `· [${x.갈래}] ${x.무엇}${x.원인 ? ' — ' + x.원인 : ''}`

function 글월만들기(머리글, 생김, 고쳐짐) {
  const 칸들 = [머리글]
  if (생김.length) 칸들.push('', `새로 생긴 문제 ${생김.length}개`, ...생김.map(문제줄글))
  if (고쳐짐.length) 칸들.push('', `돌아왔습니다 ${고쳐짐.length}개`, ...고쳐짐.map(문제줄글))
  return 칸들.join('\n')
}

// ⚠️ 발행 문제의 열쇠에는 날짜가 들어간다(`발행:2026-08-29 20:02`). 자정이 지나면 어제 열쇠가
// 새 목록에 없어 견주기 가 「고쳐짐」으로 본다 — 안 올라간 글은 여전히 안 올라간 것이라 가짜다.
// 발행이 밀린 날마다 새벽에 거짓 안심 알림이 왔다 (2026-08-29 검토). 조용히 닫는다
const 묵은발행 = (x, 오늘) => x.갈래 === '발행' && !String(x.열쇠 ?? '').startsWith(`발행:${오늘}`)

// 견준 결과가 있으면 기록하고 알린다(없으면 조용히). 새 상태를 돌려준다 — 호출부가 상태[자리] 에 담는다
async function 견줘서기록알림(머리글, 옛문제들, 새문제들, { 뿌리, 지금, 기록계정, 알림, 알림계정 }) {
  const { 생김, 고쳐짐: 다고쳐짐 } = 견주기(옛문제들, 새문제들)
  const 오늘 = 날짜글(new Date(지금))
  const 고쳐짐 = 다고쳐짐.filter((x) => !묵은발행(x, 오늘))
  if (생김.length || 고쳐짐.length) {
    const 줄들 = [...생김.map((x) => 기록줄('생김', 지금, x)), ...고쳐짐.map((x) => 기록줄('고쳐짐', 지금, x))]
    await 기록더하기(기록계정, 줄들, 뿌리)
    // ⚠️ 알리기 는 실패해도 안 던지고 { 보냄:false } 를 돌려준다. 그 값을 안 보면 상태가 「알렸다」로
    // 넘어가 다음 판부터 침묵한다 — 마지막 파수꾼의 유일한 바깥 통로가 한 번 끊기면 그 사건은
    // 영영 안 알려진다. 못 보냈으면 던진다. 상태를 안 넘겨야 다음 판이 다시 재고 다시 보낸다
    const 결과 = await 알림(글월만들기(머리글, 생김, 고쳐짐), 알림계정)
    if (결과 && 결과.보냄 === false) {
      console.error(`‼️  점검 — 텔레그램으로 못 보냈습니다 (${결과.까닭})`)
      throw new Error(`알림을 못 보냈습니다: ${결과.까닭}`)
    }
  }
  return 새문제들
}

// 한 계정(또는 전체)이 죽어도 판을 계속 돌리려고 부른다 — 실패는 삼키지 않고 흔적을 남긴다.
// (점검.sh 가 stderr 를 logs/점검.log 로 받는다.) 실패하면 상태[자리] 는 안 건드린다 —
// 옛 상태가 그대로 남아야 다음 판이 다시 재 보고, 이미 알린 다른 자리가 중복 알림을 안 낸다
async function 한자리(이름표, 자리, 실행할것) {
  try {
    return await 실행할것()
  } catch (e) {
    console.error(`‼️  점검 — ${이름표 || '(전체)'} 자리(${자리 || 'main'})가 죽었습니다: ${e?.message}`)
    return undefined
  }
}

export async function 한판({ 뿌리, 계정들, 지금 = Date.now(), 실행, 런치폴더, 알림 }) {
  // 자리마다 제 파일이다 (2026-08-29). 한 자리를 다 재면 **그 자리 파일을 바로 쓴다** —
  // 옛 한 파일 시절에는 마지막에 한 번 몰아 썼고, 죽은 자리가 있으면 그 판독까지 흔들렸다.
  // 죽은 자리는 파일을 아예 안 건드린다. 옛 판독이 그대로 남아 다음 판이 이어서 견준다
  const 마치기 = async (자리, 결과) => {
    if (결과 === undefined) return // 죽은 자리 — 남의 판독을 지우지 않는다
    await 상태쓰기(자리, 결과, 뿌리)
  }

  // 계정을 안 가리는 자동화(헬스체크·조회수알리미·감시)는 한 번만 잰다 — 계정마다 되풀이하지 않는다.
  // 전체자리 에 담는다 — 옛 '' 는 첫 계정과 같은 열쇠라 둘이 서로를 덮어쓰며 알림 폭풍이 났다
  await 마치기(전체자리, await 한자리('전체', 전체자리, async () => {
    const 옛것 = await 상태읽기(전체자리, 뿌리)
    const 전체새문제들 = await 전체점검({ 뿌리, 지금, 실행, 런치폴더, 계정들 })
    return 견줘서기록알림('🔎 점검 — 전체(계정 공통)', 옛것, 전체새문제들,
      { 뿌리, 지금, 기록계정: 전체자리, 알림, 알림계정: '전체' })
  }))

  for (const 계정 of 계정들) {
    await 마치기(계정, await 한자리(계정, 계정, async () => {
      const 옛것 = await 상태읽기(계정, 뿌리)
      const 새문제들 = await 계정점검(계정, { 뿌리, 지금, 실행, 런치폴더 })
      const { 별칭 } = await 정보(계정, 뿌리)
      const 이름표 = 계정 ? `${별칭}(${계정})` : 별칭
      return 견줘서기록알림(`🔎 점검 — ${이름표}`, 옛것, 새문제들,
        { 뿌리, 지금, 기록계정: 계정, 알림, 알림계정: 계정 })
    }))
  }
}

if (import.meta.main) {
  const 뿌리 = process.cwd()
  const 장부 = await 장부읽기(뿌리)
  const 계정들 = Object.keys(장부)
  const 런치폴더 = join(homedir(), 'Library', 'LaunchAgents')

  // 잠잠시간을 0 으로 둔다 — 반복 억제는 견주기 가 이미 한다. 잠잠시간까지 걸면 「돌아왔습니다」가 눌린다
  await 한판({
    뿌리, 계정들, 런치폴더,
    알림: (글, 계정) => 알리기(글, { 종류: `점검-${계정 || 'main'}`, 잠잠시간: 0 }),
  })
}
