// ⚠️ **한 편만 재면 안 된다** — 멀쩡한 쿠키로 48편을 재 보니 그중 한 편이 null 이었다 (실측).
// 잰 값은 버리지 않는다. 여기서 채운 조회수는 뒤에서 그대로 쓰인다
export const 표본수 = 3

export async function 조회수읽히나(글들, { cookie, 채우기 = 상세채우기 } = {}) {
  const 표본 = (글들 ?? []).slice(0, 표본수)
  if (!표본.length) return false
  await 채우기(표본, { cookie })
  return 표본.some((p) => typeof p.조회수 === 'number' && p.조회수 > 0)
}

// 「재추천」을 누를 때마다 **다른 검색어**를 써야 한다.
// 돌려쓰기는 시각으로 자리를 정해서, 같은 시각에 다시 부르면 같은 단어가 나온다.
// 그것을 모르고 십 분 사이에 세 번 돌렸더니 그 네 단어가 조여 후보가 스물셋 → 넷으로 줄었다 (실측).
// 그래서 부를 때마다 자리를 밀어 준다. 검색어 23개에 한 번에 4개면 다섯 번까지는 안 겹친다
export function 검색어고르기(풀, 때, 자리 = 0) {
  const 돈것 = 돌려쓰기(풀, 때)
  const 시작 = ((자리 % 돈것.length) + 돈것.length) % 돈것.length
  return [...돈것.slice(시작), ...돈것.slice(0, 시작)].slice(0, 한도.검색어)
}

// ① 검색 → ② 작성자별 묶기 → ③ 프로필(팔로워 + 그 계정 글) → ④ 반응 좋은 글의 조회수 → ⑤ 확산 상위 계정
