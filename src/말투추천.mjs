// 같은 작성자의 글을 한 덩이로 묶는다. 계정을 고르는 것이지 글을 고르는 것이 아니다
export function 작성자별로묶기(글들) {
  const 통 = new Map()
  for (const p of 글들) {
    if (!p?.작성자) continue
    if (!통.has(p.작성자)) 통.set(p.작성자, [])
    통.get(p.작성자).push(p)
  }
  return 통
}

// 반응 = 좋아요 + 댓글 + 리포스트 + 공유. 넷 다 검색·프로필 문서에 이미 들어 있어 공짜다.
// ⚠️ **저장 수는 못 받는다.** 스레드가 남의 글의 저장 수를 아무 데도 안 준다 (실측).
// 없는 값을 0 으로 두고 세면 저장이 많은 글이 손해를 본다 — 그래서 아예 세지 않는다
export function 반응점수(글) {
  return ['좋아요', '댓글', '리포스트', '공유']
    .reduce((합, 칸) => 합 + (typeof 글?.[칸] === 'number' ? 글[칸] : 0), 0)
}

// 계정마다 조회수를 잴 글을 고른다.
// ⚠️ **검색에 걸린 글 한 편은 반드시 넣는다.** 그 글이 이 계정을 이 분야로 데려온 근거다.
// 반응만 보고 고르면 프로필의 잡담 글이 세 칸을 다 차지하고, 그러면 아래 분야 필터가
// "이 계정은 요리 계정이 아니다" 로 읽어 **멀쩡한 계정이 통째로 떨어진다** (실측 — 4개 중 0개가 남았다)
export function 읽을글고르기(검색글, 모든글, 몇편) {
  const 처음 = (검색글 ?? []).slice(0, 1)
  const 나머지 = (모든글 ?? []).filter((p) => !처음.includes(p))
    .sort((a, b) => 반응점수(b) - 반응점수(a))
  return [...처음, ...나머지].slice(0, 몇편)
}

// 검색에서 걷은 글과 프로필에서 걷은 글을 한 덩이로 만든다. 같은 글은 code 로 가린다.
// 검색으로 받은 값을 프로필 값이 덮지 않게 한다 — 상세로 이미 채운 조회수가 지워진다
export function 글합치기(먼저, 나중) {
  const 통 = new Map()
  for (const p of [...(먼저 ?? []), ...(나중 ?? [])]) {
    if (!p?.code) continue
    if (!통.has(p.code)) 통.set(p.code, p)
  }
  return [...통.values()]
}

// 확산 = 조회수 ÷ 팔로워. 이 저장소가 이미 쓰는 잣대 그대로다 (src/score.mjs).
// 계정 하나의 확산은 **최근 글들의 중간값**으로 본다 — 평균은 대박 한 편에 통째로 끌려간다
export function 계정확산(글들, 팔로워) {
  if (!(팔로워 > 0)) return null
  const 값 = 글들.map((p) => p.조회수).filter((v) => typeof v === 'number' && v > 0)
    .map((v) => v / 팔로워).sort((a, b) => a - b)
  if (!값.length) return null
  return Number(값[Math.floor(값.length / 2)].toFixed(2))
}

// 팔로워가 너무 적으면 확산이 폭발한다 — 팔로워 4명이 조회 655 로 163배를 찍은 적이 있다 (실측).
// 문턱은 점수 설정과 같은 것을 쓴다. 두 곳이 어긋나면 안 된다
export function 쓸만한계정인가(팔로워, 확산, 문턱 = 한도.최소팔로워) {
  return typeof 팔로워 === 'number' && 팔로워 >= 문턱 && typeof 확산 === 'number' && 확산 > 0
}

