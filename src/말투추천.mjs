export function 결과다듬기(원시, 언어 = '한국어') {
  let j
  try { j = JSON.parse(원시) } catch { throw new Error(`LLM 이 JSON 이 아닌 것을 돌려줬다: ${String(원시).slice(0, 120)}`) }
  const 정체성 = String(j.정체성 ?? '').trim()
  const 말투 = String(j.말투 ?? '').trim()
  if (!정체성 || !말투) throw new Error('추천이 비었다. 「재추천」으로 다시 해 보세요')
  const 표현들 = (Array.isArray(j.자주쓰는표현) ? j.자주쓰는표현 : [])
    .map((v) => String(v).trim()).filter(Boolean).slice(0, 6)
  const 뜻 = {
    정체성: String(j.정체성뜻 ?? '').trim(),
    말투: String(j.말투뜻 ?? '').trim(),
    표현: (Array.isArray(j.표현뜻) ? j.표현뜻 : []).map((v) => String(v).trim()).slice(0, 6).join(', '),
  }
  // 그 언어로 받았으면 뜻이 반드시 있어야 한다. 못 읽는 말이 자기 계정 말투로 박히면 안 된다
  if (언어 !== '한국어' && !(뜻.정체성 && 뜻.말투)) {
    throw new Error('한국어 뜻이 안 왔다 — 무슨 말투인지 못 읽는 채로 넣을 수 없다. 「다시 추천」을 눌러 주세요')
  }
  // 이모지 규칙이 안 오면 기본값을 준다 — 빈 칸이면 프롬프트에서 그 줄이 통째로 빠진다
  const 이모지 = String(j.이모지 ?? '').trim() || '맨 끝에 딱 하나만. 음식과 어울리는 것으로.'
  return {
    정체성,
    말투,
    표현: 표현들.join(', '),
    이모지,
    뜻: 언어 === '한국어' ? null : 뜻,
    왜: String(j.왜 ?? '').trim(),
  }
}

export async function 말투추천(분야, {
  cookie, 물어보기: 묻기 = 물어보기, 알림 = () => {}, 찾기 = 퍼지는계정찾기, 때 = new Date(), 자리 = 0,
  언어 = '한국어', 멈췄나 = () => {}, 빌릴쿠키들 = [], 빌렸다 = () => {},
} = {}) {
  const 계정들 = await 찾기(분야, { 언어, cookie, 알림, 때, 자리, 멈췄나, 빌릴쿠키들, 빌렸다 })
  // LLM 을 부르기 전에 한 번 더 본다. 중단을 눌렀는데 돈을 쓰면 안 된다
  멈췄나()
  알림(`계정 ${계정들.length}개의 글을 읽고 말투를 뽑는 중... (30초쯤)`)

  const { system, user } = 지시문만들기(분야, 읽을거리만들기(계정들), 언어)
  // 지시와 남의 글을 갈라 넘긴다
  const 원시 = await 묻기({ system, user })

  return {
    ...결과다듬기(원시, 언어),
    // 「바이럴 글 예시」 칸에 그대로 채울 글이다. LLM 이 지어낸 것이 아니라 실제로 잘 퍼진 남의 글이다
    예시들: 예시고르기(계정들, 고르기(분야, 언어).분야팩),
    // 어느 계정을 보고 뽑았는지 숨기지 않는다. 사용자가 직접 열어 볼 수 있어야 한다
    본계정들: 계정들.map((c) => ({ 작성자: c.작성자, 팔로워: c.팔로워, 확산: c.확산 })),
  }
}
