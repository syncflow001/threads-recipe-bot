// 날마다 계정마다 「조용히 덜 퍼지고 있나」를 밖에서 재서 장부에 쌓고, 나빠질 때만 알린다.
// ⚠️ 단정하지 않는다 — 진짜 확인은 앱의 「계정 상태」 화면뿐이다 (docs/섀도우밴-대응.md)
import { 한판 as 계정한판, 장부읽기 } from './섀도우밴.mjs'
import { 계정목록 } from './계정.mjs'
import { 알리기 } from './알림.mjs'

// 어제와 견줘 **나빠졌을 때만** 말한다. 날마다 같은 말을 보내면 사람이 안 읽게 된다.
// ⚠️ 「못잼」은 등급이 아니라 **모름**이다. 순위에 넣으면 「못잼 → 괜찮음」이 나빠짐으로 읽혀
// 계정이 멀쩡해진 날에 본문이 텅 빈 ⚠️ 경고가 나간다 (2026-08-31 검수에서 잡혔다).
// 「덜잼」도 마찬가지로 모름 쪽이다
const 순위 = { 괜찮음: 0, 주의: 1, 의심: 2 }
const 아는등급 = (등급) => (등급 in 순위 ? 등급 : null)

export async function 한판({ 뿌리 = process.cwd(), 계정들, 알림 = () => {}, ...옵션 } = {}) {
  const 것들 = []
  for (const 계정 of 계정들) {
    // 한판() 이 쌓기 **전에** 읽는다 — 그래야 마지막 줄이 어제 것이다
    const 어제줄 = Promise.resolve((await 장부읽기(계정, 뿌리, 1))[0] ?? null)
    const 어제등급 = 아는등급((await 어제줄)?.등급)
    const 줄 = await 계정한판(계정, { 뿌리, ...옵션 })
    것들.push(줄)
    const 이름 = 계정 || '첫 계정'

    // 기준선을 못 믿겠으면 따로 말한다. **등급과 다른 이야기다** — 「덜 퍼지고 있다」가 아니라
    // 「우리 자가 틀렸으니 다시 재야 한다」다. 어제도 같은 말이었으면 다시 안 한다
    const 어제탈 = (await 어제줄)?.기준선탈 ?? null
    if (줄.기준선탈 && 줄.기준선탈 !== 어제탈) {
      알림(`📏 [${이름}] 도달 기준선을 못 믿겠습니다\n· ${줄.기준선탈}\n` +
        `그동안 도달 신호를 안 씁니다. 「점검」 쪽 도달 칸에서 **기준선 다시 찍기** 를 눌러 주세요.`, 계정)
    }

    const 오늘등급 = 아는등급(줄.등급)
    if (!오늘등급) continue // 못 쟀거나 덜 쟀으면 아무 말도 안 한다
    if (어제등급 == null || 순위[오늘등급] > 순위[어제등급]) {
      if (오늘등급 === '괜찮음') continue // 좋아진 것을 나빠짐으로 말하지 않는다
      const 몸 = 줄.신호들.filter((s) => s.빛 !== '초록').map((s) => `· ${s.이름} — ${s.말}`).join('\n')
      알림(`⚠️ [${이름}] 덜 퍼지고 있는 것 같습니다 (${줄.등급})\n${몸}\n` +
        `앱에서 설정 → 계정 → 「계정 상태」 를 확인해 주세요.`, 계정)
    } else if (어제등급 != null && 순위[오늘등급] < 순위[어제등급] && 오늘등급 === '괜찮음') {
      알림(`✅ [${이름}] 돌아왔습니다 — 노출이 정상으로 보입니다.`, 계정)
    }
  }
  return 것들
}

if (import.meta.main) {
  const 뿌리 = process.cwd()
  const 계정들 = await 계정목록(뿌리)
  const 것들 = await 한판({
    뿌리, 계정들,
    알림: (글, 계정) => 알리기(글, { 종류: `섀도우밴-${계정 || 'main'}`, 잠잠시간: 0 }),
  })
  for (const r of 것들) {
    console.log(`${(r.계정 || '첫 계정').padEnd(20)} ${r.등급.padEnd(6)} ` +
      r.신호들.map((s) => `${s.이름} ${s.빛}`).join(' · '))
  }
}
