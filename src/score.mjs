// 게시물에 등급을 매긴다 — 문턱을 먼저 넘긴 뒤에만 비율로 줄을 세운다

// 표본 76개로 정한 값이다 (docs/threads-sample-2026-08-18.json).
// 더 모으면 조정한다. 그래서 상수로 빼 둔다.
export const 설정 = {
  // 문턱이 없으면 기준이 거꾸로 돈다 — 조회 1회에 좋아요 1개인 글이 100% 로 1등을 한다.
  // 비율과 조회수의 상관계수가 -0.177 이었다. 분모가 작으면 비율이 폭발하기 때문이다.
  최소조회수: 5000,
  구간: [
    ['플래티넘', 0.02],
    ['골드', 0.012],
    ['실버', 0.006],
    ['브론즈', 0],
  ],
}

// 조회수가 없으면(로그인 없음·추출 실패) 등급을 지어내지 않는다. null 을 돌려준다.
export function 등급(게시물, 옵션 = 설정) {
  const { 조회수, 좋아요 } = 게시물
  if (typeof 조회수 !== 'number' || 조회수 <= 0) return null
  if (조회수 < 옵션.최소조회수) return { 등급: '미달', 비율: 좋아요 / 조회수 }
  const 비율 = 좋아요 / 조회수
  const 이름 = 옵션.구간.find(([, 하한]) => 비율 >= 하한)?.[0] ?? '브론즈'
  return { 등급: 이름, 비율 }
}

// 등급 매기고 좋은 순으로 세운다. 미달과 등급없음은 뒤로 보낸다.
export function 줄세우기(목록, 옵션 = 설정) {
  const 순위 = { 플래티넘: 0, 골드: 1, 실버: 2, 브론즈: 3, 미달: 4 }
  return 목록
    .map((p) => ({ ...p, ...(등급(p, 옵션) ?? { 등급: '알수없음', 비율: null }) }))
    .sort((a, b) => (순위[a.등급] ?? 9) - (순위[b.등급] ?? 9) || (b.비율 ?? -1) - (a.비율 ?? -1))
}
