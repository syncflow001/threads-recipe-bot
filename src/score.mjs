// 게시물에 등급을 매긴다 — 확산(조회수÷팔로워)이 1차 지표다

// ⚠️ 확산은 **본문 글 기준이다.** 글타래(레시피가 실린 답글)의 조회수로 재지 않는다.
// 답글은 본문보다 훨씬 적게 읽히므로, 답글로 재면 잘 퍼진 글까지 전부 바닥으로 깔린다.
//
// 문턱이 없으면 기준이 거꾸로 돈다 — 팔로워 4명짜리 글이 조회 655 로 163배를 찍어 1등을 했다 (실측).
// 좋아요÷조회수 도 같은 병을 앓는다. 조회 1회에 좋아요 1개면 100% 다.
// 그래서 분모마다 문턱을 둔다.
export const 설정 = {
  최소조회수: 2000,
  최소팔로워: 50,
  // 확산 구간. 홈에서 걷은 표본 179개로 정했다 (2026-08-20). 더 모으면 조정한다
  확산구간: [
    ['플래티넘', 20],
    ['골드', 10],
    ['실버', 5],
    ['브론즈', 2],
  ],
  // 팔로워를 못 받았을 때 쓰는 예전 기준 (좋아요÷조회수). 검색 경로가 아직 이걸 탄다
  비율구간: [
    ['플래티넘', 0.02],
    ['골드', 0.012],
    ['실버', 0.006],
    ['브론즈', 0],
  ],
}

const 고르기 = (구간, 값) => 구간.find(([, 하한]) => 값 >= 하한)?.[0] ?? '미달'

// 조회수가 없으면(로그인 없음·추출 실패) 등급을 지어내지 않는다. null 을 돌려준다.
export function 등급(게시물, 옵션 = 설정) {
  const { 조회수, 좋아요, 팔로워 } = 게시물
  if (typeof 조회수 !== 'number' || 조회수 <= 0) return null

  const 비율 = 좋아요 / 조회수
  const 확산 = typeof 팔로워 === 'number' && 팔로워 > 0 ? Number((조회수 / 팔로워).toFixed(2)) : null

  if (조회수 < 옵션.최소조회수) return { 등급: '미달', 비율, 확산 }

  // 팔로워를 알면 확산으로 매긴다. 모르면 예전 기준으로 돌아간다 —
  // 검색 경로는 팔로워를 안 받아 오므로 여기서 막으면 그 길이 통째로 죽는다
  if (확산 !== null && 팔로워 >= 옵션.최소팔로워) {
    return { 등급: 고르기(옵션.확산구간, 확산), 비율, 확산 }
  }
  return { 등급: 고르기(옵션.비율구간, 비율), 비율, 확산 }
}

// 등급 매기고 좋은 순으로 세운다. 미달과 등급없음은 뒤로 보낸다.
// 같은 등급이면 확산이 큰 쪽이 앞이고, 확산을 모르면 비율로 가른다
export function 줄세우기(목록, 옵션 = 설정) {
  const 순위 = { 플래티넘: 0, 골드: 1, 실버: 2, 브론즈: 3, 미달: 4 }
  return 목록
    .map((p) => ({ ...p, ...(등급(p, 옵션) ?? { 등급: '알수없음', 비율: null, 확산: null }) }))
    .sort((a, b) =>
      (순위[a.등급] ?? 9) - (순위[b.등급] ?? 9) ||
      (b.확산 ?? -1) - (a.확산 ?? -1) ||
      (b.비율 ?? -1) - (a.비율 ?? -1))
}
