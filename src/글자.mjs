// 여러 분야가 함께 쓰는 글자 다듬기 — 폭 없는 문자를 씻어낸다

// 스레드 글에는 폭 없는 문자가 게시물당 3~25개씩 섞여 있다 (이모지 변형 선택자, 제로폭 공백).
// 자바스크립트의 \s 는 이것들을 공백으로 치지 않아서, "1<제로폭>모" 는 분량으로 안 잡힌다.
// 씻어내지 않으면 멀쩡한 글이 통째로 걸러진다. 분야마다 베껴 두면 한쪽만 고쳐져 어긋나므로
// 여기 한 곳에 둔다.
// 이스케이프 꼴로 적는다 — 눈에 안 보이는 글자를 소스에 그대로 박으면 아무도 못 고친다
export const 씻기 = (s) => String(s ?? '').replace(/[\u200B-\u200D\uFEFF\u2060\uFE0E\uFE0F]/g, '')

// 견줄 때는 공백까지 걷어낸다. 스레드가 줄바꿈과 띄어쓰기를 제멋대로 접기 때문이다
export const 붙이기 = (s) => 씻기(s).replace(/\s+/g, '')
