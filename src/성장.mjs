export function 중앙값(숫자들) {
  const 성한것 = (숫자들 ?? []).filter((n) => Number.isFinite(n)).sort((a, b) => a - b)
  if (!성한것.length) return null
  const 가운데 = Math.floor(성한것.length / 2)
  return 성한것.length % 2
    ? 성한것[가운데]
    : (성한것[가운데 - 1] + 성한것[가운데]) / 2
}

// 그대로면 50 · 두 배면 100 · 반토막이면 0. 늘고 주는 것이 대칭이라 눈이 안 속는다
export function 점수(최근, 그전) {
  if (!Number.isFinite(최근) || !Number.isFinite(그전) || 그전 <= 0) return null
  if (최근 <= 0) return 0
  return Math.max(0, Math.min(100, Math.round(50 + 50 * Math.log2(최근 / 그전))))
}

// 다 자란 글만 최근 순으로. 갓 올린 글은 조회가 아직 안 붙어 견주면 거짓 하락이 난다
export function 익은글들(성적것들, 지금 = Date.now()) {
  return (성적것들 ?? [])
    .filter((g) => g.올린때 && 지금 - Date.parse(g.올린때) >= 익는시간)
    .filter((g) => Number.isFinite(g.지금?.조회수))
    .sort((a, b) => String(b.올린때).localeCompare(String(a.올린때)))
}

const 합 = (것, 칸들) => 칸들.reduce((ㅅ, 칸) => ㅅ + (Number(것?.[칸]) || 0), 0)
export const 반응수 = (것) => 합(것, ['좋아요', '답글', '리포스트', '인용', '공유'])
export const 확산수 = (것) => 합(것, ['리포스트', '인용', '공유'])

// 최근 무리와 그 전 무리로 가른다. 둘 다 최소편수를 넘어야 견준다
export function 두무리(글들) {
  const 반 = Math.floor(글들.length / 2)
  if (반 < 최소편수) return null
  return {
    최근: 글들.slice(0, Math.min(반, 무리최대)),
    그전: 글들.slice(반, 반 + Math.min(반, 무리최대)),
  }
}

// 팔로워 — 최근 이레에 는 만큼과 그 전 이레에 는 만큼을 견준다.
// 늘어난 「양」을 견준다. 총량을 견주면 팔로워가 많은 계정은 언제나 100 이 된다
export function 팔로워기둥(줄들, 지금 = Date.now()) {
  const 성한것 = (줄들 ?? []).filter((r) => Number.isFinite(r.수))
    .sort((a, b) => a.날.localeCompare(b.날))
  if (성한것.length < 3) return { 점수: null, 까닭: '측정한 날이 아직 며칠 안 됐어요' }

  const 날글 = (t) => new Date(t).toLocaleDateString('sv-SE')
  const 이레전 = 날글(지금 - 7 * 86400000)
  const 두레전 = 날글(지금 - 14 * 86400000)
  const 고르기 = (날) => {
    const 앞선것 = 성한것.filter((r) => r.날 <= 날)
    return 앞선것.length ? 앞선것[앞선것.length - 1] : null
  }
  const 끝 = 성한것[성한것.length - 1]
  const 중간 = 고르기(이레전)
  const 처음 = 고르기(두레전)
  if (!중간 || !처음 || 처음.날 === 중간.날 || 중간.날 === 끝.날) {
    return { 점수: null, 까닭: '2주는 모여야 비교할 수 있어요' }
  }

  const 최근늚 = 끝.수 - 중간.수
  const 그전늚 = 중간.수 - 처음.수
  // 그 전 이레에 하나도 안 늘었으면 나눌 수가 없다. 지금 늘고 있으면 좋은 것으로 본다
  if (그전늚 <= 0) {
    return {
      점수: 최근늚 > 0 ? 75 : 50,
      최근값: 최근늚, 그전값: 그전늚,
      까닭: 최근늚 > 0 ? '지난주엔 안 늘었는데 이번 주에 늘었어요' : '2주 내내 안 늘었어요',
    }
  }
  return { 점수: 점수(최근늚, 그전늚), 최근값: 최근늚, 그전값: 그전늚 }
}

// 꾸준함 — 최근 이레 성공률과 그 전 이레 성공률
export function 꾸준함기둥(줄들) {
  const 셈 = (묶음) => {
    const 칸 = 묶음.flatMap((줄) => 줄.칸 ?? []).filter((c) => c.상태 !== '아직')
    return 칸.length ? 칸.filter((c) => c.상태 === '올림').length / 칸.length : null
  }
  const 다 = (줄들 ?? []).slice(0, 14) // 격자는 최근이 앞이다
  if (다.length < 8) return { 점수: null, 까닭: '2주는 모여야 비교할 수 있어요' }
  const 최근 = 셈(다.slice(0, 7))
  const 그전 = 셈(다.slice(7, 14))
  if (최근 === null || 그전 === null) return { 점수: null, 까닭: '지나간 발행 횟수가 모자라요' }
  // 성공률은 0~1 이라 로그 환산이 거칠다. 그 전이 0 이면 지금이 성한지만 본다
  if (그전 === 0) return { 점수: 최근 > 0 ? 75 : 50, 최근값: 최근, 그전값: 그전 }
  return { 점수: 점수(최근, 그전), 최근값: 최근, 그전값: 그전 }
}

// ★ 지수만 크게 보여 주면 과신을 부른다. 글 세 편씩으로 낸 97 과
//   서른 편씩으로 낸 97 은 같은 말이 아니다. 얼마나 믿을 값인지를 함께 낸다.
//   ⚠️ 지수 자체를 표본으로 깎지는 않는다. 설명 못 하는 숫자를 만들면 안 된다
export function 믿음정도({ 센기둥, 무리크기, 판수 }) {
  if (!센기둥) return { 결: '없음', 말: '아직 측정한 게 없어요' }
  const 까닭 = []
  if (무리크기 < 5) 까닭.push(`앞뒤 ${무리크기}개씩만 비교했어요`)
  if (센기둥 <= 2) 까닭.push(`항목 ${센기둥}개만 반영됐어요`)
  if (판수 <= 1) 까닭.push('아직 한 번밖에 측정 안 했어요')
  if (!까닭.length) return { 결: '높음', 말: '데이터가 충분해요' }
  const 결 = (무리크기 < 5 && 판수 <= 1) || 센기둥 <= 2 ? '낮음' : '보통'
  return { 결, 말: 까닭.join(' · ') }
}

export const 등급 = (지수) => {
  if (지수 == null) return { 이름: '아직 알 수 없어요', 결: '모름' }
  if (지수 >= 70) return { 이름: '자라고 있습니다', 결: '좋음' }
  if (지수 >= 57) return { 이름: '조금 자라고 있습니다', 결: '좋음' }
  if (지수 >= 43) return { 이름: '제자리입니다', 결: '보통' }
  if (지수 >= 30) return { 이름: '조금씩 떨어지고 있습니다', 결: '나쁨' }
  return { 이름: '계속 떨어지고 있습니다', 결: '나쁨' }
}

