// 「왜 안 올라갔나」에 한 번에 답한다 — 읽기만 하고 아무것도 고치지 않는다
import { readFile, stat } from 'node:fs/promises'
import { 꺼내기, 읽기 as 보관함읽기 } from './보관함.mjs'
import { join } from 'node:path'
import { homedir } from 'node:os'
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'

const 실행 = promisify(execFile)
import { 멈춤인가 } from './멈춤.mjs'
import { 막힌글들 } from './관문.mjs'
import { 시각표찾기 } from './대시보드.mjs'
import { 미디어뿌리, 계정길 } from './계정.mjs'

// 됨: true 괜찮음 · false 손봐야 함 · null 확인 못 함.
// null 을 false 로 뭉뚱그리면 갓 만든 계정이 전부 빨갛게 뜨고, 그러면 아무도 안 본다
// 풀이 = 이 줄이 무슨 뜻인지 한 마디. 사용자가 비개발자라 이름만으로는 알 수 없다 —
// 「멈춤 파일 · 없음」을 보고 좋은 것인지 나쁜 것인지 알 도리가 없었다 (사용자가 짚었다)
const 항목 = (이름, 됨, 지금, 조치 = null, 풀이 = '') => ({ 이름, 됨, 지금, 조치, 풀이 })

const 있나 = async (곳) => !!(await stat(곳).catch(() => null))

const 필수열쇠 = ['THREADS_ACCESS_TOKEN', 'THREADS_USER_ID']

// 값이 있음 = 그 키 줄이 있고 비어 있지 않다. 정의됨 = 그 키 줄이 있다(값이 비었어도).
// 값은 절대 읽어서 보여주지 않는다 — 있다/없다만 본다
const 값있음 = (글, k) => !!(글 && new RegExp(`^${k}=.+`, 'm').test(글))
const 정의됨 = (글, k) => !!(글 && new RegExp(`^${k}=`, 'm').test(글))

// 자동발행.sh 가 실제로 켜는 순서와 같게 본다 — --env-file=.env.local --env-file=.env.<계정>.
// 계정 파일이 그 키를 언급하면(빈 값이어도) 그 파일이 이기고, 언급이 없으면 .env.local 값을 물려받는다.
// 이 순서를 안 지키면 .env.local 이 채워 주는 키를 계정 파일만 보고 「없다」고 잘못 판정한다
const 합쳐값있음 = (계정글, 로컬글, k) => (정의됨(계정글, k) ? 값있음(계정글, k) : 값있음(로컬글, k))

export async function 진단(계정, { 뿌리 = process.cwd(), 지금 = Date.now() } = {}) {
  const 것들 = []

  // 1) 멈춤
  const 멈춤 = await 멈춤인가(계정, 뿌리)
  것들.push(멈춤.멈춤
    ? 항목('자동 발행 스위치', false, `꺼져 있습니다 (${멈춤.어느것} · ${멈춤.때?.slice(0, 16).replace('T', ' ')})`,
      '설정 화면 맨 위의 「다시 켜기」 를 누르세요', '꺼 두면 이 계정은 한 글자도 안 올라갑니다')
    : 항목('자동 발행 스위치', true, '켜져 있습니다', null, '꺼 두면 이 계정은 한 글자도 안 올라갑니다'))

  // 2) 시각표
  const 시각표 = await 시각표찾기(계정).catch(() => null)
  것들.push(시각표
    ? 항목('올리는 시각', true, `${시각표.칸들.map((c) => `${c.시}시 ${c.분}분`).join(' · ')}`, null,
      '맥이 이 시각마다 저절로 한 편씩 올립니다')
    : 항목('올리는 시각', false, '정해져 있지 않습니다', '설정 화면에서 자동 발행을 켜세요',
      '시각이 없으면 저절로 올라가는 일이 아예 없습니다'))

  // 3) 마지막 발행 — 한 번도 안 돈 것은 실패가 아니다
  const 마지막파일 = join(뿌리, 'logs', 계정 ? `마지막발행-${계정}.txt` : '마지막발행.txt')
  const 적힌것 = await readFile(마지막파일, 'utf8').then((s) => Number(s.trim())).catch(() => NaN)
  if (!Number.isFinite(적힌것) || 적힌것 <= 0) {
    것들.push(항목('마지막으로 올린 때', null, '아직 한 번도 올린 적이 없습니다', null,
      '갓 만든 계정이면 정상입니다'))
  } else {
    const 지난시간 = Math.round((지금 - 적힌것 * 1000) / 3600000)
    것들.push(지난시간 > 26
      ? 항목('마지막으로 올린 때', false, `${지난시간}시간 전`,
        '시각표가 안 돌고 있을 수 있습니다. 맥이 자고 있었는지 보세요',
        '하루가 넘도록 안 올라갔으면 어딘가 막힌 것입니다')
      : 항목('마지막으로 올린 때', true, `${지난시간}시간 전`, null, '하루 안쪽이면 잘 돌고 있는 것입니다'))
  }

  // 4) 열쇠 — 값은 절대 보여주지 않는다. .env.local 과 .env.<계정> 을 합쳐서 본다.
  // 이름 없는 첫 계정은 처음부터 .env.local 하나뿐이라 계정 파일이 없다
  const 로컬글 = await readFile(join(뿌리, '.env.local'), 'utf8').catch(() => null)
  const 계정글 = 계정 ? await readFile(join(뿌리, 계정길(계정, '열쇠.env')), 'utf8').catch(() => null) : null

  if (로컬글 === null && 계정글 === null) {
    것들.push(항목('스레드 출입증', false, '없습니다',
      `${계정 ? `.env.local 이나 ${계정길(계정, '열쇠.env')}` : '.env.local'} 을 만들어야 합니다`,
      '스레드에 글을 올릴 권한입니다. 이게 없으면 못 올립니다'))
  } else {
    const 빠진것 = 필수열쇠.filter((k) => !합쳐값있음(계정글, 로컬글, k))
    것들.push(빠진것.length
      ? 항목('스레드 출입증', false, `${빠진것.join(', ')} 이(가) 비어 있습니다`, '설정 화면 열쇠 칸에서 채우세요',
        '스레드에 글을 올릴 권한입니다. 60일마다 새로 받아야 합니다')
      : 항목('스레드 출입증', true, '있습니다', null,
        '스레드에 글을 올릴 권한입니다. 60일마다 새로 받아야 합니다'))
  }

  // 4-b) 클로드 로그인 — 글을 다시 쓰는 것이 전부 여기 달렸다.
  // 구독이 끊기면 열쇠는 멀쩡한데 한 편도 못 올라간다. 값은 안 보고 파일이 있나만 본다
  // 맥은 열쇠꾸러미(Keychain)에 넣는다. 파일만 보면 늘 「안 됨」이 나온다 (실측).
  // 값은 꺼내지 않는다 — 있나 없나만 묻는다
  const 꾸러미에있나 = await 실행('security',
    ['find-generic-password', '-s', 'Claude Code-credentials', '-w']).then(() => true).catch(() => false)
  const 장부에있나 = await readFile(join(homedir(), '.claude.json'), 'utf8')
    .then((글) => /"oauthAccount"\s*:/.test(글)).catch(() => false)
  const 로그인함 = 꾸러미에있나 || 장부에있나 || !!process.env.CLAUDE_CODE_OAUTH_TOKEN
  것들.push(로그인함
    ? 항목('글 쓰는 AI', true, '로그인되어 있습니다', null,
      '원글을 내 말투로 다시 쓰는 곳입니다')
    : 항목('글 쓰는 AI', false, '로그인이 풀렸습니다',
      '터미널에서 claude 를 열고 /login 을 하세요',
      '원글을 내 말투로 다시 쓰는 곳입니다. 끊기면 한 편도 못 올립니다'))

  // 5) 쿠키 — 없어도 발행은 된다. 조회수만 못 본다. 열쇠와 같은 순서로 합쳐서 본다
  const 쿠키있나 = 합쳐값있음(계정글, 로컬글, 'THREADS_COOKIE')
  것들.push(쿠키있나
    ? 항목('스레드 로그인', true, '되어 있습니다', null,
      '남의 글을 가져오고 조회수를 보는 데 씁니다')
    : 항목('스레드 로그인', null, '안 되어 있습니다', '설정 화면 「열쇠」 에 새 쿠키를 넣어 주세요',
      '없어도 글은 올라갑니다. 대신 남의 글을 못 가져오고 조회수도 못 봅니다'))

  // 6) 후보 — 쓸 글이 없으면 조용히 안 올라간다. 그건 고장이 아니다.
  // ⚠️ 파일에 든 줄 수를 세면 안 된다. 걷어 온 지 오래된 글은 안 꺼내므로
  // 「35편 있습니다」라고 해 놓고 정작 한 편도 못 꺼내는 일이 생긴다 (실측).
  // 꺼내기() 에 물어야 실제로 쓸 수 있는 수가 나온다
  // 등급으로 막지 않는다 (2026-08-25 확정). 여기서 세는 수가 곧 실제로 쓸 수 있는 수다 —
  // 예전에는 계정별 MIN_GRADE 가 이 뒤에서 또 걸러, 「1편 ✓」 라고 해 놓고 한 편도 못 쓴 적이 있다
  const 보관함 = 계정길(계정, '보관함.json')
  const 있나2 = await readFile(join(뿌리, 보관함), 'utf8').then(() => true).catch(() => false)
  const 쓸수있는것 = 있나2
    ? (await 꺼내기({ 파일: join(뿌리, 보관함), 지금 }).catch(() => [])).length
    : null
  const 다합쳐 = 있나2
    ? (await 보관함읽기(join(뿌리, 보관함)).catch(() => [])).length
    : null
  것들.push(쓸수있는것 === null
    ? 항목('모아 둔 글', null, '아직 없습니다', null, '미리 골라 둔 글입니다. 없으면 그때그때 홈을 훑습니다')
    : 쓸수있는것 === 0
      ? 항목('바로 쓸 수 있는 글', false,
        다합쳐 ? `0편 (모아 둔 ${다합쳐}편은 걷어 온 지 오래됐습니다)` : '0편',
        '「발행」 쪽에서 저장소에 글 모으기를 눌러 채우세요',
        '등급은 순서만 정합니다. 0편이면 그 판은 홈을 새로 훑습니다')
      : 항목('바로 쓸 수 있는 글', true,
        `${쓸수있는것}편` + (다합쳐 > 쓸수있는것 ? ` (모아 둔 것은 ${다합쳐}편)` : ''),
        null, '등급 좋은 것부터 꺼내 씁니다. 미달도 맨 뒤 차례로 씁니다'))

  // 7) 막힌 글 — 최근 7일
  const 이레전 = 지금 - 7 * 24 * 3600 * 1000
  const 막힌것 = (await 막힌글들(뿌리, 계정)).filter((b) => Date.parse(b.때) >= 이레전)
  것들.push(막힌것.length
    ? 항목('검사에 걸린 글', null, `최근 7일에 ${막힌것.length}편`, '아래 「막힌 글」 을 열어 왜 걸렸는지 보세요',
      '올리려다 우리 검사에 걸려 멈춘 글입니다. 몇 편은 정상입니다')
    : 항목('검사에 걸린 글', true, '없습니다', null, '올리려다 우리 검사에 걸려 멈춘 글입니다'))

  // 8) 미디어 폴더 — 계정마다 자리가 다르다. 첫 계정만 media/ 이고 나머지는 media/<계정>/ 이다.
  // 여기서 media/ 만 보던 탓에 이름 있는 계정은 늘 「있습니다」로 나왔다 (2026-08-29 실측)
  것들.push(await 있나(join(뿌리, 미디어뿌리(계정)))
    ? 항목('사진 저장 자리', true, '있습니다', null, '내려받은 사진·영상을 두는 곳입니다')
    : 항목('사진 저장 자리', null, '아직 없습니다', null, '첫 판에 저절로 만들어집니다'))

  return 것들
}

// 아홉 줄을 훑어도 「그래서 왜 안 올라갔나」에 답이 안 된다 (사용자가 짚었다).
// 맨 위에 한 줄로 답한다 — 손봐야 할 것이 있으면 그것을, 없으면 없다고 말한다
export function 한줄답(것들 = []) {
  const 나쁨 = 것들.filter((h) => h.됨 === false)
  if (나쁨.length) {
    const 첫 = 나쁨[0]
    return {
      괜찮나: false,
      글: `${첫.이름} 때문에 안 올라갑니다 — ${첫.지금}`,
      조치: 첫.조치 || '설정 화면 「열쇠」 를 살펴보세요',
      더: 나쁨.length > 1 ? `손볼 것이 ${나쁨.length}가지입니다` : '',
    }
  }
  const 모름 = 것들.filter((h) => h.됨 === null && h.조치)
  return {
    괜찮나: true,
    글: '살펴본 것 가운데 고장은 없습니다',
    // 「고장이 없다」와 「글이 올라갔다」는 다른 말이다. 여기서 끊으면 사용자가 헷갈린다
    조치: '글이 안 올라갔다면 그때 올릴 만한 글이 없었다는 뜻입니다. 그건 고장이 아닙니다',
    더: 모름.length ? `${모름.map((h) => h.이름).join(' · ')} 은(는) 한 번 봐 두면 좋습니다` : '',
  }
}
