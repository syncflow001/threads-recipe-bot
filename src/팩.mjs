// 계정이 고른 분야·언어·제휴에 맞는 팩을 골라 **조립해** 준다

// 계정 하나 = 팩 셋의 조합이다 (설계서 §11).
//   언어팩 — 어느 말로 쓰는가, 광고를 어떻게 표기하는가, 분량을 어떻게 적는가
//   분야팩 — 무엇을 쓸 만한 글로 보는가, 글의 뼈대가 무엇인가
//   제휴팩 — 상품을 어디서 찾고 대가성 문구를 뭐라고 적는가
//
// **분야팩은 로직 하나 + 언어별 낱말 하나로 조립한다** (2026-08-26).
//   `분야/요리.mjs`        — 레시피 판정 알고리즘·지시문 조립. 언어와 무관하다. 한 벌뿐
//   `분야/요리/일본어.mjs` — 醤油·大さじ·일본어 지시문. **낱말과 문장만, 함수는 없다**
// 「醤油」는 요리 낱말이면서 일본어 낱말이라 이 교차분은 없앨 수가 없다. 없앨 수 없는 것을
// **데이터로만** 남기고 알고리즘은 한 곳에 모은 것이다 — 베낀 알고리즘이 한쪽만 고쳐져
// 발행 직전에 후보 네 편이 죽은 적이 있다 (2026-08-24, 설계서 §11).
//
// 새 팩을 넣으려면
//   ① 낱말 파일을 하나 만들고 (있는 언어면 그것 하나로 끝난다)
//   ② 아래 목록에 등록하고  ③ src/계정.mjs 에서 `됨: true` 로 바꾼다
// 셋을 다 해야 열린다. 하나만 하면 계정 만들기에서 막히거나 엉뚱한 글이 나간다.

import 요리로직 from './분야/요리.mjs'
import 뷰티로직 from './분야/뷰티.mjs'
import 요리한국어 from './분야/요리/한국어.mjs'
import 요리일본어 from './분야/요리/일본어.mjs'
import 요리영어 from './분야/요리/영어.mjs'
import 뷰티한국어 from './분야/뷰티/한국어.mjs'
import 한국어 from './언어/한국어.mjs'
import 일본어 from './언어/일본어.mjs'
import 영어 from './언어/영어.mjs'
import 쿠팡파트너스 from './제휴/쿠팡파트너스.mjs'
import 제휴없음 from './제휴/없음.mjs'

// 분야마다 로직 하나. 낱말은 `분야/언어` 로 찾는다
const 분야로직들 = { 요리: 요리로직, 뷰티: 뷰티로직 }
const 낱말들 = {
  '요리/한국어': 요리한국어,
  '요리/일본어': 요리일본어,
  '요리/영어': 요리영어,
  '뷰티/한국어': 뷰티한국어,
}
const 언어팩들 = { 한국어, 일본어, 영어 }
const 제휴팩들 = { 쿠팡파트너스, 없음: 제휴없음 }

// 언어를 주면 그 언어로 되는 분야만. 안 주면 어느 언어로든 되는 분야를 겹치지 않게 돌려준다 —
// 같은 분야가 언어마다 있으니 중복을 없애야 한다
export const 있는분야 = (언어) => [...new Set(Object.keys(낱말들)
  .filter((k) => !언어 || k.endsWith(`/${언어}`))
  .map((k) => k.split('/')[0]))]
export const 있는언어 = () => Object.keys(언어팩들)
export const 있는제휴 = () => Object.keys(제휴팩들)
// 어떤 조합이 실제로 되는지. 화면이 이것으로 안내한다
export const 되는조합 = () => Object.keys(낱말들).map((k) => {
  const [분야, 언어] = k.split('/')
  return { 분야, 언어 }
})

// 없으면 던진다. 조용히 다른 팩으로 넘어가면 일본어 계정에서 한국어 글이 나간다 —
// 그 조용한 실패를 없애려고 팩으로 나눈 것이다
export function 고르기(분야, 언어 = '한국어', 제휴 = '없음') {
  const 언어팩 = 언어팩들[언어]
  if (!언어팩) throw new Error(`"${언어}" 언어팩이 아직 없다 (있는 것: ${있는언어().join('·')})`)

  const 낱말 = 낱말들[`${분야}/${언어}`]
  if (!낱말) {
    const 그언어것 = 있는분야(언어)
    throw new Error(그언어것.length
      ? `"${분야} × ${언어}" 팩이 아직 없다 (${언어}로 되는 분야: ${그언어것.join('·')})`
      : `"${언어}" 로 되는 분야가 아직 하나도 없다`)
  }

  const 제휴팩 = 제휴팩들[제휴]
  if (!제휴팩) throw new Error(`"${제휴}" 제휴팩이 아직 없다 (있는 것: ${있는제휴().join('·')})`)

  // 여기서 조립한다. 부르는 쪽(run.mjs·compose.mjs)은 갈라 놓기 전과 똑같은 모양을 받는다
  return { 분야팩: 분야로직들[분야](낱말, 언어팩), 언어팩, 제휴팩 }
}

// 계정정보를 그대로 넘겨 쓰는 짧은 길
export const 계정팩 = (정보) => 고르기(정보?.분야, 정보?.언어, 정보?.제휴)
