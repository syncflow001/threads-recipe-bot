'use client'
// 발행 성공률 카드 — 숫자줄(옛 HTML 1065~1069, JS 2295~2306)
import { 카드, 귀띔 } from '@/components/공용/카드'
import { 숫자줄 } from '@/components/공용/숫자줄'
import type { 발행칸, 발행줄, 발행격자자료 } from '@/components/공용/발행격자'

export type { 발행칸, 발행줄, 발행격자자료 }

export function 발행성공률({ 자료, 에러 }: { 자료?: 발행격자자료; 에러?: unknown }) {
  const 비었나 = 에러 || !(자료?.시각들 ?? []).length
  if (비었나) {
    return (
      <카드 제목="발행 성공률" 넓게>
        <귀띔>위 이력을 상태별로 세어 봤어요.</귀띔>
        <숫자줄 항목={[]} />
      </카드>
    )
  }

  const 줄들 = 자료!.첫판날짜 ? 자료!.줄.filter((줄) => 줄.날짜 >= 자료!.첫판날짜!) : 자료!.줄
  const 잘림 = 자료!.줄.length - 줄들.length
  // 아직 안 지난 칸은 세지 않는다 — 오늘 저녁 몫까지 「못 올림」으로 세면 성적이 늘 나쁘다
  const 다 = 줄들.flatMap((줄) => 줄.칸).filter((c) => c.상태 !== '아직')
  const 셈 = (상태: string) => 다.filter((c) => c.상태 === 상태).length

  return (
    <카드 제목="발행 성공률" 넓게>
      <귀띔>위 이력을 상태별로 세어 봤어요.</귀띔>
      <숫자줄 항목={[
        { 이름: '올림', 값: 셈('올림') },
        { 이름: '못 올림', 값: 셈('못올림') + 셈('기록없음') },
        { 이름: '건너뜀', 값: 셈('건너뜀') },
        { 이름: '실패', 값: 셈('실패') },
        { 이름: '성공률', 값: 다.length ? Math.round((셈('올림') / 다.length) * 100) + '%' : '—' },
        ...(잘림 ? [{
          이름: <>이 계정이 생긴 날<br />그 전 {잘림}일은 세지 않습니다</>,
          값: 자료!.첫판날짜!.slice(5).replace('-', '/'),
        }] : []),
      ]} />
    </카드>
  )
}
