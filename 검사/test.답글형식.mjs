{ // ⑨ 도입 유형에 **한국 표본 갈래**가 들어 있다 (2026-09-02)
  // 전에는 일곱 개가 전부 일본 표본이었다 — 한국 계정의 첫 줄을 일본 자료로 정하고 있었다
  const 것들 = 요리한국어.말투서식['도입 유형']
  const 말들 = 것들.map((v) => v.말).join(' / ')
  for (const [갈래, 낱말] of [['공감', /공감을 구하며/], ['말끊기', /문장을 끊어 연다/],
    ['질문', /곧장 물으며 연다/], ['하소연', /털어놓으며 연다/], ['숫자', /숫자로 못 박으며/]])
    assert.match(말들, 낱말, `도입 유형에 한국 표본의 「${갈래}」 갈래가 없다`)

  // 한국 표본이 절반쯤은 돼야 한다 — 한국 계정 글이다
  const 합 = 것들.reduce((a, b) => a + (b.무게 ?? 1), 0)
  const 한국몫 = 것들.filter((v) => /공감을 구하며|문장을 끊어|곧장 물으며|털어놓으며|숫자로 못 박|저장해 두라고|비법을 알지만/.test(v.말))
    .reduce((a, b) => a + b.무게, 0)
  assert.ok(한국몫 / 합 > 0.35, `한국 표본 몫이 ${(한국몫 / 합 * 100).toFixed(0)}% 뿐이다`)

  // ⚠️ 표본 3편짜리(비법·감춤 6.3배)를 1등으로 올리면 안 된다 — 문서가 못 믿는다고 적었다
  const 비법 = 것들.find((v) => /비법을 알지만/.test(v.말))
  assert.ok(비법.무게 <= 2, `표본 3편짜리 갈래의 무게가 ${비법.무게} 다 — 문서가 못 믿는다고 적었다`)

  // 한 갈래가 판을 지배하면 봇처럼 보인다 (docs/섀도우밴-대응.md §2)
  const 셈 = {}
  for (let i = 0; i < 2000; i++) { const v = 도입고르기(것들, 'C' + i); 셈[v] = (셈[v] ?? 0) + 1 }
  const 최대 = Math.max(...Object.values(셈)) / 2000
  assert.ok(최대 < 0.2, `한 갈래가 ${(최대 * 100).toFixed(0)}% 를 차지한다 — 매번 같은 훅은 봇처럼 보인다`)
  assert.equal(Object.keys(셈).length, 것들.length, '안 뽑히는 갈래가 있다')
  console.log('도입 유형에 한국 갈래가 들어 있고 골고루 뽑힌다 ✓')
}

