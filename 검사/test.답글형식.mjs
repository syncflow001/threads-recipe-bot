  //    `브라우저로답글달기` 가 주제결과를 계산해 놓고 return 에서 빠뜨렸다. 그래서
  //    publish 의 `r.주제결과` 가 늘 undefined 였고, run 의 `if (주제태그 && 주제결과 && …)` 가
  //    한 번도 안 걸렸다 — **브라우저로 나가는 모든 발행에서 이 알림이 죽어 있었다.**
  //    위의 글자 검사들은 셋 다 초록이었다. 문구만 보면 흐름을 못 잡는다
  const 답글 = readFileSync('src/브라우저답글.mjs', 'utf8')
  const 몸통 = 답글.slice(답글.indexOf('export async function 브라우저로답글달기'))
  assert.match(몸통, /const 주제결과 =/, '주제결과를 재는 자리가 없다')
