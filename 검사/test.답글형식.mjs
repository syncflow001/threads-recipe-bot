{ // ⑤ 주제 태그 — 「커뮤니티 또는 주제」 칸에 「광고」를 넣는다 (2026-09-02)
  const { 주제붙이기 } = await import('../src/브라우저답글.mjs')
  const 한국어 = (await import('../src/언어/한국어.mjs')).default
  assert.equal(한국어.주제태그, '광고', '한국어팩이 주제 태그를 「광고」로 정해야 한다')
  // ⚠️ 태그를 달아도 **본문 광고표기는 그대로 둔다.** 자동화가 조용히 실패하면
  //    표기가 통째로 사라진다 — 되돌릴 수 없는 위험이다
  // 2026-09-02 — 사용자가 본문 [광고] 를 빼기로 정했다. 광고 표시는 주제 태그 하나뿐이다
  assert.equal(한국어.광고표기, '', '본문 광고표기를 뺐다 — 표시는 주제 태그가 맡는다')

  // 가짜 화면으로 판정을 본다.
  // ⚠️ **판정은 「칸에 그 말이 들어갔나」로 한다. 후보를 눌렀나로 재면 안 된다** (2026-09-03 실측).
  //    옛 코드는 후보 누르기 성공으로 쟀다. 그런데 **후보 목록은 창 밖(포털)에 그려져서**
  //    창 안에서 찾다 30초를 기다리다 죽었고 「못 달았다」를 돌려줬다 —
  //    그런데 **글에는 「광고」가 멀쩡히 붙어 있었다.** 스레드가 친 글자 그대로를 주제로 받기 때문이다.
  //    그대로 뒀으면 판마다 헛경보가 나갔다. 늘 빨간불인 신호는 아무도 안 읽는다.
  //    ⚠️ 옛 검사는 초록이었다 — **가짜 화면이 진짜와 달랐다.** 후보를 창 안에 두고 잘 눌리게 만들어 뒀다
  const 친것 = []
  const 누른것 = []
  const 가짜쪽 = ({ 눌리나 = false } = {}) => ({
    waitForTimeout: async () => {},
    keyboard: { type: async (t) => 친것.push(t) },
    // 진짜 화면에서는 이 자리가 대개 헛친다. 헛쳐도 판정이 안 흔들려야 한다
    locator: () => ({ filter: () => ({ first: () => ({
      click: async () => { if (!눌리나) throw new Error('못 누른다'); 누른것.push('광고') },
    }) }) }),
  })
  const 가짜창 = (칸) => ({
    getByRole: () => ({ first: () => ({ or: () => 칸 }) }),
    getByPlaceholder: () => ({ first: () => ({}) }),
  })
  const 칸꼴 = (값) => ({ count: async () => 1, click: async () => {}, inputValue: async () => 값, innerText: async () => '' })

  // 후보를 못 눌러도 칸에 들어갔으면 **달은 것이다**
  assert.equal(await 주제붙이기(가짜창(칸꼴('광고')), 가짜쪽(), '광고'), '「광고」 달았다',
    '후보 누르기가 죽어도 칸에 들어갔으면 성공이다 — 안 그러면 판마다 헛경보가 난다')
  assert.deepEqual(친것, ['광고'], '주제 칸에 「광고」를 쳐 넣어야 한다')
  // 눌리는 화면에서도 똑같이 성공이다
  assert.equal(await 주제붙이기(가짜창(칸꼴('광고')), 가짜쪽({ 눌리나: true }), '광고'), '「광고」 달았다')
  // 앞뒤 공백은 봐준다
  assert.equal(await 주제붙이기(가짜창(칸꼴('  광고 ')), 가짜쪽(), '광고'), '「광고」 달았다')
  // ⛔ 딴 말이 들어갔으면 실패다 — 「광고대행사」를 골라 놓고 달았다고 하면 안 된다
  assert.match(await 주제붙이기(가짜창(칸꼴('광고대행사')), 가짜쪽(), '광고'), /칸에 안 들어갔다/)
  assert.match(await 주제붙이기(가짜창(칸꼴('')), 가짜쪽(), '광고'), /칸에 안 들어갔다/)
  // 성공 문구는 run.mjs 의 판정을 통과해야 한다. 두 곳이 어긋나면 늘 알림이 뜬다
  assert.match(await 주제붙이기(가짜창(칸꼴('광고')), 가짜쪽(), '광고'), /^「.+」 달았다$/)

  // ⛔ **주제 칸 자체가 없을 때** — 스레드가 화면을 바꾸면 이렇게 된다. 던지면 답글 전체가 죽는다
  const 칸없을때 = await 주제붙이기(가짜창({ count: async () => 0 }), 가짜쪽(), '광고')
    .catch((e) => `던졌다: ${e.message}`)
  assert.match(칸없을때, /못 찾았다/, '주제 칸이 없어도 던지면 안 된다 — 던지면 글이 안 올라간다')
  assert.doesNotMatch(칸없을때, /던졌다/, '주제 칸이 없을 때 던졌다 — 답글 전체가 실패한다')
  console.log('주제 태그를 달고, 못 달면 까닭을 돌려준다 ✓')
}

