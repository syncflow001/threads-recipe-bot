{ // 실제 지시문에 서식이 실린다 — 말투 파일이 비어도 레시피 생김새가 나온다
  const 글 = 프롬프트만들기(
    { code: 'AAA', 본문: '김치찌개', 글타래: [] },
    { 정체성: '나', 말투: '반말' },   // 레시피 칸이 하나도 없는 말투
    요리,
  )
  const 지시 = typeof 글 === 'string' ? 글 : JSON.stringify(글)
  assert.match(지시, /🛒 준비물/, '지시문에 레시피 형식이 안 실렸다')
  // 2026-09-02 — 「25줄 이내」에서 「17줄·420자 이내」로 조였다. 답글이 둘로 쪼개지면
  // 조회수가 0.62배가 되는데, 옛 값으로는 우리 레시피 중앙값이 497자여서 늘 쪼개졌다
  // 숫자를 여기 또 적으면 팩과 어긋난다 — 팩이 시키는 값을 그대로 받아 본다
  assert.match(지시, new RegExp(레시피서식['레시피 길이'].replace(/[.*+?^${}()|[\]\\]/g, '\\$&')),
    '지시문에 레시피 길이가 안 실렸다')
}

{ // ⚠️ 첫 줄 훅 — **무게는 실측 배수다** (docs/조사-일본요리계정-수익화-글구성.md §1)
  const 훅들 = 요리.말투서식['도입 유형']
  assert.ok(Array.isArray(훅들) && 훅들.length >= 5, '팩에 도입 유형이 없다')
  assert.equal(훅들[0].무게, 3.7, '1등이 「의심 → 반전」(3.7배) 이 아니다')
  assert.equal(훅들[1].무게, 3.5, '2등이 「남이 물어봄」(3.5배) 이 아니다')
  assert.match(훅들[0].말, /안 믿었는데/, '1등 훅이 「나도 안 믿었는데」 결이 아니다')
  assert.match(훅들[1].말, /남이 먼저 물어/, '2등 훅이 「남이 물어봄」 결이 아니다')
  // ⚠️ 2026-09-02 — **자가 둘이라 전체 내림차순이 아니다.**
  //   앞 일곱 = 일본 110글의 조회 중앙값 대비 배수
  //   뒤 일곱 = 한국 640편의 조회·반응과 2,037편의 「퍼진 글 대 평소 글」 비율
  // 서로 다른 방식으로 잰 값이라 **한 눈금에 놓으면 안 된다.** 그래서 묶음 안에서만 내림차순을 본다.
  // 전체 내림차순으로 강제하면 두 자를 견줄 수 있다고 잘못 말하는 셈이 된다
  const 한국것 = /공감을 구하며|문장을 끊어|곧장 물으며|털어놓으며|숫자로 못 박|저장해 두라고|비법을 알지만/
  const 가름 = 훅들.findIndex((v) => 한국것.test(v.말))
  assert.ok(가름 > 0, '한국 표본 갈래가 없다')
  for (const [이름, 묶음] of [['일본', 훅들.slice(0, 가름)], ['한국', 훅들.slice(가름)]]) {
    assert.ok(묶음.length >= 5, `${이름} 묶음이 ${묶음.length}개뿐이다`)
    for (let i = 1; i < 묶음.length; i++)
      assert.ok(묶음[i].무게 <= 묶음[i - 1].무게,
        `${이름} 묶음 ${i + 1}번째 훅의 무게가 앞보다 크다 — 묶음 안에서는 내림차순이어야 한다`)
  }
  // 두 묶음이 섞여 있으면 안 된다 — 가름 뒤에 일본 것이 끼면 위 검사가 뜻을 잃는다
  assert.ok(훅들.slice(가름).every((v) => 한국것.test(v.말)),
    '한국 갈래 뒤에 일본 갈래가 섞여 있다 — 묶음을 갈라 두어야 자가 안 섞인다')
}

{ // 무게만큼 자주 뽑는다 — 그러나 **낮은 것도 계속 섞인다** (매번 같은 훅이면 봇처럼 보인다)
  const 훅들 = 요리.말투서식['도입 유형']
  const 셈 = new Map()
  for (let i = 0; i < 3000; i++) {
    const 것 = 도입고르기(훅들, 'code' + i)
    셈.set(것, (셈.get(것) ?? 0) + 1)
  }
  assert.equal(셈.size, 훅들.length, '안 뽑히는 훅이 있다 — 다양성이 사라지면 봇처럼 보인다')
  const 첫째 = 셈.get(훅들[0].말) / 3000
  const 꼴찌 = 셈.get(훅들[훅들.length - 1].말) / 3000
  assert.ok(첫째 > 꼴찌 * 1.8, `1등(${(첫째 * 100).toFixed(0)}%)이 꼴찌(${(꼴찌 * 100).toFixed(0)}%)보다 충분히 자주 안 뽑힌다`)
  assert.ok(꼴찌 > 0.03, '꼴찌가 너무 안 뽑힌다 — 다양성이 죽는다')
}

{ // 같은 글은 늘 같은 훅이다 — 판을 다시 돌려도 결과가 흔들리면 안 된다
  const 훅들 = 요리.말투서식['도입 유형']
  assert.equal(도입고르기(훅들, 'AAA'), 도입고르기(훅들, 'AAA'))
  assert.notEqual(도입고르기(훅들, 'AAA'), '')
  // 옛 꼴(글자 배열)도 그대로 돈다 — 다른 분야 팩이 아직 그렇다
  assert.equal(도입고르기(['하나'], 'x'), '하나')
  assert.ok(['가', '나'].includes(도입고르기(['가', '나'], 'x')))
  assert.equal(도입고르기([], 'x'), '')
  assert.equal(도입고르기(null, 'x'), '')
}

{ // ⚠️ **도입 유형은 계정이 못 덮는다** — 취향이 아니라 실측이다.
  // 계정 파일의 것은 언어별로 똑같이 베껴진 보일러플레이트였다 (열 계정이 세 벌을 나눠 가짐)
  assert.ok(분야가정하는칸(요리).has('도입 유형'))
  const 깔린것 = 서식깔기({ '도입 유형': ['내 맘대로 연다'] }, 요리)
  assert.deepEqual(깔린것['도입 유형'], 요리.말투서식['도입 유형'],
    '계정 파일이 실측 훅 순위를 덮었다')
  // 팩에 그 칸이 없는 분야에서는 계정 것을 그대로 쓴다
  assert.deepEqual(서식깔기({ '도입 유형': ['내 맘대로'] }, { 말투서식: { 'x': 1 } })['도입 유형'],
    ['내 맘대로'])
}

