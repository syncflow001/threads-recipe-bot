// 분야 팩 서식이 계정 말투의 바탕으로 깔리는가 — node 검사/test.서식깔기.mjs
// 2026-08-31. 레시피 생김새는 **계정마다 달라야 하는 것이 아니다.** 전에는 계정 파일에만 있어서
// sample_salim 의 말투 파일에 그 칸이 없자 밋밋한 「[준비물] 1. 2. 3.」 이 그대로 나갔다
import assert from 'node:assert/strict'
import { 서식깔기, 프롬프트만들기, 도입고르기, 분야가정하는칸 } from '../src/compose.mjs'
