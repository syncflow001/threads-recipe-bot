    // 아홉 줄만 주면 사람이 「그래서 왜 안 올라갔나」를 스스로 읽어 내야 한다. 답을 먼저 준다
    맞나(typeof 진단결과.답?.글 === 'string' && 진단결과.답.글.length > 0, '한 줄 답을 함께 준다')
    맞나(typeof 진단결과.답?.조치 === 'string' && 진단결과.답.조치.length > 0, '무엇을 하면 되는지도 함께 준다')
    // 줄마다 무슨 뜻인지 붙는다 — 이름만으로는 좋은 것인지 나쁜 것인지 알 수 없었다
    맞나(진단결과.것들.filter((h) => h.풀이).length >= 6, '대부분의 줄에 무슨 뜻인지가 붙는다')

