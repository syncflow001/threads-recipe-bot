  // ── 적대적: 프롬프트 인젝션 ──────────────────────────────────
  // 우리는 남이 쓴 글을 통째로 LLM 에 던진다. 그 글에 지시문이 심겨 있으면
  // 어떻게 되는지 여기서 잰다. 실제 구조는 프롬프트만들기() 가 { system: 우리 지시, user: 원글 재료 }
