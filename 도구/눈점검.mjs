// 계정마다 「남의 글의 답글을 읽을 수 있는가」를 재서 한 표로 보여 준다 — 아무것도 안 바꾼다
//
//   node 도구/눈점검.mjs                 (모든 계정)
//   node 도구/눈점검.mjs sample_salim   (한 계정만)
//
// 왜 있나. 2026-09-05 에 아홉 계정이 하루 5편에서 1~3편으로 떨어졌는데 헬스체크는 초록불이었다.
// 「쿠키 주인이 누구냐」만 물었기 때문이다 — 반쯤 죽은 쿠키도 그 질문에는 제대로 답한다.
// 이 도구는 **답글을 실제로 읽어 본다.** 까닭은 `src/눈점검.mjs` 머리에 적었다.
//
// ⚠️ 쿠키 값은 한 글자도 안 찍는다.
import { 한판, 막힌계정들, 막힘풀기 } from '../src/눈점검.mjs'
import { 계정목록 } from '../src/계정.mjs'

const 고른계정 = process.argv.slice(2).filter((a) => !a.startsWith('--'))
const 자세히 = process.argv.includes('--자세히')

// ⚠️ **한 계정만 재 달라고 해도 다른 계정을 함께 읽는다.** 눈이 하나뿐이면
// 「답글을 못 읽는 눈」과 「답글이 원래 없는 글」을 가를 수가 없다
// ([[못-읽는-것과-없는-것을-가르려면-남의-눈으로-같은-것을-봐라]]). 화면에는 물어본 계정만 보여 준다
const 다 = await 계정목록()
const 잴것 = 고른계정.length
  ? [...고른계정, ...다.filter((a) => !고른계정.includes(a)).slice(0, 2)]
  : 다

console.log('스레드에 물어보는 중입니다 — 계정 수만큼 걸립니다 (한 계정에 5초쯤)\n')

const { 기준글, 결과: 전부 } = await 한판({
  계정들: 잴것,
  알림: 자세히 ? (m) => console.log(`  ${m}`) : () => {},
})
const 결과 = 고른계정.length ? 전부.filter((r) => 고른계정.includes(r.계정)) : 전부

if (!기준글.length) {
  console.log('⚠️  잣대로 쓸 글을 한 편도 못 구했습니다.')
  console.log('   답글이 달린 우리 글을 아무 계정으로도 못 읽었다는 뜻입니다 —')
  console.log('   모든 계정이 막혔거나, 발행 토큰이 죽어 글 주소를 못 가져온 것입니다.')
  console.log('   낱낱을 보려면  node 도구/눈점검.mjs --자세히')
  process.exit(1)
}
console.log(`기준글 ${기준글.length}편으로 쟀습니다 (답글이 달려 있는 것이 확인된 글입니다)\n`)

// 「다시 로그인해도 안 고쳐진다」고 표시해 둔 계정. 헬스체크는 이것을 안 부른다
const 막힌것 = await 막힌계정들()
const 표시 = { 멀쩡: '✅', 반쯤: '⚠️ ', 끊김: '❌', 없음: '❌', 못잼: '❔' }
for (const r of 결과) {
  const 꼬리 = 막힌것[r.계정] ? `  (${막힌것[r.계정]} 부터 「막힘」으로 표시 — 알림 안 옴)` : ''
  console.log(`${표시[r.갈래] ?? '❔'} ${r.계정.padEnd(20)} 조회수 ${r.조회수본것}/${기준글.length} · `
    + `답글 ${r.글타래본것}/${기준글.length}   ${r.말}${꼬리}`)
  // 다시 읽히면 표시를 지운다. 남겨 두면 진짜 고장이 났을 때 그것까지 가린다
  if (r.갈래 === '멀쩡' && 막힌것[r.계정] && await 막힘풀기(r.계정)) {
    console.log(`   → ${r.계정} 의 「막힘」 표시를 지웠습니다. 이제 제 눈으로 읽습니다.`)
    delete 막힌것[r.계정]   // 아래 셈에서 빼야 한다. 안 지우면 다 나았는데 「2곳 막힘」이라 말한다
  }
}

// 고쳐야 할 계정에는 **붙여넣을 줄을 그대로 찍어 준다.** 사용자가 명령을 지어내지 않게 한다
// 표시해 둔 막힘은 「고칠 것」에 안 넣는다 — 다시 로그인해도 안 고쳐지는 것이 확인됐다
const 고칠것 = 결과.filter((r) => r.갈래 !== '멀쩡' && r.갈래 !== '못잼' && !막힌것[r.계정])
if (!고칠것.length) {
  const 막힌수 = 결과.filter((r) => 막힌것[r.계정]).length
  console.log(막힌수
    ? `\n손댈 것이 없습니다 — 못 읽는 ${막힌수}곳은 「막힘」으로 표시돼 있습니다 (다시 로그인해도 안 고쳐집니다).`
    : '\n✅ 모든 계정이 답글을 읽습니다 — 손댈 것이 없습니다.')
} else {
  console.log(`\n손봐야 할 계정 ${고칠것.length}곳입니다. 아래를 **한 줄씩** 터미널에 붙여넣으세요.`)
  console.log('크롬 창이 열리면 그 계정으로 로그인만 하시면 됩니다. 나머지는 알아서 합니다.\n')
  for (const r of 고칠것) console.log(`node 도구/쿠키받기.mjs ${r.계정}`)
  console.log('\n다 끝나면 이것으로 다시 재 보세요.\n\nnode 도구/눈점검.mjs')
}
